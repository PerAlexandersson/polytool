#[test]
fn inverse_factorial_multiplier_is_proved() {
    // Q_n = sum_k binom(n, k) x^k / k! (Laguerre L_n(-x)):
    // m Q_m = (2m - 1 + x) Q_(m-1) - (m - 1) Q_(m-2), Q_0 = 1, Q_1 = 1 + x.
    let rule = Recurrence {
        terms: vec![
            RecurrenceTerm::new(
                1,
                0,
                BivarPoly {
                    coeffs: vec![vec![q(-1), q(1)], vec![q(2)]],
                },
            ),
            RecurrenceTerm::new(
                2,
                0,
                BivarPoly {
                    coeffs: vec![vec![q(1)], vec![q(-1)]],
                },
            ),
        ],
        denominator: Some(BivarPoly {
            coeffs: vec![vec![q(0)], vec![q(1)]],
        }),
        inhomogeneous: None,
    };
    let report = find_hadamard_factor_lifts(
        &rule,
        &[vec![q(1)], vec![q(1), q(1)]],
        0,
        &HadamardFactorLiftOptions::default(),
    )
    .unwrap();
    report.verify().unwrap();
    let lift = report.proved_lifts().next().expect("a proved lift");
    assert_eq!(lift.factor_text, "1/k!");
    assert!(lift
        .multiplier_sequence
        .as_deref()
        .unwrap()
        .contains("Example 41"));
}

#[test]
fn rising_factorial_is_certified_without_transfer_theorem() {
    // Q_n = sum_k binom(n, k) (1/2)_k x^k: the identity is certified, but
    // (1/2)_k is not a multiplier sequence, so the lift stays open.
    let rows: Vec<Vec<BigRational>> = (0..14usize)
        .map(|n| {
            let mut binomial = q(1);
            let mut rising = q(1);
            (0..=n)
                .map(|k| {
                    if k > 0 {
                        binomial = binomial.clone() * q((n - k + 1) as i64) / q(k as i64);
                        rising = rising.clone()
                            * (BigRational::new(1.into(), 2.into()) + q(k as i64 - 1));
                    }
                    binomial.clone() * rising.clone()
                })
                .collect()
        })
        .collect();
    let (rule, seeds) = fitted_family(&rows);
    let report = find_hadamard_factor_lifts(
        &rule,
        &seeds,
        0,
        &HadamardFactorLiftOptions {
            max_binomial_offset: 0,
            ..Default::default()
        },
    )
    .unwrap();
    report.verify().unwrap();
    let lift = report
        .lifts
        .iter()
        .find(|lift| lift.factor_text == "(1/2)_k")
        .expect("the (1/2)_k lift");
    certificate(lift).verify().unwrap();
    assert!(lift.multiplier_sequence.is_none());
    assert_eq!(lift.lift_summary.verdict, LiftVerdict::Open);
    assert_eq!(
        lift.lift_summary.hypotheses[0].status,
        LiftHypothesisStatus::Unresolved
    );
    assert_eq!(report.proved_lifts().count(), 0);
}

