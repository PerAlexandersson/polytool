//! Hadamard-factor lifts: catalog families proved end to end, a factor
//! without a transfer theorem, near misses, budgets and certificate replay.

use polytool::oeis;
use polytool::recurrence::*;

fn q(value: i64) -> BigRational {
    BigRational::from_integer(value.into())
}

fn catalog_report(id: &str, options: &HadamardFactorLiftOptions) -> HadamardFactorLiftReport {
    let family = oeis::by_id(id).expect("catalog family");
    let (rule, rows) = family.recurrence_parts().expect("catalog recurrence");
    find_hadamard_factor_lifts(&rule, &rows, family.recurrence_first_index, options)
        .expect("search succeeds")
}

fn certificate(lift: &HadamardFactorLift) -> &HadamardFactorCertificate {
    match &lift.identity {
        HadamardFactorIdentityStatus::Certified { certificate } => certificate,
        other => panic!("not certified: {other:?}"),
    }
}

/// Rows generated by fitting a recurrence to explicit rows, with the rule
/// shifted to first index 0.
fn fitted_family(rows: &[Vec<BigRational>]) -> (Recurrence, Vec<Vec<BigRational>>) {
    let fit = find_recurrence_adaptive_rational(rows, &AdaptiveSearchOptions::default())
        .expect("a recurrence");
    let rule = fit.recurrence.shift_index(1);
    let seeds = rows[..rule.max_offset()].to_vec();
    (rule, seeds)
}

#[test]
fn narayana_is_proved_end_to_end() {
    // Catalog rows are sum_k N(n+1, k+1) x^k with n >= 0.
    let report = catalog_report(
        "A001263",
        &HadamardFactorLiftOptions {
            max_binomial_offset: 1,
            ..Default::default()
        },
    );
    report.verify().unwrap();
    let lift = report.proved_lifts().next().expect("a proved lift");
    assert_eq!(lift.factor_text, "binom(n+1, k+1)");
    // The quotient (1 + x)^(n+1) / (n+1) needs its top coefficient continued
    // and is normalised to the periodic product (1 + x)^(n+1).
    assert_eq!(
        lift.hidden_coefficients,
        HadamardHiddenCoefficients::Continuation
    );
    assert_eq!(
        lift.gauge,
        VeroneseSectionGauge::Ratio {
            numerator: vec!["0".into(), "1".into()],
            denominator: vec!["1".into(), "1".into()],
            initial_value: "1".into(),
        }
    );
    assert_eq!(
        lift.parent_proof.route,
        Some(VeroneseParentProofRoute::PeriodicProduct)
    );
    let certificate = certificate(lift);
    assert!(certificate.row_annihilator.is_some());
    certificate.verify().unwrap();
    let summary = &lift.lift_summary;
    assert_eq!(summary.verdict, LiftVerdict::Proved);
    assert!(summary.is_consistent());
    assert_eq!(
        summary.operation,
        LiftOperation::HadamardFactor {
            factor: "binom(n+1, k+1)".into()
        }
    );
    assert!(summary.root_transfer.theorem.contains("arXiv:1410.6601"));

    // JSON round trip, exact strings and the schema tag.
    let json = serde_json::to_value(&report).unwrap();
    assert_eq!(json["schema"], HADAMARD_FACTOR_LIFTS_SCHEMA);
    assert_eq!(
        json["lifts"][0]["lift_summary"]["operation"]["kind"],
        "hadamard_factor"
    );
    let back: HadamardFactorLiftReport = serde_json::from_value(json).unwrap();
    assert_eq!(back, report);
    back.verify().unwrap();

    // Near misses recorded for the same input.
    let rejected = |text: &str| {
        report
            .rejected
            .iter()
            .find(|r| r.factor_text == text)
            .unwrap_or_else(|| panic!("{text} rejected"))
            .kind
    };
    assert_eq!(
        rejected("binom(n, k-1)"),
        HadamardFactorRejectionKind::VanishesOnSupport
    );
    assert_eq!(
        rejected("1/k!"),
        HadamardFactorRejectionKind::NoSmallerParent
    );
    assert_eq!(
        rejected("binom(n-1, k)"),
        HadamardFactorRejectionKind::InvalidForDomain
    );
}

#[test]
fn tampered_certificates_are_rejected() {
    let report = catalog_report(
        "A001263",
        &HadamardFactorLiftOptions {
            max_binomial_offset: 1,
            ..Default::default()
        },
    );
    let lift = report.proved_lifts().next().unwrap().clone();
    let original = certificate(&lift).clone();

    let mut wrong_multiplier = original.clone();
    wrong_multiplier.multiplier.push("1".into());
    assert!(wrong_multiplier.verify().is_err());

    let mut wrong_factor = original.clone();
    wrong_factor.factor = HadamardFactor::single(HadamardFactorTerm::Binomial {
        index_offset: 1,
        coefficient_offset: 0,
    });
    assert!(wrong_factor.verify().is_err());

    let mut dropped_quotient = original.clone();
    dropped_quotient.quotients.pop();
    assert!(dropped_quotient.verify().is_err());

    let mut no_annihilator = original.clone();
    no_annihilator.row_annihilator = None;
    assert!(no_annihilator.verify().is_err());

    // A lift whose certificate belongs to another factor, or whose summary
    // was edited, fails its replay.
    let mut edited = lift.clone();
    edited.identity = HadamardFactorIdentityStatus::Certified {
        certificate: Box::new(HadamardFactorCertificate {
            gauge: VeroneseSectionGauge::None,
            ..original.clone()
        }),
    };
    assert!(edited.verify().is_err());
    let mut edited = lift;
    edited.lift_summary.verdict = LiftVerdict::Open;
    assert!(edited.verify().is_err());
}

