fn format_tableau(rows: &[Vec<u32>]) -> String {
    if rows.is_empty() {
        return "[]".into();
    }
    rows.iter()
        .map(|row| {
            format!(
                "[{}]",
                row.iter().map(u32::to_string).collect::<Vec<_>>().join(" ")
            )
        })
        .collect::<Vec<_>>()
        .join("/")
}

