fn background_values(
    base: &PathData,
    mask: u64,
    low: usize,
    mid: usize,
    top: usize,
) -> Result<(usize, usize, usize), String> {
    let mut upward = base.strict_edges.clone();
    upward.extend(
        base.normal_edges
            .iter()
            .enumerate()
            .filter(|(index, edge)| **edge != (low, mid) && mask & (1u64 << index) != 0)
            .map(|(_, &edge)| edge),
    );
    let hrv = highest_reachable_vertices(base.n, &upward)
        .ok_or_else(|| "bounce background upward graph is invalid".to_string())?;
    Ok((hrv[low], hrv[mid], hrv[top]))
}

fn set_background_bit(
    base: &PathData,
    mask: u64,
    edge: (usize, usize),
    value: bool,
) -> Result<u64, String> {
    let index = base
        .normal_edges
        .binary_search(&edge)
        .map_err(|_| format!("background does not contain distinguished edge {edge:?}"))?;
    Ok(if value {
        mask | (1u64 << index)
    } else {
        mask & !(1u64 << index)
    })
}

fn swap_background_orientation(
    base: &PathData,
    mask: u64,
    low: usize,
    mid: usize,
) -> Result<u64, String> {
    let distinguished = (low, mid);
    let selected = selected_edges(base, mask)
        .into_iter()
        .map(|edge| {
            if edge == distinguished {
                edge
            } else {
                swap_edge(edge, low, mid)
            }
        })
        .collect::<Vec<_>>();
    mask_for_edges(base, &selected)
}

fn bounce_match(
    base: &PathData,
    low: usize,
    mid: usize,
    top: usize,
    factor: bool,
    orientation: u64,
) -> Result<(bool, u64), String> {
    let beta = mask_contains_edge(base, orientation, (low, mid))?;
    let (a, c, h) = background_values(base, orientation, low, mid, top)?;
    if h <= c {
        if beta || h <= a {
            Ok((factor, orientation))
        } else {
            Ok((
                factor,
                set_background_bit(
                    base,
                    swap_background_orientation(base, orientation, low, mid)?,
                    (low, mid),
                    false,
                )?,
            ))
        }
    } else if factor {
        Ok((
            beta,
            set_background_bit(base, orientation, (low, mid), true)?,
        ))
    } else {
        Ok((
            beta,
            set_background_bit(
                base,
                swap_background_orientation(base, orientation, low, mid)?,
                (low, mid),
                false,
            )?,
        ))
    }
}

fn bounce_unmatch(
    base: &PathData,
    low: usize,
    mid: usize,
    top: usize,
    factor: bool,
    orientation: u64,
) -> Result<(bool, u64), String> {
    let beta = mask_contains_edge(base, orientation, (low, mid))?;
    let (a, c, h) = background_values(base, orientation, low, mid, top)?;
    if beta {
        if h <= c {
            Ok((factor, orientation))
        } else {
            Ok((
                true,
                set_background_bit(base, orientation, (low, mid), factor)?,
            ))
        }
    } else if h <= a {
        if h <= c {
            Ok((factor, orientation))
        } else {
            Ok((
                factor,
                swap_background_orientation(base, orientation, low, mid)?,
            ))
        }
    } else {
        Ok((
            false,
            set_background_bit(
                base,
                swap_background_orientation(base, orientation, low, mid)?,
                (low, mid),
                factor,
            )?,
        ))
    }
}

fn second_match(
    base: &PathData,
    low: usize,
    mid: usize,
    top: usize,
    source_bit: bool,
    orientation: u64,
) -> Result<(bool, u64), String> {
    let beta = mask_contains_edge(base, orientation, (low, mid))?;
    let (a, c, h) = background_values(base, orientation, low, mid, top)?;
    if source_bit == beta {
        if source_bit {
            Ok((true, orientation))
        } else {
            Ok((
                false,
                set_background_bit(
                    base,
                    swap_background_orientation(base, orientation, low, mid)?,
                    (low, mid),
                    false,
                )?,
            ))
        }
    } else if a <= h && c <= h {
        if source_bit {
            Ok((
                false,
                set_background_bit(base, orientation, (low, mid), true)?,
            ))
        } else {
            Ok((
                true,
                set_background_bit(
                    base,
                    swap_background_orientation(base, orientation, low, mid)?,
                    (low, mid),
                    false,
                )?,
            ))
        }
    } else if source_bit {
        if c <= a {
            Ok((true, orientation))
        } else {
            Ok((
                false,
                set_background_bit(
                    base,
                    swap_background_orientation(base, orientation, low, mid)?,
                    (low, mid),
                    true,
                )?,
            ))
        }
    } else if a <= c {
        Ok((false, orientation))
    } else {
        Ok((
            true,
            set_background_bit(
                base,
                swap_background_orientation(base, orientation, low, mid)?,
                (low, mid),
                false,
            )?,
        ))
    }
}

