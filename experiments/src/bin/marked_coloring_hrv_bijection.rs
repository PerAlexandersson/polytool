fn detect_fibre_transport(
    source_path: &PathData,
    source_mask: u64,
    target_path: &PathData,
    target_mask: u64,
    low: usize,
    mid: usize,
) -> Result<FibreTransport, String> {
    let source_hrv = hrv_for_mask(source_path, source_mask)?;
    let target_hrv = hrv_for_mask(target_path, target_mask)?;
    if source_hrv == target_hrv {
        return Ok(FibreTransport::Identity);
    }
    let transport = FibreTransport::Swap(low, mid);
    if (0..source_path.n)
        .all(|vertex| target_hrv[transport.apply(vertex)] == transport.apply(source_hrv[vertex]))
    {
        Ok(transport)
    } else {
        Err("matched bounce orientations have no proved identity/swap HRV conjugacy".into())
    }
}

fn transport_columns(
    source_path: &PathData,
    source_mask: u64,
    source_word: &[u8],
    target_path: &PathData,
    target_mask: u64,
    transport: FibreTransport,
) -> Result<Vec<u8>, String> {
    let source = TargetState {
        orientation_mask: source_mask,
        column_word: source_word.to_vec(),
    };
    validate_target(source_path, &source)?;
    if source_path.n != target_path.n {
        return Err("cannot transport columns between different ranks".into());
    }
    let source_hrv = hrv_for_mask(source_path, source_mask)?;
    let target_hrv = hrv_for_mask(target_path, target_mask)?;
    if !(0..source_path.n)
        .all(|vertex| target_hrv[transport.apply(vertex)] == transport.apply(source_hrv[vertex]))
    {
        return Err("column transport does not conjugate the two HRV maps".into());
    }
    let mut target_word = vec![0u8; source_path.n];
    let mut assigned = vec![false; source_path.n];
    for fibre in fibres(&source_hrv) {
        let mut colors = fibre
            .iter()
            .map(|&vertex| source_word[vertex])
            .collect::<Vec<_>>();
        colors.sort_unstable();
        let mut target_vertices = fibre
            .iter()
            .map(|&vertex| transport.apply(vertex))
            .collect::<Vec<_>>();
        target_vertices.sort_unstable();
        for (vertex, color) in target_vertices.into_iter().zip(colors) {
            if std::mem::replace(&mut assigned[vertex], true) {
                return Err("column transport assigned a vertex twice".into());
            }
            target_word[vertex] = color;
        }
    }
    if assigned.iter().any(|assigned| !assigned) {
        return Err("column transport omitted a vertex".into());
    }
    let target = TargetState {
        orientation_mask: target_mask,
        column_word: target_word,
    };
    validate_target(target_path, &target)?;
    if color_content(source_word) != color_content(&target.column_word) {
        return Err("column transport changed color content".into());
    }
    Ok(target.column_word)
}

fn standardize_word(word: &[u8]) -> (Vec<u8>, Vec<u8>) {
    let alphabet = word
        .iter()
        .copied()
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let ranks = alphabet
        .iter()
        .enumerate()
        .map(|(rank, &color)| (color, rank as u8))
        .collect::<BTreeMap<_, _>>();
    (word.iter().map(|color| ranks[color]).collect(), alphabet)
}

fn lift_word(word: &[u8], alphabet: &[u8]) -> Result<Vec<u8>, String> {
    word.iter()
        .map(|&color| {
            alphabet
                .get(color as usize)
                .copied()
                .ok_or_else(|| "standardized color is outside its recorded alphabet".to_string())
        })
        .collect()
}

fn shifted_selected_edges(path: &PathData, mask: u64, shift: usize) -> Vec<(usize, usize)> {
    path.normal_edges
        .iter()
        .enumerate()
        .filter(|(index, _)| mask & (1u64 << index) != 0)
        .map(|(_, &(u, v))| (u + shift, v + shift))
        .collect()
}

fn mask_for_edges(path: &PathData, selected: &[(usize, usize)]) -> Result<u64, String> {
    let selected = selected.iter().copied().collect::<BTreeSet<_>>();
    if selected
        .iter()
        .any(|edge| path.normal_edges.binary_search(edge).is_err())
    {
        return Err(format!(
            "selected edge is not normal in path {}",
            path.word()
        ));
    }
    Ok(path
        .normal_edges
        .iter()
        .enumerate()
        .fold(0u64, |mask, (index, edge)| {
            if selected.contains(edge) {
                mask | (1u64 << index)
            } else {
                mask
            }
        }))
}

fn restrict_mask(
    parent: &PathData,
    parent_mask: u64,
    child: &PathData,
    child_shift: usize,
) -> Result<u64, String> {
    let selected = shifted_selected_edges(parent, parent_mask, 0)
        .into_iter()
        .filter_map(|(u, v)| {
            (u >= child_shift && v >= child_shift).then_some((u - child_shift, v - child_shift))
        })
        .filter(|edge| child.normal_edges.binary_search(edge).is_ok())
        .collect::<Vec<_>>();
    mask_for_edges(child, &selected)
}

fn mask_contains_edge(path: &PathData, mask: u64, edge: (usize, usize)) -> Result<bool, String> {
    let index = path.normal_edges.binary_search(&edge).map_err(|_| {
        format!(
            "distinguished edge {edge:?} is not normal in {}",
            path.word()
        )
    })?;
    Ok(mask & (1u64 << index) != 0)
}

fn format_edge((u, v): (usize, usize)) -> String {
    format!("{}{}", u + 1, v + 1)
}

fn enumerate_sources(path: &PathData) -> Vec<SourceState> {
    let mut result = Vec::new();
    for coloring in packed_words(path.n) {
        if !increases_on_edges(&coloring, &path.strict_edges) {
            continue;
        }
        let ascent_mask = edge_ascent_mask(&coloring, &path.normal_edges);
        let mut marked_mask = ascent_mask;
        loop {
            result.push(SourceState {
                coloring: coloring.clone(),
                marked_mask,
            });
            if marked_mask == 0 {
                break;
            }
            marked_mask = (marked_mask - 1) & ascent_mask;
        }
    }
    result
}

fn enumerate_targets(path: &PathData) -> Result<Vec<TargetState>, String> {
    if path.normal_edges.len() >= u64::BITS as usize {
        return Err("too many normal edges for the prototype mask".into());
    }
    let words = packed_words(path.n);
    let mut result = Vec::new();
    for orientation_mask in 0..(1u64 << path.normal_edges.len()) {
        let hrv = hrv_for_mask(path, orientation_mask)?;
        let fibres = fibres(&hrv);
        for column_word in &words {
            if fibres.iter().all(|fibre| {
                fibre
                    .windows(2)
                    .all(|vertices| column_word[vertices[0]] < column_word[vertices[1]])
            }) {
                result.push(TargetState {
                    orientation_mask,
                    column_word: column_word.clone(),
                });
            }
        }
    }
    Ok(result)
}

fn validate_source(path: &PathData, source: &SourceState) -> Result<(), String> {
    validate_packed_word(&source.coloring, path.n)?;
    if !increases_on_edges(&source.coloring, &path.strict_edges) {
        return Err("source coloring violates a strict edge".into());
    }
    let ascents = edge_ascent_mask(&source.coloring, &path.normal_edges);
    if source.marked_mask & !ascents != 0 {
        return Err("source marks a normal edge that is not a coloring ascent".into());
    }
    Ok(())
}

fn validate_target(path: &PathData, target: &TargetState) -> Result<(), String> {
    validate_packed_word(&target.column_word, path.n)?;
    if target.orientation_mask >> path.normal_edges.len() != 0 {
        return Err("target orientation mask has an out-of-range edge".into());
    }
    let hrv = hrv_for_mask(path, target.orientation_mask)?;
    for fibre in fibres(&hrv) {
        if !fibre
            .windows(2)
            .all(|vertices| target.column_word[vertices[0]] < target.column_word[vertices[1]])
        {
            return Err("target column is not strictly increasing".into());
        }
    }
    Ok(())
}

fn source_signature(source: &SourceState) -> Signature {
    Signature {
        content: color_content(&source.coloring),
        q_degree: source.marked_mask.count_ones() as usize,
    }
}

fn target_signature(target: &TargetState) -> Signature {
    Signature {
        content: color_content(&target.column_word),
        q_degree: target.orientation_mask.count_ones() as usize,
    }
}

fn hrv_for_mask(path: &PathData, mask: u64) -> Result<Vec<usize>, String> {
    let mut upward_edges = path.strict_edges.clone();
    upward_edges.extend(
        path.normal_edges
            .iter()
            .enumerate()
            .filter(|(index, _)| mask & (1u64 << index) != 0)
            .map(|(_, &edge)| edge),
    );
    highest_reachable_vertices(path.n, &upward_edges)
        .ok_or_else(|| "ordinary upward graph unexpectedly invalid or cyclic".to_string())
}

fn fibres(hrv: &[usize]) -> Vec<Vec<usize>> {
    let mut by_sink: BTreeMap<usize, Vec<usize>> = BTreeMap::new();
    for (vertex, &sink) in hrv.iter().enumerate() {
        by_sink.entry(sink).or_default().push(vertex);
    }
    by_sink.into_values().collect()
}

fn validate_arbitrary_source(path: &PathData, source: &SourceState) -> Result<(), String> {
    if source.coloring.len() != path.n {
        return Err(format!(
            "word length {} differs from rank {}",
            source.coloring.len(),
            path.n
        ));
    }
    if !increases_on_edges(&source.coloring, &path.strict_edges) {
        return Err("source coloring violates a strict edge".into());
    }
    let ascents = edge_ascent_mask(&source.coloring, &path.normal_edges);
    if source.marked_mask & !ascents != 0 {
        return Err("source marks a normal edge that is not a coloring ascent".into());
    }
    Ok(())
}

fn validate_arbitrary_target(path: &PathData, target: &TargetState) -> Result<(), String> {
    if target.column_word.len() != path.n {
        return Err(format!(
            "word length {} differs from rank {}",
            target.column_word.len(),
            path.n
        ));
    }
    if target.orientation_mask >> path.normal_edges.len() != 0 {
        return Err("target orientation mask has an out-of-range edge".into());
    }
    let hrv = hrv_for_mask(path, target.orientation_mask)?;
    if fibres(&hrv).iter().any(|fibre| {
        !fibre
            .windows(2)
            .all(|vertices| target.column_word[vertices[0]] < target.column_word[vertices[1]])
    }) {
        return Err("target column is not strictly increasing".into());
    }
    Ok(())
}

fn map_arbitrary_source(
    matcher: &mut RecursiveMatcher,
    path: &PathData,
    source: &SourceState,
) -> Result<TargetState, String> {
    validate_arbitrary_source(path, source)?;
    let (coloring, alphabet) = standardize_word(&source.coloring);
    let packed = SourceState {
        coloring,
        marked_mask: source.marked_mask,
    };
    let certificate = matcher.map(path, &packed)?;
    let target = TargetState {
        orientation_mask: certificate.target.orientation_mask,
        column_word: lift_word(&certificate.target.column_word, &alphabet)?,
    };
    validate_arbitrary_target(path, &target)?;
    Ok(target)
}

fn inverse_arbitrary_target(
    matcher: &mut RecursiveMatcher,
    path: &PathData,
    target: &TargetState,
) -> Result<SourceState, String> {
    validate_arbitrary_target(path, target)?;
    let (column_word, alphabet) = standardize_word(&target.column_word);
    let packed = TargetState {
        orientation_mask: target.orientation_mask,
        column_word,
    };
    let packed_source = matcher.inverse(path, &packed)?;
    let source = SourceState {
        coloring: lift_word(&packed_source.coloring, &alphabet)?,
        marked_mask: packed_source.marked_mask,
    };
    validate_arbitrary_source(path, &source)?;
    Ok(source)
}

fn transport_submask_by_rank(
    from_mask: u64,
    to_mask: u64,
    subset: u64,
    edge_count: usize,
) -> Result<u64, String> {
    let valid_bits = if edge_count == u64::BITS as usize {
        u64::MAX
    } else {
        (1u64 << edge_count) - 1
    };
    if from_mask & !valid_bits != 0 || to_mask & !valid_bits != 0 || subset & !valid_bits != 0 {
        return Err("rank-transport mask has an out-of-range edge".into());
    }
    if subset & !from_mask != 0 {
        return Err("rank-transport subset is not contained in its ambient mask".into());
    }
    let from = (0..edge_count)
        .filter(|&index| from_mask & (1u64 << index) != 0)
        .collect::<Vec<_>>();
    let to = (0..edge_count)
        .filter(|&index| to_mask & (1u64 << index) != 0)
        .collect::<Vec<_>>();
    if from.len() != to.len() {
        return Err("rank transport requires equally large ambient masks".into());
    }
    Ok(from.into_iter().zip(to).fold(0u64, |mask, (old, new)| {
        if subset & (1u64 << old) != 0 {
            mask | (1u64 << new)
        } else {
            mask
        }
    }))
}

fn target_column_crystal_word(path: &PathData, target: &TargetState) -> Result<Vec<u32>, String> {
    validate_arbitrary_target(path, target)?;
    let hrv = hrv_for_mask(path, target.orientation_mask)?;
    Ok(fibres(&hrv)
        .into_iter()
        .flat_map(|fibre| {
            fibre
                .into_iter()
                .rev()
                .map(|vertex| u32::from(target.column_word[vertex]) + 1)
                .collect::<Vec<_>>()
        })
        .collect())
}

fn target_from_column_crystal_word(
    path: &PathData,
    orientation_mask: u64,
    word: &[u32],
) -> Result<TargetState, String> {
    if word.len() != path.n {
        return Err("column-crystal word has the wrong length".into());
    }
    let hrv = hrv_for_mask(path, orientation_mask)?;
    let ordered_vertices = fibres(&hrv)
        .into_iter()
        .flat_map(|fibre| fibre.into_iter().rev())
        .collect::<Vec<_>>();
    let mut column_word = vec![0u8; path.n];
    for (&vertex, &entry) in ordered_vertices.iter().zip(word) {
        let color = entry
            .checked_sub(1)
            .and_then(|value| u8::try_from(value).ok())
            .ok_or_else(|| "tableau entry is outside the prototype color range".to_string())?;
        column_word[vertex] = color;
    }
    let target = TargetState {
        orientation_mask,
        column_word,
    };
    validate_arbitrary_target(path, &target)?;
    Ok(target)
}

fn inverse_rsk(p: &Tableau, q: &Tableau) -> Result<Vec<u32>, String> {
    if !p.is_semistandard() || !q.is_standard() || p.size() != q.size() {
        return Err("inverse RSK requires an SSYT and a same-size standard tableau".into());
    }
    let mut p_rows = p.rows().to_vec();
    let mut q_rows = q.rows().to_vec();
    if p_rows.iter().map(Vec::len).collect::<Vec<_>>()
        != q_rows.iter().map(Vec::len).collect::<Vec<_>>()
    {
        return Err("inverse RSK tableaux have different shapes".into());
    }
    let mut word = vec![0u32; p.size() as usize];
    for label in (1..=p.size()).rev() {
        let (row, column) = q_rows
            .iter()
            .enumerate()
            .find_map(|(row, entries)| {
                entries
                    .iter()
                    .position(|&entry| entry == label)
                    .map(|column| (row, column))
            })
            .ok_or_else(|| format!("recording tableau omits label {label}"))?;
        if column + 1 != q_rows[row].len()
            || q_rows
                .get(row + 1)
                .is_some_and(|next_row| column < next_row.len())
        {
            return Err(format!("recording label {label} is not in an outer corner"));
        }
        q_rows[row].pop();
        let mut value = p_rows[row]
            .pop()
            .ok_or_else(|| "insertion tableau corner is missing".to_string())?;
        for earlier_row in (0..row).rev() {
            let position = p_rows[earlier_row]
                .iter()
                .rposition(|&entry| entry < value)
                .ok_or_else(|| "reverse row insertion found no smaller entry".to_string())?;
            std::mem::swap(&mut value, &mut p_rows[earlier_row][position]);
        }
        word[label as usize - 1] = value;
        while p_rows.last().is_some_and(Vec::is_empty) {
            p_rows.pop();
        }
        while q_rows.last().is_some_and(Vec::is_empty) {
            q_rows.pop();
        }
    }
    if !p_rows.is_empty() || !q_rows.is_empty() {
        return Err("inverse RSK did not exhaust its tableaux".into());
    }
    Ok(word)
}

fn signed_source_to_tableau(
    matcher: &mut RecursiveMatcher,
    path: &PathData,
    signed: &SignedSourceState,
) -> Result<SignedTableauState, String> {
    validate_arbitrary_source(path, &signed.source)?;
    if signed.retained_mask & !signed.source.marked_mask != 0 {
        return Err("B is not a subset of the marked ascent set A".into());
    }
    let target = map_arbitrary_source(matcher, path, &signed.source)?;
    let retained_orientation_mask = transport_submask_by_rank(
        signed.source.marked_mask,
        target.orientation_mask,
        signed.retained_mask,
        path.normal_edges.len(),
    )?;
    let word = target_column_crystal_word(path, &target)?;
    let (p, q) = Tableau::rsk(&word);
    let state = SignedTableauState {
        orientation_mask: target.orientation_mask,
        retained_orientation_mask,
        insertion_rows: p.rows().to_vec(),
        recording_rows: q.rows().to_vec(),
    };
    let recovered = tableau_to_signed_source(matcher, path, &state)?;
    if recovered != *signed {
        return Err("signed tableau encoding did not immediately invert".into());
    }
    Ok(state)
}

fn tableau_target(path: &PathData, state: &SignedTableauState) -> Result<TargetState, String> {
    let p = Tableau::new(state.insertion_rows.clone());
    let q = Tableau::new(state.recording_rows.clone());
    let word = inverse_rsk(&p, &q)?;
    target_from_column_crystal_word(path, state.orientation_mask, &word)
}

fn tableau_to_signed_source(
    matcher: &mut RecursiveMatcher,
    path: &PathData,
    state: &SignedTableauState,
) -> Result<SignedSourceState, String> {
    if state.retained_orientation_mask & !state.orientation_mask != 0 {
        return Err("retained target edges are not contained in eta".into());
    }
    let target = tableau_target(path, state)?;
    let source = inverse_arbitrary_target(matcher, path, &target)?;
    let retained_mask = transport_submask_by_rank(
        state.orientation_mask,
        source.marked_mask,
        state.retained_orientation_mask,
        path.normal_edges.len(),
    )?;
    let signed = SignedSourceState {
        source,
        retained_mask,
    };
    if signed.retained_mask & !signed.source.marked_mask != 0 {
        return Err("decoded B is not contained in decoded A".into());
    }
    Ok(signed)
}

fn signed_tableau_involution(
    matcher: &mut RecursiveMatcher,
    path: &PathData,
    state: &SignedTableauState,
) -> Result<SignedTableauState, String> {
    let mut signed = tableau_to_signed_source(matcher, path, state)?;
    let ascents = edge_ascent_mask(&signed.source.coloring, &path.normal_edges);
    let toggle_candidates = ascents & !signed.retained_mask;
    if toggle_candidates == 0 {
        return Ok(state.clone());
    }
    let edge = toggle_candidates.trailing_zeros();
    signed.source.marked_mask ^= 1u64 << edge;
    signed_source_to_tableau(matcher, path, &signed)
}

fn tableau_crystal_step(
    path: &PathData,
    state: &SignedTableauState,
    index: u32,
    raising: bool,
) -> Result<Option<SignedTableauState>, String> {
    let p = Tableau::new(state.insertion_rows.clone());
    let changed = if raising {
        p.crystal_e(index)
    } else {
        p.crystal_f(index)
    };
    let Some(changed) = changed else {
        return Ok(None);
    };
    let result = SignedTableauState {
        orientation_mask: state.orientation_mask,
        retained_orientation_mask: state.retained_orientation_mask,
        insertion_rows: changed.rows().to_vec(),
        recording_rows: state.recording_rows.clone(),
    };
    tableau_target(path, &result)?;
    Ok(Some(result))
}

fn tableau_simple_reflection(
    path: &PathData,
    state: &SignedTableauState,
    index: u32,
) -> Result<SignedTableauState, String> {
    let p = Tableau::new(state.insertion_rows.clone());
    let mut epsilon = 0usize;
    let mut raised = p.clone();
    while let Some(next) = raised.crystal_e(index) {
        epsilon += 1;
        raised = next;
    }
    let mut phi = 0usize;
    let mut lowered = p.clone();
    while let Some(next) = lowered.crystal_f(index) {
        phi += 1;
        lowered = next;
    }
    let mut reflected = p;
    if phi >= epsilon {
        for _ in 0..phi - epsilon {
            reflected = reflected
                .crystal_f(index)
                .ok_or_else(|| "S_i lowering string ended too early".to_string())?;
        }
    } else {
        for _ in 0..epsilon - phi {
            reflected = reflected
                .crystal_e(index)
                .ok_or_else(|| "S_i raising string ended too early".to_string())?;
        }
    }
    let result = SignedTableauState {
        orientation_mask: state.orientation_mask,
        retained_orientation_mask: state.retained_orientation_mask,
        insertion_rows: reflected.rows().to_vec(),
        recording_rows: state.recording_rows.clone(),
    };
    tableau_target(path, &result)?;
    Ok(result)
}

fn tableau_skeleton(state: &SignedTableauState) -> TableauSkeleton {
    TableauSkeleton {
        orientation_mask: state.orientation_mask,
        retained_orientation_mask: state.retained_orientation_mask,
        recording_rows: state.recording_rows.clone(),
    }
}

fn skeleton_sign(skeleton: &TableauSkeleton) -> i8 {
    if (skeleton.orientation_mask.count_ones() - skeleton.retained_orientation_mask.count_ones())
        % 2
        == 0
    {
        1
    } else {
        -1
    }
}

fn skeleton_key(skeleton: &TableauSkeleton) -> SchurKey {
    SchurKey {
        q_degree: skeleton.retained_orientation_mask.count_ones() as usize,
        shape: tableau_shape(&skeleton.recording_rows),
    }
}

fn first_mask_bit(mask: u64) -> u64 {
    debug_assert_ne!(mask, 0);
    1u64 << mask.trailing_zeros()
}

/// The first-stage Boolean cancellation at fixed HRV map and recording tableau.
///
/// A returned partner differs by one unmarked orientation edge.  `None` means
/// that every row is in one of the two critical forms described by the
/// fixed-HRV product formula.
fn boolean_hrv_partner(
    path: &PathData,
    skeleton: &TableauSkeleton,
) -> Result<Option<TableauSkeleton>, String> {
    if skeleton.retained_orientation_mask & !skeleton.orientation_mask != 0 {
        return Err("Boolean HRV state has a retained edge outside eta".into());
    }
    let hrv = hrv_for_mask(path, skeleton.orientation_mask)?;
    let retained = skeleton.retained_orientation_mask;
    let mut toggle = None;
    for vertex in 0..path.n {
        let mut lower = 0u64;
        let mut tied = 0u64;
        for (index, &(tail, head)) in path.normal_edges.iter().enumerate() {
            if tail != vertex {
                continue;
            }
            let bit = 1u64 << index;
            match hrv[head].cmp(&hrv[vertex]) {
                std::cmp::Ordering::Less => lower |= bit,
                std::cmp::Ordering::Equal => tied |= bit,
                std::cmp::Ordering::Greater => {}
            }
        }

        let unmarked_lower = lower & !retained;
        if unmarked_lower != 0 {
            toggle = Some(first_mask_bit(unmarked_lower));
            break;
        }

        let forced = hrv[vertex] == vertex
            || path
                .strict_edges
                .iter()
                .any(|&(tail, head)| tail == vertex && hrv[head] == hrv[vertex]);
        if forced {
            let unmarked_tied = tied & !retained;
            if unmarked_tied != 0 {
                toggle = Some(first_mask_bit(unmarked_tied));
                break;
            }
            continue;
        }

        let marked_tied = tied & retained;
        if marked_tied != 0 {
            let unmarked_tied = tied & !retained;
            if unmarked_tied != 0 {
                toggle = Some(first_mask_bit(unmarked_tied));
                break;
            }
        } else {
            if tied == 0 {
                return Err(format!(
                    "unforced vertex {vertex} has no tied normal edge for HRV map {hrv:?}"
                ));
            }
            let pivot = first_mask_bit(tied);
            if skeleton.orientation_mask & tied & !pivot != 0 {
                toggle = Some(pivot);
                break;
            }
            if skeleton.orientation_mask & tied != pivot {
                return Err(format!(
                    "unforced vertex {vertex} has neither a marked tied edge nor the pivot singleton"
                ));
            }
        }
    }

    let Some(toggle) = toggle else {
        return Ok(None);
    };
    let partner = TableauSkeleton {
        orientation_mask: skeleton.orientation_mask ^ toggle,
        retained_orientation_mask: retained,
        recording_rows: skeleton.recording_rows.clone(),
    };
    if partner.retained_orientation_mask & !partner.orientation_mask != 0 {
        return Err("Boolean HRV toggle removed a retained edge".into());
    }
    if hrv_for_mask(path, partner.orientation_mask)? != hrv {
        return Err("Boolean HRV toggle changed the HRV map".into());
    }
    if skeleton_sign(&partner) != -skeleton_sign(skeleton) {
        return Err("Boolean HRV toggle did not reverse sign".into());
    }
    Ok(Some(partner))
}

fn is_triangle_surgery(path: &PathData, minus: &TableauSkeleton, plus: &TableauSkeleton) -> bool {
    if minus.recording_rows != plus.recording_rows {
        return false;
    }
    let eta_change = minus.orientation_mask ^ plus.orientation_mask;
    let retained_change = minus.retained_orientation_mask ^ plus.retained_orientation_mask;
    if eta_change.count_ones() != 3 || retained_change.count_ones() != 2 {
        return false;
    }
    let changed_edges = path
        .normal_edges
        .iter()
        .enumerate()
        .filter(|(index, _)| eta_change & (1u64 << index) != 0)
        .map(|(_, &edge)| edge)
        .collect::<BTreeSet<_>>();
    let vertices = changed_edges
        .iter()
        .flat_map(|&(u, v)| [u, v])
        .collect::<BTreeSet<_>>();
    if vertices.len() != 3 {
        return false;
    }
    let vertices = vertices.into_iter().collect::<Vec<_>>();
    let [low, mid, high] = vertices.as_slice() else {
        unreachable!("checked three vertices")
    };
    let triangle = BTreeSet::from([(*low, *mid), (*low, *high), (*mid, *high)]);
    if changed_edges != triangle {
        return false;
    }
    let lower_bit = path
        .normal_edges
        .binary_search(&(*low, *mid))
        .ok()
        .map(|index| 1u64 << index);
    let upper_bit = path
        .normal_edges
        .binary_search(&(*mid, *high))
        .ok()
        .map(|index| 1u64 << index);
    let (Some(lower_bit), Some(upper_bit)) = (lower_bit, upper_bit) else {
        return false;
    };
    let minus_changed_marks = minus.retained_orientation_mask & retained_change;
    let plus_changed_marks = plus.retained_orientation_mask & retained_change;
    if !((minus_changed_marks == lower_bit && plus_changed_marks == upper_bit)
        || (minus_changed_marks == upper_bit && plus_changed_marks == lower_bit))
    {
        return false;
    }
    (minus.orientation_mask & eta_change).count_ones() == 2
        && (plus.orientation_mask & eta_change).count_ones() == 1
}

fn permutations(n: usize) -> Vec<Vec<u32>> {
    fn recurse(
        n: usize,
        permutation: &mut Vec<u32>,
        used: &mut [bool],
        output: &mut Vec<Vec<u32>>,
    ) {
        if permutation.len() == n {
            output.push(permutation.clone());
            return;
        }
        for value in 1..=n {
            if !used[value] {
                used[value] = true;
                permutation.push(value as u32);
                recurse(n, permutation, used, output);
                permutation.pop();
                used[value] = false;
            }
        }
    }

    let mut output = Vec::new();
    recurse(n, &mut Vec::new(), &mut vec![false; n + 1], &mut output);
    output
}

fn admissible_recordings(
    n: usize,
    column_lengths: &[usize],
    permutation_cache: &[Vec<u32>],
) -> BTreeSet<Vec<Vec<u32>>> {
    debug_assert_eq!(column_lengths.iter().sum::<usize>(), n);
    permutation_cache
        .iter()
        .filter(|permutation| {
            let mut start = 0usize;
            for &length in column_lengths {
                let end = start + length;
                if !permutation[start..end]
                    .windows(2)
                    .all(|pair| pair[0] > pair[1])
                {
                    return false;
                }
                start = end;
            }
            true
        })
        .map(|permutation| Tableau::rsk(permutation).1.rows().to_vec())
        .collect()
}

fn enumerate_tableau_skeletons(path: &PathData) -> Result<Vec<TableauSkeleton>, String> {
    let permutation_cache = permutations(path.n);
    let mut recording_cache: BTreeMap<Vec<usize>, BTreeSet<Vec<Vec<u32>>>> = BTreeMap::new();
    let mut skeletons = Vec::new();
    for orientation_mask in 0..(1u64 << path.normal_edges.len()) {
        let hrv = hrv_for_mask(path, orientation_mask)?;
        let column_lengths = fibres(&hrv)
            .into_iter()
            .map(|fibre| fibre.len())
            .collect::<Vec<_>>();
        let recordings = recording_cache
            .entry(column_lengths.clone())
            .or_insert_with(|| admissible_recordings(path.n, &column_lengths, &permutation_cache));
        let mut retained_orientation_mask = orientation_mask;
        loop {
            skeletons.extend(
                recordings
                    .iter()
                    .cloned()
                    .map(|recording_rows| TableauSkeleton {
                        orientation_mask,
                        retained_orientation_mask,
                        recording_rows,
                    }),
            );
            if retained_orientation_mask == 0 {
                break;
            }
            retained_orientation_mask = (retained_orientation_mask - 1) & orientation_mask;
        }
    }
    Ok(skeletons)
}

#[allow(dead_code)]
fn elementary_dual_equivalence(rows: &[Vec<u32>], index: u32) -> Vec<Vec<u32>> {
    debug_assert!(index >= 2);
    let tableau = Tableau::new(rows.to_vec());
    debug_assert!(tableau.is_standard());
    let word = tableau.reading_word();
    let position = |entry| {
        word.iter()
            .position(|&value| value == entry)
            .expect("standard tableau contains every label")
    };
    let lower = position(index - 1);
    let middle = position(index);
    let upper = position(index + 1);
    if (lower < middle && middle < upper) || (upper < middle && middle < lower) {
        return rows.to_vec();
    }
    let swap_with = if middle.abs_diff(lower) > middle.abs_diff(upper) {
        index - 1
    } else {
        index + 1
    };
    rows.iter()
        .map(|row| {
            row.iter()
                .map(|&entry| {
                    if entry == index {
                        swap_with
                    } else if entry == swap_with {
                        index
                    } else {
                        entry
                    }
                })
                .collect()
        })
        .collect()
}

