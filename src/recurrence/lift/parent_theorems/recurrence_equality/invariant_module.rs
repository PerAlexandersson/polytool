//! The invariant module of a rule modulo a target recurrence: the general
//! step of [`super::certify_recurrence_equality`] when the target rule does
//! not divide the other rule (module documentation of `recurrence_equality`,
//! "Invariant module").
//!
//! Let `L = g(n, x) S^k + (terms of shift < k)` be the target recurrence
//! (its leader free of derivatives, possibly dependent on `x`) and `E` a
//! rule.  Operators of shift below `k` form, modulo the left ideal of `L`,
//! the free left module `M = K<D>^k` over `K<D>`, `K = Q(n, x)`: every
//! operator reduces to one of shift `< k` by subtracting left multiples of
//! `S^j o L`.  The rows `P` of the target annihilate a submodule of `M`;
//! the module generated by `E` and closed under `S` (left multiplication
//! by `S`, then reduction modulo `L`) is the smallest one that an
//! induction on the index can prove annihilates `P`.
//!
//! [`invariant_module`] computes it exactly.  A submodule is kept in an
//! echelon (Hermite) form: at most one generator per *pivot* column (its
//! largest shift), whose top term `a(n, x) D^r S^i` has the least
//! derivative order `r` in that column.  The term order is the shift, then
//! the derivative order.  A top term `c D^m S^i` of an operator is reduced
//!
//! - for `i >= k`: by `c D^m S^(i-k) o L`, after a left multiplication by
//!   `g(n + i - k, x)` (the top of `D^m S^(i-k) o L` is
//!   `g(n + i - k, x) D^m S^i`, since `S` and `D` commute and the leader
//!   is free of `D`);
//! - for `i < k`: by `c D^(m-r) o G`, after a left multiplication by the
//!   pivot coefficient `a(n, x)` of the generator `G` of column `i`, when
//!   `m >= r`.
//!
//! An operator whose top term cannot be reduced is not in the module (the
//! generators have distinct pivot columns, so the top term of every module
//! element is a left multiple of a pivot term).  Inserting such an operator
//! either fills an empty pivot column or replaces the generator of a
//! larger derivative order, which is reduced again (a Euclidean step over
//! `K<D>`).  The closure inserts `S o G` for every generator until every
//! one reduces to zero; ascending chains of submodules of `M` stop
//! (`K<D>` is a left Noetherian ring), and budgets keep the search bounded.
//!
//! The result is a set of generators `G_1, ..., G_r` (shift below `k`)
//! and polynomial identities
//!
//! ```text
//! W_i(n, x) (S o G_i) = Y_i o L + sum_l Z_(i,l) o G_l,
//! W(n, x) E = Y o L + sum_l Z_l o G_l,
//! ```
//!
//! with `Z_(i,l)` shift-free (`S o G_i` has shift at most `k`).  Nothing in
//! the identities depends on how they were found:
//! [`InvariantModule::identities_hold`] recomputes them.

use crate::polynomial::Polynomial;
use crate::recurrence::implicit::algebra::{Biv, DOp};
use crate::recurrence::lift::hadamard_factor::annihilator::bivariate_exact_quotient;
use crate::vec_poly;
use crate::BigRational;
use num_bigint::BigInt;
use num_integer::Integer;
use num_traits::{One, Signed, Zero};

type Q = BigRational;

/// Bounds of [`invariant_module`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct ModuleBudget {
    /// Largest number of closure rounds.
    pub(super) max_rounds: usize,
    /// Largest number of insertions into the echelon form.
    pub(super) max_insertions: usize,
    /// Largest number of top-term reductions in one reduction.
    pub(super) max_reduction_steps: usize,
    /// Largest number of terms of an operator built along the way.
    pub(super) max_terms: usize,
    /// Largest number of rational coefficient entries of an operator built
    /// along the way.
    pub(super) max_entries: usize,
    /// Largest total bit length of the coefficients of an operator built
    /// along the way.
    pub(super) max_bits: u64,
    /// Largest total work: the sum, over every reduction step, of the
    /// coefficient bit length of the operators combined (a deterministic
    /// proxy of the running time).
    pub(super) max_work: u64,
}

/// One identity `multiplier · dividend = recurrence_quotient o L +
/// sum_l generator_quotients[l] o G_l`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct ModuleIdentity {
    /// `W(n, x)` as a product of nonzero factors (the leaders and pivot
    /// coefficients used, without repetition of equal factors in the list
    /// order); `W(n, .)` vanishes exactly where a factor does.
    pub(super) multiplier_factors: Vec<(Biv, usize)>,
    /// `Y`.
    pub(super) recurrence_quotient: DOp,
    /// `Z_l`, one per generator.
    pub(super) generator_quotients: Vec<DOp>,
}

impl ModuleIdentity {
    /// `W(n, x)`, the product of the factors.
    pub(super) fn multiplier(&self) -> Biv {
        self.multiplier_factors
            .iter()
            .fold(Biv::one(), |acc, (factor, power)| {
                acc.multiply(&factor.power(*power))
            })
    }

    fn holds(&self, dividend: &DOp, recurrence: &DOp, generators: &[DOp]) -> bool {
        if self.multiplier_factors.iter().any(|(f, _)| f.is_zero())
            || self.generator_quotients.len() != generators.len()
        {
            return false;
        }
        let mut right = self.recurrence_quotient.compose(recurrence);
        for (z, g) in self.generator_quotients.iter().zip(generators) {
            right = right.add(&z.compose(g));
        }
        dividend.left_multiply(&self.multiplier()) == right
    }
}

/// The invariant module of a rule modulo a target recurrence (module
/// documentation).
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct InvariantModule {
    /// `G_1, ..., G_r`, by increasing pivot column, each of shift below the
    /// order of the recurrence.
    pub(super) generators: Vec<DOp>,
    /// `W_i (S o G_i) = Y_i o L + sum_l Z_(i,l) o G_l`, one per generator,
    /// with `Y_i` and every `Z_(i,l)` shift-free.
    pub(super) steps: Vec<ModuleIdentity>,
    /// `W E = Y o L + sum_l Z_l o G_l`.
    pub(super) rule: ModuleIdentity,
}

impl InvariantModule {
    /// Recompute every identity exactly, with the shape conditions of the
    /// induction (generators of shift below `order`, shift-free step
    /// quotients).
    pub(super) fn identities_hold(&self, rule: &DOp, recurrence: &DOp, order: usize) -> bool {
        if self.steps.len() != self.generators.len()
            || self
                .generators
                .iter()
                .any(|g| g.is_zero() || g.max_shift() >= order)
        {
            return false;
        }
        let shift_free = |op: &DOp| op.is_zero() || op.max_shift() == 0;
        self.generators.iter().zip(&self.steps).all(|(g, step)| {
            shift_free(&step.recurrence_quotient)
                && step.generator_quotients.iter().all(shift_free)
                && step.holds(&g.shifted(1), recurrence, &self.generators)
        }) && self.rule.holds(rule, recurrence, &self.generators)
    }
}

/// The top term key `(shift, derivative order)`, `None` for zero.
fn top_key(op: &DOp) -> Option<(usize, usize)> {
    op.0.keys().next_back().copied()
}

/// The number of rational entries of the coefficients of `op`.
fn entries(op: &DOp) -> usize {
    op.0.values()
        .map(|c| c.rows().iter().map(Vec::len).sum::<usize>())
        .sum()
}

/// The total bit length of the numerators and denominators of the
/// coefficients of `op`.
fn bits(op: &DOp) -> u64 {
    op.0.values()
        .flat_map(|c| c.rows().iter().flatten())
        .map(|v| v.numer().bits() + v.denom().bits())
        .sum()
}

/// A prime below `2^31` for the modular coprimality test of
/// [`integer_gcd`] (products of two residues fit in `u64`).
const GCD_PRIME: u64 = 2_147_483_647;

fn residues(p: &[BigInt]) -> Vec<u64> {
    let prime = BigInt::from(GCD_PRIME);
    let mut out: Vec<u64> = p
        .iter()
        .map(|c| {
            let r = c.mod_floor(&prime);
            u64::try_from(r).expect("a residue fits in u64")
        })
        .collect();
    while out.last() == Some(&0) {
        out.pop();
    }
    out
}

fn power_mod(mut base: u64, mut exponent: u64) -> u64 {
    let mut out = 1u64;
    while exponent > 0 {
        if exponent & 1 == 1 {
            out = out * base % GCD_PRIME;
        }
        base = base * base % GCD_PRIME;
        exponent >>= 1;
    }
    out
}

/// The gcd of two nonzero polynomials modulo `GCD_PRIME` (not normalized).
fn modular_gcd(mut a: Vec<u64>, mut b: Vec<u64>) -> Vec<u64> {
    if a.len() < b.len() {
        std::mem::swap(&mut a, &mut b);
    }
    while !b.is_empty() {
        let inverse = power_mod(*b.last().expect("nonzero"), GCD_PRIME - 2);
        while a.len() >= b.len() {
            let factor = a.last().expect("nonzero") * inverse % GCD_PRIME;
            let offset = a.len() - b.len();
            for (i, c) in b.iter().enumerate() {
                let slot = &mut a[offset + i];
                *slot = (*slot + GCD_PRIME - factor * c % GCD_PRIME) % GCD_PRIME;
            }
            while a.last() == Some(&0) {
                a.pop();
            }
            if a.is_empty() {
                break;
            }
        }
        std::mem::swap(&mut a, &mut b);
    }
    a
}

/// `p` divided by the gcd of its integer coefficients, with a positive
/// leading coefficient (empty for zero).
fn integer_primitive(p: &[BigInt]) -> Vec<BigInt> {
    let mut p = p.to_vec();
    while p.last().is_some_and(Zero::is_zero) {
        p.pop();
    }
    let content = p.iter().fold(BigInt::zero(), |acc, c| acc.gcd(c));
    if content.is_zero() {
        return Vec::new();
    }
    let content = if p.last().expect("nonzero").is_negative() {
        -content
    } else {
        content
    };
    p.iter().map(|c| c / &content).collect()
}

/// The primitive gcd of two nonzero primitive integer polynomials: a
/// modular test settles coprimality (when the prime divides neither
/// leading coefficient the modular gcd has at least the true degree), the
/// primitive pseudo-remainder sequence computes the rest.
fn integer_gcd(a: &[BigInt], b: &[BigInt]) -> Vec<BigInt> {
    let prime = BigInt::from(GCD_PRIME);
    let leading_survives = |p: &[BigInt]| !p.last().expect("nonzero").mod_floor(&prime).is_zero();
    if leading_survives(a)
        && leading_survives(b)
        && modular_gcd(residues(a), residues(b)).len() <= 1
    {
        return vec![BigInt::one()];
    }
    let (mut left, mut right) = if a.len() >= b.len() {
        (a.to_vec(), b.to_vec())
    } else {
        (b.to_vec(), a.to_vec())
    };
    while !right.is_empty() {
        // Pseudo-remainder of left by right.
        let lead = right.last().expect("nonzero").clone();
        let mut remainder = left.clone();
        while remainder.len() >= right.len() {
            let top = remainder.last().expect("nonzero").clone();
            let offset = remainder.len() - right.len();
            for c in remainder.iter_mut() {
                *c *= &lead;
            }
            for (i, c) in right.iter().enumerate() {
                remainder[offset + i] -= &top * c;
            }
            while remainder.last().is_some_and(Zero::is_zero) {
                remainder.pop();
            }
        }
        left = right;
        right = integer_primitive(&remainder);
    }
    integer_primitive(&left)
}

/// Whether `divisor` divides `p` exactly (integer polynomials).
fn divides_exactly(divisor: &[BigInt], p: &[BigInt]) -> bool {
    let to_q = |v: &[BigInt]| Polynomial::new(v.iter().cloned().map(Q::from_integer).collect());
    let (_, remainder) = to_q(p).div_rem(&to_q(divisor));
    remainder.coeffs().iter().all(Zero::is_zero)
}

/// The gcd of univariate polynomials over the rationals as a primitive
/// integer polynomial (`[1]` when it is constant, empty when every input
/// is zero).  The common power of the variable is split off first; a
/// modular gcd of all inputs settles the common case of no further common
/// factor, and otherwise the exact gcd is updated only by inputs that the
/// current candidate does not divide.
fn univariate_gcd<'a>(polynomials: impl Iterator<Item = &'a [Q]>) -> Vec<Q> {
    let mut inputs: Vec<Vec<BigInt>> = polynomials
        .map(|p| integer_primitive(&vec_poly::clear_denominators(p)))
        .filter(|p| !p.is_empty())
        .collect();
    if inputs.is_empty() {
        return Vec::new();
    }
    let valuation = inputs
        .iter()
        .map(|p| p.iter().position(|c| !c.is_zero()).expect("nonzero"))
        .min()
        .expect("nonempty");
    for p in &mut inputs {
        p.drain(..valuation);
    }
    inputs.sort_by_key(Vec::len);
    let prime = BigInt::from(GCD_PRIME);
    let mut modular: Option<Vec<u64>> = None;
    let mut reliable = true;
    for p in &inputs {
        if p.last().expect("nonzero").mod_floor(&prime).is_zero() {
            reliable = false;
            break;
        }
        let r = residues(p);
        let next = match modular.take() {
            None => r,
            Some(m) => modular_gcd(m, r),
        };
        let constant = next.len() <= 1;
        modular = Some(next);
        if constant {
            break;
        }
    }
    let mut gcd = vec![BigInt::one()];
    if !(reliable && modular.as_ref().is_some_and(|m| m.len() <= 1)) {
        let mut candidate = inputs[0].clone();
        for p in &inputs[1..] {
            if candidate.len() <= 1 {
                break;
            }
            if !divides_exactly(&candidate, p) {
                candidate = integer_gcd(&candidate, p);
            }
        }
        gcd = candidate;
    }
    let mut out = vec![Q::zero(); valuation];
    out.extend(gcd.into_iter().map(Q::from_integer));
    if out.len() <= 1 {
        return vec![Q::one()];
    }
    out
}

/// `p / divisor` for a polynomial `divisor` in `x` dividing every row.
fn divide_rows_by(p: &Biv, divisor: &Polynomial<Q>) -> Biv {
    Biv::new(
        p.rows()
            .iter()
            .map(|row| {
                Polynomial::new(row.clone())
                    .div_rem(divisor)
                    .0
                    .coeffs()
                    .to_vec()
            })
            .collect(),
    )
}

/// `p / divisor` for a polynomial `divisor` in `n` dividing every column.
fn divide_columns_by(p: &Biv, divisor: &Polynomial<Q>) -> Biv {
    let width = p.variable_degree().map_or(0, |d| d + 1);
    let columns: Vec<Vec<Q>> = (0..width)
        .map(|j| {
            Polynomial::new(p.variable_coefficient(j))
                .div_rem(divisor)
                .0
                .coeffs()
                .to_vec()
        })
        .collect();
    let height = columns.iter().map(Vec::len).max().unwrap_or(0);
    Biv::new(
        (0..height)
            .map(|i| {
                columns
                    .iter()
                    .map(|column| column.get(i).cloned().unwrap_or_else(Q::zero))
                    .collect()
            })
            .collect(),
    )
}

/// `op` divided by its content: the common factors in `x` alone and in `n`
/// alone (univariate gcds) and the rational content, with integer
/// coefficients and a positive top coefficient.  Only shortens the
/// coefficients (a nonzero factor in `Q[n, x]` changes no membership in a
/// module over `Q(n, x)<D>`).
fn normalized_operator(op: &DOp, factors: &[Biv]) -> DOp {
    if op.is_zero() {
        return op.clone();
    }
    let x_content = univariate_gcd(
        op.0.values()
            .flat_map(|c| c.rows().iter().map(Vec::as_slice)),
    );
    let mut out = op.clone();
    if x_content.len() > 1 {
        let divisor = Polynomial::new(x_content);
        out = DOp(out
            .0
            .iter()
            .map(|(key, c)| (*key, divide_rows_by(c, &divisor)))
            .collect());
    }
    let columns: Vec<Vec<Q>> = out
        .0
        .values()
        .flat_map(|c| {
            let width = c.variable_degree().map_or(0, |d| d + 1);
            (0..width).map(move |j| c.variable_coefficient(j))
        })
        .collect();
    let n_content = univariate_gcd(columns.iter().map(Vec::as_slice));
    if n_content.len() > 1 {
        let divisor = Polynomial::new(n_content);
        out = DOp(out
            .0
            .iter()
            .map(|(key, c)| (*key, divide_columns_by(c, &divisor)))
            .collect());
    }
    // Known mixed factors (pivot coefficients met before), as often as
    // they divide every coefficient.
    for factor in factors {
        loop {
            if !out.0.values().all(|c| may_divide(c, factor)) {
                break;
            }
            let quotients: Option<Vec<((usize, usize), Biv)>> = out
                .0
                .iter()
                .map(|(key, c)| bivariate_exact_quotient(c, factor).map(|q| (*key, q)))
                .collect();
            match quotients {
                Some(quotients) => out = DOp(quotients.into_iter().collect()),
                None => break,
            }
        }
    }
    // Rational content: lcm of denominators over gcd of numerators.
    let (denominator_lcm, _) = vec_poly::clear_denominators_with_scale_iter(
        out.0
            .values()
            .flat_map(|c| c.rows().iter().flatten())
            .filter(|value| !value.is_zero()),
    );
    let mut numerator_gcd = BigInt::zero();
    for c in out.0.values() {
        for value in c.rows().iter().flatten() {
            if !value.is_zero() {
                numerator_gcd = numerator_gcd.gcd(value.numer());
            }
        }
    }
    let top_sign_negative = out
        .0
        .values()
        .next_back()
        .and_then(|c| c.leading().cloned())
        .is_some_and(|lead| lead.is_negative());
    let mut scale = Q::new(denominator_lcm, numerator_gcd);
    if top_sign_negative {
        scale = -scale;
    }
    out.scale(&scale)
}

/// The specialization point `n = N0` of the modular divisibility filter.
const FILTER_INDEX: u64 = 1_000_003;

/// `p(N0, x)` modulo `GCD_PRIME`, `None` when a denominator vanishes there.
fn specialized_residues(p: &Biv) -> Option<Vec<u64>> {
    let prime = BigInt::from(GCD_PRIME);
    let width = p.variable_degree().map_or(0, |d| d + 1);
    let mut out = vec![0u64; width];
    let mut power = 1u64;
    for row in p.rows() {
        for (j, value) in row.iter().enumerate() {
            if value.is_zero() {
                continue;
            }
            let numerator = u64::try_from(value.numer().mod_floor(&prime)).ok()?;
            let denominator = u64::try_from(value.denom().mod_floor(&prime)).ok()?;
            if denominator == 0 {
                return None;
            }
            let term = numerator * power_mod(denominator, GCD_PRIME - 2) % GCD_PRIME;
            out[j] = (out[j] + term * power) % GCD_PRIME;
        }
        power = power * (FILTER_INDEX % GCD_PRIME) % GCD_PRIME;
    }
    while out.last() == Some(&0) {
        out.pop();
    }
    Some(out)
}

/// `false` only when `f` certainly does not divide `c`: `c(N0, x)` is not
/// divisible by `f(N0, x)` modulo `GCD_PRIME` while `f(N0, x)` keeps its
/// degree (a quick filter before the exact division).
fn may_divide(c: &Biv, f: &Biv) -> bool {
    let (Some(mut a), Some(b)) = (specialized_residues(c), specialized_residues(f)) else {
        return true;
    };
    if b.is_empty() || Some(b.len() - 1) != f.variable_degree() {
        return true;
    }
    let inverse = power_mod(*b.last().expect("nonzero"), GCD_PRIME - 2);
    while a.len() >= b.len() {
        let factor = a.last().expect("nonzero") * inverse % GCD_PRIME;
        let offset = a.len() - b.len();
        for (i, v) in b.iter().enumerate() {
            let slot = &mut a[offset + i];
            *slot = (*slot + GCD_PRIME - factor * v % GCD_PRIME) % GCD_PRIME;
        }
        while a.last() == Some(&0) {
            a.pop();
        }
    }
    a.is_empty()
}

/// Shifts `f(n + s, x)` of every known mixed factor tried on remainders
/// (`S` shifts the coefficients of the generators it is applied to).
const FACTOR_SHIFTS: std::ops::RangeInclusive<i64> = -2..=4;

/// The part of `f` that depends on both `n` and `x`: `f` divided by its
/// contents in `x` alone and in `n` alone; `None` when that part is free of
/// `n` or of `x`.
fn mixed_part(f: &Biv) -> Option<Biv> {
    let as_operator = DOp::single(0, 0, f.clone());
    let part = normalized_operator(&as_operator, &[])
        .0
        .into_values()
        .next()?;
    (part.index_degree().unwrap_or(0) > 0 && part.variable_degree().unwrap_or(0) > 0)
        .then_some(part)
}

/// The echelon form of a submodule of `M` and the reductions modulo it.
struct Reducer<'a> {
    recurrence: &'a DOp,
    order: usize,
    /// `g(n, x)`, the leader of the recurrence.
    leader: Biv,
    /// The generator of each pivot column.
    generators: Vec<Option<DOp>>,
    budget: &'a ModuleBudget,
    insertions: usize,
    /// The work spent so far (see [`ModuleBudget::max_work`]).
    work: std::cell::Cell<u64>,
    /// Mixed parts of the leader and of every pivot coefficient met, tried
    /// as factors of remainders (pseudo-remainders carry powers of earlier
    /// leading coefficients).
    known_factors: Vec<Biv>,
}

/// A reduction `multiplier · dividend = recurrence_quotient o L + sum
/// generator_quotients[column] o G_column + remainder` (the quotients are
/// tracked only on request).
struct Reduction {
    multiplier_factors: Vec<(Biv, usize)>,
    recurrence_quotient: DOp,
    /// Indexed by pivot column.
    generator_quotients: Vec<DOp>,
    remainder: DOp,
}

impl Reducer<'_> {
    fn check_size(&self, op: &DOp, what: &str) -> Result<(), String> {
        if op.0.len() > self.budget.max_terms {
            return Err(format!(
                "{what} has {} terms, more than the budget {}",
                op.0.len(),
                self.budget.max_terms
            ));
        }
        let size = entries(op);
        if size > self.budget.max_entries {
            return Err(format!(
                "{what} has {size} coefficient entries, more than the budget {}",
                self.budget.max_entries
            ));
        }
        let size = bits(op);
        if size > self.budget.max_bits {
            return Err(format!(
                "{what} has coefficients of {size} bits in total, more than the budget {}",
                self.budget.max_bits
            ));
        }
        Ok(())
    }

    /// Reduce top terms until the top term is not reducible (or the
    /// operator is zero).  Without tracking, the remainder is kept
    /// primitive (a nonzero factor in `Q[n, x]` changes no membership).
    fn reduce(&self, op: &DOp, track: bool) -> Result<Reduction, String> {
        let mut out = Reduction {
            multiplier_factors: Vec::new(),
            recurrence_quotient: DOp::default(),
            generator_quotients: vec![DOp::default(); self.order],
            remainder: if track {
                op.clone()
            } else {
                normalized_operator(op, &self.known_factors)
            },
        };
        let mut steps = 0usize;
        while let Some((shift, derivative)) = top_key(&out.remainder) {
            let c = out.remainder.0[&(shift, derivative)].clone();
            let (factor, step, column) = if shift >= self.order {
                (
                    self.leader.shift_index((shift - self.order) as i64),
                    DOp::single(shift - self.order, derivative, c),
                    None,
                )
            } else if let Some(generator) = &self.generators[shift] {
                let (_, pivot) = top_key(generator).expect("generators are nonzero");
                if pivot > derivative {
                    break;
                }
                (
                    generator.0[&(shift, pivot)].clone(),
                    DOp::single(0, derivative - pivot, c),
                    Some(shift),
                )
            } else {
                break;
            };
            steps += 1;
            if steps > self.budget.max_reduction_steps {
                return Err(format!(
                    "a reduction needs more than {} steps",
                    self.budget.max_reduction_steps
                ));
            }
            let divisor = match column {
                None => self.recurrence,
                Some(column) => self.generators[column].as_ref().expect("checked"),
            };
            // The step costs about the product of the remainder's size
            // and the factor's, plus the composition with the divisor.
            let cost = bits(&out.remainder)
                .saturating_mul(1 + factor.rows().iter().flatten().count() as u64)
                .saturating_add(bits(divisor).saturating_mul(1 + step.0.len() as u64));
            self.work.set(self.work.get().saturating_add(cost));
            if self.work.get() > self.budget.max_work {
                return Err(format!(
                    "the module search exceeds the work budget {}",
                    self.budget.max_work
                ));
            }
            out.remainder = out
                .remainder
                .left_multiply(&factor)
                .subtract(&step.compose(divisor));
            if out.remainder.0.contains_key(&(shift, derivative)) {
                return Err("a reduction step did not cancel the top term".into());
            }
            if track {
                match out
                    .multiplier_factors
                    .iter_mut()
                    .find(|(known, _)| *known == factor)
                {
                    Some((_, power)) => *power += 1,
                    None => out.multiplier_factors.push((factor.clone(), 1)),
                }
                out.recurrence_quotient = out.recurrence_quotient.left_multiply(&factor);
                for quotient in &mut out.generator_quotients {
                    *quotient = quotient.left_multiply(&factor);
                }
                match column {
                    None => out.recurrence_quotient = out.recurrence_quotient.add(&step),
                    Some(column) => {
                        out.generator_quotients[column] = out.generator_quotients[column].add(&step)
                    }
                }
                self.check_size(&out.recurrence_quotient, "a quotient")?;
            } else {
                out.remainder = normalized_operator(&out.remainder, &self.known_factors);
            }
            self.check_size(&out.remainder, "a remainder")?;
        }
        Ok(out)
    }

    /// Insert an operator into the echelon form (a Euclidean step when its
    /// pivot column is taken by a generator of larger derivative order).
    fn insert(&mut self, op: DOp) -> Result<(), String> {
        let mut pending = vec![op];
        while let Some(next) = pending.pop() {
            let reduced = self.reduce(&next, false)?.remainder;
            let Some((column, _)) = top_key(&reduced) else {
                continue;
            };
            self.insertions += 1;
            if self.insertions > self.budget.max_insertions {
                return Err(format!(
                    "the module needs more than {} insertions",
                    self.budget.max_insertions
                ));
            }
            let pivot = &reduced.0[&top_key(&reduced).expect("nonzero")];
            if let Some(part) = mixed_part(pivot) {
                for shift in FACTOR_SHIFTS {
                    let shifted = part.shift_index(shift);
                    if !self.known_factors.contains(&shifted) {
                        self.known_factors.push(shifted);
                    }
                }
            }
            if let Some(previous) = self.generators[column].replace(reduced) {
                pending.push(previous);
            }
        }
        Ok(())
    }

    fn generator_list(&self) -> Vec<DOp> {
        self.generators.iter().flatten().cloned().collect()
    }

    /// The tracked reduction of `op` to zero as an identity over the
    /// generator list; `Err` when the remainder is not zero.
    fn identity(&self, op: &DOp, what: &str) -> Result<ModuleIdentity, String> {
        let reduction = self.reduce(op, true)?;
        if !reduction.remainder.is_zero() {
            return Err(format!("{what} does not reduce to zero modulo the module"));
        }
        let generator_quotients = self
            .generators
            .iter()
            .zip(reduction.generator_quotients)
            .filter(|(generator, _)| generator.is_some())
            .map(|(_, quotient)| quotient)
            .collect();
        Ok(ModuleIdentity {
            multiplier_factors: reduction.multiplier_factors,
            recurrence_quotient: reduction.recurrence_quotient,
            generator_quotients,
        })
    }
}

/// The smallest submodule of `M` that contains `rule` modulo `recurrence`
/// and is closed under `S`, with its identities (module documentation).
/// `recurrence` must have the leader `g(n, x) S^order` (one term, free of
/// derivatives).  `Err` names the budget or shape that stopped the search.
pub(super) fn invariant_module(
    rule: &DOp,
    recurrence: &DOp,
    order: usize,
    hints: &[DOp],
    budget: &ModuleBudget,
) -> Result<InvariantModule, String> {
    // The same pair recurs (normalized searches try several dropped-row
    // counts with one rule; discovery certifies a pair more than once), so
    // recent results are reused.  The computation is deterministic, so the
    // cache changes no result.
    let key = CacheKey {
        rule: rule.clone(),
        recurrence: recurrence.clone(),
        order,
        hints: hints.to_vec(),
        budget: *budget,
    };
    if let Some(result) = MODULE_CACHE.lock().ok().and_then(|cache| {
        cache
            .iter()
            .find(|(k, _)| *k == key)
            .map(|(_, r)| r.clone())
    }) {
        return result;
    }
    let result = compute_invariant_module(rule, recurrence, order, hints, budget);
    if let Ok(mut cache) = MODULE_CACHE.lock() {
        if cache.len() >= MODULE_CACHE_SIZE {
            drop(cache.remove(0));
        }
        cache.push((key, result.clone()));
    }
    result
}

/// The inputs of one [`invariant_module`] computation.
#[derive(Clone, Debug, PartialEq, Eq)]
struct CacheKey {
    rule: DOp,
    recurrence: DOp,
    order: usize,
    hints: Vec<DOp>,
    budget: ModuleBudget,
}

/// Number of recent [`invariant_module`] results kept.
const MODULE_CACHE_SIZE: usize = 16;

type CachedModule = (CacheKey, Result<InvariantModule, String>);

static MODULE_CACHE: std::sync::Mutex<Vec<CachedModule>> = std::sync::Mutex::new(Vec::new());

fn compute_invariant_module(
    rule: &DOp,
    recurrence: &DOp,
    order: usize,
    hints: &[DOp],
    budget: &ModuleBudget,
) -> Result<InvariantModule, String> {
    let column = recurrence.column(order);
    let leader = match column.0.iter().next() {
        Some(((_, 0), leader)) if column.term_count() == 1 && order > 0 => leader.clone(),
        _ => {
            return Err(
                "the target rule's leader must be one term g(n, x) S^k free of derivatives".into(),
            )
        }
    };
    let mut reducer = Reducer {
        recurrence,
        order,
        leader,
        generators: vec![None; order],
        budget,
        insertions: 0,
        work: std::cell::Cell::new(0),
        known_factors: Vec::new(),
    };
    if let Some(part) = mixed_part(&reducer.leader) {
        for shift in FACTOR_SHIFTS {
            reducer.known_factors.push(part.shift_index(shift));
        }
    }
    for hint in hints {
        if !hint.is_zero() && hint.max_shift() < order {
            reducer.insert(hint.clone())?;
        }
    }
    reducer.insert(rule.clone())?;
    let mut closed = false;
    for _ in 0..budget.max_rounds {
        let mut changed = false;
        for generator in reducer.generator_list() {
            let reduced = reducer.reduce(&generator.shifted(1), false)?.remainder;
            if !reduced.is_zero() {
                reducer.insert(reduced)?;
                changed = true;
            }
        }
        if !changed {
            closed = true;
            break;
        }
    }
    if !closed {
        return Err(format!(
            "the module is not closed under the shift after {} rounds",
            budget.max_rounds
        ));
    }
    let generators = reducer.generator_list();
    let steps = generators
        .iter()
        .map(|g| reducer.identity(&g.shifted(1), "a shifted generator"))
        .collect::<Result<Vec<_>, _>>()?;
    let rule_identity = reducer.identity(rule, "the rule")?;
    let module = InvariantModule {
        generators,
        steps,
        rule: rule_identity,
    };
    if !module.identities_hold(rule, recurrence, order) {
        return Err("the module identities do not hold".into());
    }
    Ok(module)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::recurrence::implicit::algebra::q;

    fn biv(rows: &[&[i64]]) -> Biv {
        Biv::new(
            rows.iter()
                .map(|row| row.iter().map(|c| q(*c)).collect())
                .collect(),
        )
    }

    fn budget() -> ModuleBudget {
        ModuleBudget {
            max_rounds: 8,
            max_insertions: 32,
            max_reduction_steps: 2_000,
            max_terms: 2_000,
            max_entries: 100_000,
            max_bits: 10_000_000,
            max_work: 10_000_000_000,
        }
    }

    #[test]
    fn binomial_rows_have_a_first_order_contiguity_module() {
        // L: P_(n+2) = 2(1 + x) P_(n+1) - (1 + x)^2 P_n (rows (1 + x)^n
        // from the seeds 1, 1 + x).  E: P_(n+1) - (1 + x) P_n is not a left
        // multiple of L; its module is generated by E itself.
        let mut l = DOp::default();
        l.add_term((2, 0), Biv::one());
        l.add_term((1, 0), biv(&[&[-2, -2]]));
        l.add_term((0, 0), biv(&[&[1, 2, 1]]));
        let mut e = DOp::default();
        e.add_term((1, 0), Biv::one());
        e.add_term((0, 0), biv(&[&[-1, -1]]));
        let module = invariant_module(&e, &l, 2, &[], &budget()).unwrap();
        assert_eq!(module.generators.len(), 1);
        assert!(module.identities_hold(&e, &l, 2));
        // A left multiple of L gives the zero module.
        let multiple = DOp::single(1, 1, biv(&[&[0, 1]])).compose(&l);
        let module = invariant_module(&multiple, &l, 2, &[], &budget()).unwrap();
        assert!(module.generators.is_empty());
        assert!(module.identities_hold(&multiple, &l, 2));
    }
}
