//! All-index equality of two recurrence definitions of one sequence: a
//! defining record `(L_1, first index, seeds)` and an alternative record
//! `(L_2, first index, seeds)` whose seeds are rows of the defining family.
//!
//! [`certify_recurrence_equality`] proves, for every index `n >= first
//! index`, that the rows defined by the two records are equal, or reports
//! why it could not.  Nothing rests on a finite fit or on held-out rows: the
//! proof is an exact identity in the Ore algebra (`ore-algebra`) together
//! with exact row checks at finitely many indices.
//!
//! # The argument
//!
//! Write both rules in forward form at base `n`: `L_i` is
//! `g_i(n) S^(k_i) + (lower shifts, derivatives)`, with `g_i` free of `x`
//! (a left-hand factor `x^e f(n)` is normalized first, as in the theorem
//! checks), applied at every base `n >= b_i = N_i - k_i`, where
//! `N_i = first index + (number of seeds)` is the first row the rule
//! computes.  For a *target* family `s` (rows generated by its own rule `L`)
//! and a *rule* `E`, the claim "`(E s)_n = 0` for every base
//! `n >= b_E`" is proved as follows.
//!
//! 1. **Division.**  Right pseudo-division of `E` by `L`
//!    (`ore_algebra::right_pseudo_division`):
//!    `w(n) E = H o L + R` with `w` a polynomial in `n` only and `R` of
//!    shift below the order of `L`.  Since `(L s)_m = 0` for `m >= b_L`,
//!    `w(n) (E s)_n = (R s)_n` at every base `n >= b_L`.
//! 2. **Remainder.**  If `R = 0` nothing is left.  Otherwise `L` must have
//!    order one, `g(n) s_(n+1) = T(n) s_n`, and `R` must be shift-free;
//!    an invariant row annihilator `A(n)` of the target rows is found as in
//!    the Hadamard-factor lifts: `nu(n, x) A(n + 1) o T(n) = B(n) o A(n)`
//!    exactly, so `A(n) s_n = 0` for every `n >= b_L` once it holds at
//!    `n = b_L` and after every base where `nu(n, .)` vanishes (exact row
//!    checks), because `g(n) != 0` there and `Q[x]` has no zero divisors.
//!    Then `mu(n, x) R = Z o A` (Weyl-algebra right pseudo-division with a
//!    zero remainder) gives `(R s)_n = 0` wherever `mu(n, .) != 0`; the
//!    other bases are checked on rows.
//! 3. **Exceptional bases.**  `(E s)_n = 0` is evaluated exactly on rows at
//!    the integer roots of `w` that are `>= b_L` and at the bases
//!    `b_E <= n < b_L`.
//!
//! Two methods use this claim:
//!
//! - `defining_rows_satisfy_alternative`: the target is the defining family
//!   `P` and the rule is `L_2`.  Then `P` satisfies `L_2` at every base
//!   `n >= b_2`, the alternative seeds are rows of `P` (checked exactly),
//!   and the leader of `L_2` is a nonzero polynomial at every row it
//!   computes, so by induction the alternative rows are the rows of `P`.
//! - `alternative_rows_satisfy_defining`: the target is the alternative
//!   family `Q` and the rule is `L_1`.  Then `Q` satisfies `L_1` at every
//!   base `n >= b_1`, the rows of `Q` before `N_1` equal the defining seeds
//!   (checked exactly), and the leader of `L_1` is a nonzero polynomial at
//!   every row it computes, so `Q = P`.
//!
//! A certified report concludes that the two records define the same rows
//! for every index from the common first index on.  The certificate is
//! replayed by recomputation ([`RecurrenceEqualityCertificate::verify`]).
//!
//! Related: the theorem checks of `parent_theorems` (which prove the
//! alternative family real-rooted), `hadamard_factor` (the invariant row
//! annihilators), and the recurrence-space certificates of `fit::space`
//! (all-index identities for monic lag-only sources).

use super::*;
use crate::recurrence::implicit::algebra::{Biv, DOp};
use crate::recurrence::implicit::{op_text, ImplicitRelation};
use crate::recurrence::lift::hadamard_factor::annihilator::{
    find_invariant_annihilator, step_operator, vanishing_bases,
};
use crate::recurrence::lift::hadamard_factor::certify::right_pseudo_divide;

/// JSON schema tag of [`RecurrenceEqualityCertificate`].
pub const RECURRENCE_EQUALITY_SCHEMA: &str = "polytool.recurrence-equality.v1";

/// Largest number of terms of an operator built while certifying.
const MAX_OPERATOR_TERMS: usize = 4_000;

/// Budget of the invariant row-annihilator search: the remainder's
/// coefficient entries ([`operator_size`]) times one more than its
/// derivative order.
const MAX_REMAINDER_COST: usize = 1_000;

/// The number of rational entries of the coefficients of `op`.
fn operator_size(op: &DOp) -> usize {
    op.0.values()
        .map(|c| c.rows().iter().map(Vec::len).sum::<usize>())
        .sum()
}

/// Largest row index evaluated by an exact row check.
const MAX_CHECKED_ROWS: usize = 256;

/// An all-index equality certificate for two recurrence definitions
/// (module documentation of `recurrence_equality`), schema
/// `polytool.recurrence-equality.v1`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecurrenceEqualityCertificate {
    /// [`RECURRENCE_EQUALITY_SCHEMA`].
    pub schema: String,
    /// The defining record (search metadata is ignored).
    pub defining: RecurrenceJson,
    /// The alternative record: its seeds are rows of the defining family.
    pub alternative: RecurrenceJson,
    /// `certified` (the records define the same rows for every index) or
    /// `not_certified` (no proof found; this is not a disproof unless a
    /// reason names a row that differs).
    pub status: String,
    /// `defining_rows_satisfy_alternative` or
    /// `alternative_rows_satisfy_defining` (module documentation); omitted
    /// when not certified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub method: Option<String>,
    /// The division identity `w(n) E = H o L + R` in words, with `w`, `L`
    /// and `E`; omitted when not certified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub identity: Option<String>,
    /// The invariant row annihilator `A(n)` that kills the remainder, with
    /// its invariance identity; omitted when the remainder is zero.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub row_annihilator: Option<String>,
    /// Bases at which a relation was evaluated exactly on rows (start and
    /// restart bases of the annihilator induction, exceptional bases of the
    /// division), ascending.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub checked_bases: Vec<usize>,
    /// What the certificate establishes.
    pub statement: String,
    /// Why each method failed (empty when certified by the first method).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reasons: Vec<String>,
}

impl RecurrenceEqualityCertificate {
    /// Whether the two records are proved to define the same rows.
    pub fn is_certified(&self) -> bool {
        self.status == "certified"
    }

    /// Replay: recompute the certificate from the two recorded records and
    /// compare.
    ///
    /// # Errors
    ///
    /// [`RecurrenceError::VerificationFailed`] when the certificate differs
    /// from its recomputation or has another schema; errors of the records.
    pub fn verify(&self) -> Result<(), RecurrenceError> {
        if self.schema != RECURRENCE_EQUALITY_SCHEMA {
            return Err(RecurrenceError::VerificationFailed(format!(
                "unsupported schema `{}`",
                self.schema
            )));
        }
        let recomputed = certify_recurrence_equality(&self.defining, &self.alternative)?;
        if &recomputed != self {
            return Err(RecurrenceError::VerificationFailed(
                "the equality certificate differs from its recomputation".into(),
            ));
        }
        Ok(())
    }
}

/// A family ready for the argument: the normalized rule, its forward
/// operator and the bases where it applies.
struct EqualityFamily {
    rule: Recurrence,
    first_index: usize,
    seeds: Vec<Vec<Q>>,
    /// Forward operator, leader `g(n) S^order` free of `x`.
    operator: DOp,
    order: usize,
    /// First base `b = N - order` at which the rule holds.
    start_base: usize,
}

impl EqualityFamily {
    /// The first row the rule computes, `N = first_index + seeds`.
    fn rule_start(&self) -> usize {
        self.first_index + self.seeds.len()
    }

    fn rows(&self, last_index: usize) -> Result<Vec<Vec<Q>>, String> {
        if last_index > self.first_index + MAX_CHECKED_ROWS {
            return Err(format!(
                "an exact check needs row {last_index}, more than {MAX_CHECKED_ROWS} rows after \
                 the first index"
            ));
        }
        let count = (last_index + 1)
            .saturating_sub(self.first_index)
            .max(self.seeds.len());
        self.rule
            .generate_rows_rational(&self.seeds, self.first_index, count)
            .map(|rows| rows.iter().map(|row| vec_poly::trim(row)).collect())
            .map_err(|error| format!("the rows cannot be generated: {error}"))
    }
}

fn prepare_family(record: &RecurrenceJson, name: &str) -> Result<EqualityFamily, String> {
    let (rule, first_index, seeds) = record
        .to_recurrence_parts()
        .map_err(|error| format!("the {name} record: {error}"))?;
    let (rule, _) = rule_with_x_free_left_hand_factor(&rule)
        .map_err(|error| format!("the {name} rule: {error}"))?;
    if rule.inhomogeneous.as_ref().is_some_and(|g| !g.is_zero()) {
        return Err(format!("the {name} rule has an inhomogeneous term"));
    }
    let (relation, order) = ImplicitRelation::from_recurrence(&rule)
        .map_err(|error| format!("the {name} rule: {error}"))?;
    if order == 0 || seeds.len() < order {
        return Err(format!(
            "the {name} rule needs a positive lag and a seed for every lag"
        ));
    }
    let operator = relation.op();
    let column = operator.column(order);
    if column.term_count() != 1
        || !column
            .0
            .get(&(0, 0))
            .is_some_and(|leader| leader.is_variable_free())
    {
        return Err(format!(
            "the {name} rule's left-hand factor depends on x (after the normalization of x^e f(n))"
        ));
    }
    let start_base = first_index + seeds.len() - order;
    let leader = rule
        .denominator
        .as_ref()
        .map(Biv::from_bivar)
        .unwrap_or_else(Biv::one);
    let zeros = vanishing_bases(&leader, first_index + seeds.len());
    if leader.is_zero() || !zeros.is_empty() {
        return Err(format!(
            "the {name} rule's left-hand factor vanishes at n = {:?}, so the rule does not \
             determine those rows",
            zeros
        ));
    }
    Ok(EqualityFamily {
        rule,
        first_index,
        seeds,
        operator,
        order,
        start_base,
    })
}

/// The proof that `(rule s)_n = 0` for every base `n >= rule.start_base`,
/// with `s` the rows of `target`.
struct SatisfiedRule {
    identity: String,
    row_annihilator: Option<String>,
    checked_bases: Vec<usize>,
}

/// Evaluate `(op s)_n` exactly at each base; `Err` names the first base
/// where it is not zero.
fn check_bases(
    op: &DOp,
    target: &EqualityFamily,
    bases: &[usize],
    what: &str,
) -> Result<(), String> {
    let Some(last) = bases.iter().max() else {
        return Ok(());
    };
    let rows = target.rows(last + op.max_shift())?;
    for &base in bases {
        let value = op
            .apply(&rows, target.first_index, base)
            .ok_or_else(|| format!("{what}: the rows do not cover base n = {base}"))?;
        if !value.iter().all(Zero::is_zero) {
            return Err(format!("{what} fails at base n = {base} (exact)"));
        }
    }
    Ok(())
}

/// Step 1 to 3 of the module documentation.
fn rows_satisfy_rule(
    target: &EqualityFamily,
    rule: &EqualityFamily,
) -> Result<SatisfiedRule, String> {
    let e = &rule.operator;
    let l = &target.operator;
    let top = e.max_shift().max(l.max_shift());
    let division = ore_algebra::right_pseudo_division(e, l, top)
        .ok_or("the right division by the target rule is not defined")?;
    let assembled = division.quotient.compose(l).add(&division.remainder);
    if e.left_multiply(&division.multiplier) != assembled {
        return Err("the division identity does not hold".into());
    }
    let w = &division.multiplier;
    let remainder = &division.remainder;
    let from = target.start_base;
    let mut checked = BTreeSet::new();
    let mut annihilator_text = None;
    if !remainder.is_zero() {
        if target.order != 1 || remainder.max_shift() != 0 {
            return Err(format!(
                "the division leaves a nonzero remainder {} and the target rule is not first \
                 order with a shift-free remainder",
                op_text(remainder, "P")
            ));
        }
        let step = step_operator(l).ok_or("the target rule is not first order")?;
        // The Weyl-algebra gcd loop grows coefficients quickly: a
        // deterministic size budget keeps the search bounded.
        let size = operator_size(remainder);
        let cost = size * (remainder.max_derivative() + 1);
        if cost > MAX_REMAINDER_COST {
            return Err(format!(
                "the remainder has {size} coefficient entries and derivative order {}, beyond \
                 the row-annihilator budget (entries times order plus one at most \
                 {MAX_REMAINDER_COST})",
                remainder.max_derivative()
            ));
        }
        let invariant = find_invariant_annihilator(remainder, &step, MAX_OPERATOR_TERMS)
            .map_err(|error| format!("the row-annihilator search failed: {error}"))?
            .ok_or_else(|| {
                format!(
                    "no invariant row annihilator kills the remainder {}",
                    op_text(remainder, "P")
                )
            })?;
        let a = &invariant.annihilator;
        let (mu, _, rest) = right_pseudo_divide(remainder, a, MAX_OPERATOR_TERMS)
            .map_err(|error| format!("the remainder division failed: {error}"))?;
        if !rest.is_zero() || mu.is_zero() {
            return Err(
                "the remainder is not a left multiple of the invariant row annihilator".into(),
            );
        }
        // A(n) s_n = 0 at the start base and after every zero of nu.
        let restart = vanishing_bases(&invariant.step_multiplier, from);
        let annihilated: Vec<usize> = std::iter::once(from)
            .chain(restart.iter().map(|base| base + 1))
            .collect();
        let rows = target.rows(annihilated.iter().copied().max().unwrap_or(from))?;
        for &index in &annihilated {
            let row = &rows[index - target.first_index];
            if !a.apply_row(row, index).iter().all(Zero::is_zero) {
                return Err(format!(
                    "the row annihilator does not kill row {index} (exact)"
                ));
            }
            checked.insert(index);
        }
        // R s_n = 0 where mu(n, .) vanishes.
        let mu_zeros = vanishing_bases(&mu, from);
        check_bases(remainder, target, &mu_zeros, "the remainder")?;
        checked.extend(mu_zeros);
        annihilator_text = Some(format!(
            "A(n) = {} kills every row from n = {from} on: nu(n, x) A(n + 1) o T(n) = B(n) o \
             A(n) with T(n) = {} (exact), A checked on rows at n = {}{}; mu(n, x) R = Z o A \
             (exact)",
            op_text(a, "P").trim_end_matches(" = 0"),
            op_text(&step, "P").trim_end_matches(" = 0"),
            from,
            if restart.is_empty() {
                String::new()
            } else {
                format!(" and after the restart bases {restart:?}")
            }
        ));
    }
    let mut exceptional: Vec<usize> = vanishing_bases(w, from);
    exceptional.extend(rule.start_base..from);
    check_bases(e, target, &exceptional, "the rule")?;
    checked.extend(exceptional);
    Ok(SatisfiedRule {
        identity: format!(
            "w(n) E = H o L + R with E: {}, L: {}, w(n) = {}{}",
            op_text(e, "P"),
            op_text(l, "P"),
            format_index_polynomial(&w.variable_coefficient(0), "n"),
            if remainder.is_zero() {
                ", R = 0".to_string()
            } else {
                format!(", R: {}", op_text(remainder, "P"))
            }
        ),
        row_annihilator: annihilator_text,
        checked_bases: checked.into_iter().collect(),
    })
}

/// Prove that `alternative` and `defining` define the same rows for every
/// index (module documentation): the result is `certified` with the method,
/// or `not_certified` with the reasons.
///
/// Both records must have the same first index, and the alternative seeds
/// must be rows of the defining family (checked exactly; a differing row
/// gives `not_certified` naming that row).
///
/// # Errors
///
/// Malformed records ([`RecurrenceJson::to_recurrence_parts`]).
pub fn certify_recurrence_equality(
    defining: &RecurrenceJson,
    alternative: &RecurrenceJson,
) -> Result<RecurrenceEqualityCertificate, RecurrenceError> {
    defining.to_recurrence_parts()?;
    alternative.to_recurrence_parts()?;
    let mut certificate = RecurrenceEqualityCertificate {
        schema: RECURRENCE_EQUALITY_SCHEMA.into(),
        defining: defining.clone(),
        alternative: alternative.clone(),
        status: "not_certified".into(),
        method: None,
        identity: None,
        row_annihilator: None,
        checked_bases: Vec::new(),
        statement: String::new(),
        reasons: Vec::new(),
    };
    let families = prepare_family(defining, "defining")
        .and_then(|p| prepare_family(alternative, "alternative").map(|q| (p, q)));
    let (p, q) = match families {
        Ok(families) => families,
        Err(reason) => {
            certificate.statement = "not certified: the records are not supported".into();
            certificate.reasons.push(reason);
            return Ok(certificate);
        }
    };
    if p.first_index != q.first_index {
        certificate.statement = "not certified: the first indices differ".into();
        certificate.reasons.push(format!(
            "the defining record starts at {} and the alternative at {}",
            p.first_index, q.first_index
        ));
        return Ok(certificate);
    }
    let first = p.first_index;
    let last = p.rule_start().max(q.rule_start()) - 1;
    let consistency = p.rows(last).and_then(|p_rows| {
        let q_rows = q.rows(last)?;
        match p_rows
            .iter()
            .zip(&q_rows)
            .position(|(a, b)| vec_poly::trim(a) != vec_poly::trim(b))
        {
            Some(offset) => Err(format!(
                "row {} of the alternative record differs from the defining row (exact)",
                first + offset
            )),
            None => Ok(()),
        }
    });
    if let Err(reason) = consistency {
        certificate.statement = "not certified: the seed rows disagree".into();
        certificate.reasons.push(reason);
        return Ok(certificate);
    }
    for (method, target, rule) in [
        ("defining_rows_satisfy_alternative", &p, &q),
        ("alternative_rows_satisfy_defining", &q, &p),
    ] {
        match rows_satisfy_rule(target, rule) {
            Ok(proof) => {
                certificate.status = "certified".into();
                certificate.method = Some(method.into());
                certificate.identity = Some(proof.identity);
                certificate.row_annihilator = proof.row_annihilator;
                certificate.checked_bases = proof.checked_bases;
                let (holder, other) = if method == "defining_rows_satisfy_alternative" {
                    ("defining", "alternative")
                } else {
                    ("alternative", "defining")
                };
                certificate.statement = format!(
                    "the rows of the {holder} record satisfy the {other} rule at every base \
                     n >= {}; the rows P_{first}, ..., P_{last} agree (exact) and both \
                     left-hand factors are nonzero wherever a rule computes a row, so the two \
                     records define the same rows P_n for every n >= {first} (all-index \
                     identity, no finite fit)",
                    rule.start_base
                );
                return Ok(certificate);
            }
            Err(reason) => certificate.reasons.push(format!("{method}: {reason}")),
        }
    }
    certificate.statement =
        "not certified: neither rule was shown to hold on the other family's rows (this is \
         not a disproof)"
            .into();
    Ok(certificate)
}
