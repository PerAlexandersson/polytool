//! All-index equality of two recurrence definitions of one sequence: a
//! defining record `(L_1, first index, seeds)` and an alternative record
//! `(L_2, first index, seeds)` whose seeds are rows of the defining family.
//!
//! [`certify_recurrence_equality`] proves, for every index `n >= first
//! index`, that the rows defined by the two records are equal, or reports
//! why it could not.  Nothing rests on a finite fit or on held-out rows: the
//! proof is an exact identity in the Ore algebra (`ore-algebra`) together
//! with exact row checks at finitely many indices.
//!
//! # The argument
//!
//! Write both rules in forward form at base `n`: `L_i` is
//! `g_i(n, x) S^(k_i) + (lower shifts, derivatives)` (a left-hand factor
//! `x^e f(n)` is normalized to `f(n)` first, as in the theorem checks; the
//! leader `g_i` may depend on `x` and must not be the zero polynomial at a
//! row the rule computes), applied at every base `n >= b_i = N_i - k_i`, where
//! `N_i = first index + (number of seeds)` is the first row the rule
//! computes.  For a *target* family `s` (rows generated by its own rule `L`)
//! and a *rule* `E`, the claim "`(E s)_n = 0` for every base
//! `n >= b_E`" is proved as follows.
//!
//! The *division* method (steps 1 to 3) needs a leader of `L` free of `x`;
//! the *invariant-module* method (below) covers every pair and runs when
//! division fails.
//!
//! 1. **Division.**  Right pseudo-division of `E` by `L`
//!    (`ore_algebra::right_pseudo_division`):
//!    `w(n) E = H o L + R` with `w` a polynomial in `n` only and `R` of
//!    shift below the order of `L`.  Since `(L s)_m = 0` for `m >= b_L`,
//!    `w(n) (E s)_n = (R s)_n` at every base `n >= b_L`.
//! 2. **Remainder.**  If `R = 0` nothing is left.  Otherwise `L` must have
//!    order one, `g(n) s_(n+1) = T(n) s_n`, and `R` must be shift-free;
//!    an invariant row annihilator `A(n)` of the target rows is found as in
//!    the Hadamard-factor lifts: `nu(n, x) A(n + 1) o T(n) = B(n) o A(n)`
//!    exactly, so `A(n) s_n = 0` for every `n >= b_L` once it holds at
//!    `n = b_L` and after every base where `nu(n, .)` vanishes (exact row
//!    checks), because `g(n) != 0` there and `Q[x]` has no zero divisors.
//!    Then `mu(n, x) R = Z o A` (Weyl-algebra right pseudo-division with a
//!    zero remainder) gives `(R s)_n = 0` wherever `mu(n, .) != 0`; the
//!    other bases are checked on rows.
//! 3. **Exceptional bases.**  `(E s)_n = 0` is evaluated exactly on rows at
//!    the integer roots of `w` that are `>= b_L` and at the bases
//!    `b_E <= n < b_L`.
//!
//! # Invariant module
//!
//! When `L` does not divide `E` with a remainder that steps 2 and 3 kill,
//! the claim is proved in the left module `M = K<D>^k`, `K = Q(n, x)`, of
//! operators of shift below the order `k` of `L` modulo the left ideal of
//! `L` (the leader `g(n, x)` may depend on `x`; it must be free of `D`).
//! The rows of the target annihilate a submodule of `M`; the remainder of
//! `E` and the shifts `S o G` of everything found, reduced modulo `L`, are
//! inserted into an echelon (Hermite) form over `K<D>` until it is closed
//! under `S` (module `invariant_module`).  The result is a list of
//! generators `G_1, ..., G_r` (shift below `k`, derivatives anywhere,
//! including the leading row: `(2 x (x + 1) D - n (3 x + 1)) P_(n+1) + ...`
//! is a typical generator) with exact polynomial identities
//!
//! ```text
//! W_i(n, x) (S o G_i) = Y_i o L + sum_l Z_(i,l) o G_l,   Z_(i,l) shift-free,
//! W(n, x) E = Y o L + sum_l Z_l o G_l.
//! ```
//!
//! Applied to the target rows at a base `m >= b_L` where every `(G_l s)_m`
//! vanishes, the first identity gives `W_i(m, x) (G_i s)_(m+1) = 0`, so
//! `(G_i s)_(m+1) = 0` unless `W_i(m, .)` is the zero polynomial (`Q[x]`
//! has no zero divisors).  So every generator kills the rows at every base
//! from a start base `m_0 >= max(b_L, b_E)` once it does at `m_0` and at
//! `m + 1` for every base `m >= m_0` where a factor of some `W_i` vanishes
//! identically (exact row checks; `m_0` is the first of at most
//! `MAX_MODULE_START_DELAY + 1` bases where every generator kills the
//! rows).  The second identity then gives `(E s)_n = 0` at every base
//! `n >= m_0` where `W(n, .)` is not zero; `E` is evaluated exactly on rows
//! at the other bases `n >= b_E` (the integer roots of factors of `W` and
//! `b_E <= n < m_0`).
//!
//! The module is seeded with relations of the target rows fitted exactly
//! to rows (a first-order runnable rule and a row annihilator,
//! `ore_algebra::fit_rows_annihilator`): they are typically the small
//! generators that the Euclidean steps reach only through large
//! intermediate operators.  A fitted relation is not trusted: it becomes a
//! generator, and the induction above proves it with the others (a wrong
//! fit fails the start check).  The module search runs within
//! deterministic budgets (terms, coefficient entries and bit lengths, and a
//! work bound) and, when the seeded search fails, once more without seeds.
//! Both directions are tried, after both directions of the division
//! method.  The certificate records the generators and the checked bases;
//! a replay recomputes everything.
//!
//! Two methods use this claim:
//!
//! - `defining_rows_satisfy_alternative`: the target is the defining family
//!   `P` and the rule is `L_2`.  Then `P` satisfies `L_2` at every base
//!   `n >= b_2`, the alternative seeds are rows of `P` (checked exactly),
//!   and the leader of `L_2` is a nonzero polynomial at every row it
//!   computes, so by induction the alternative rows are the rows of `P`.
//! - `alternative_rows_satisfy_defining`: the target is the alternative
//!   family `Q` and the rule is `L_1`.  Then `Q` satisfies `L_1` at every
//!   base `n >= b_1`, the rows of `Q` before `N_1` equal the defining seeds
//!   (checked exactly), and the leader of `L_1` is a nonzero polynomial at
//!   every row it computes, so `Q = P`.
//!
//! A certified report concludes that the two records define the same rows
//! for every index from the common first index on.  The certificate is
//! replayed by recomputation ([`RecurrenceEqualityCertificate::verify`]).
//!
//! Related: the theorem checks of `parent_theorems` (which prove the
//! alternative family real-rooted), `hadamard_factor` (the invariant row
//! annihilators), `ore_algebra::find_annihilator_system` (jointly
//! invariant annihilator systems of a fixed shape), and the
//! recurrence-space certificates of `fit::space` (all-index identities for
//! monic lag-only sources).

