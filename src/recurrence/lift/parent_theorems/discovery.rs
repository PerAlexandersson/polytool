/// The first index of the tail (module documentation, step 2) and the
/// reason: the index after the last row among the seeds and the next
/// `maximum_start_delay` rows that is zero or not real-rooted, when every
/// later row up to `GENERATED_ROWS` rows past the seeds is nonzero and
/// real-rooted.  `None` when there is no such row, or the rows cannot be
/// generated.
fn tail_start(
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
) -> Option<(usize, String)> {
    let count = seeds.len() + GENERATED_ROWS;
    let rows = rule
        .generate_rows_rational(seeds, first_index, count)
        .ok()?;
    let bad = |row: &Vec<Q>| {
        let row = vec_poly::trim(row);
        vec_poly::is_zero(&row) || !is_real_rooted_rational(&row)
    };
    let window = (seeds.len() + options.maximum_start_delay).min(rows.len());
    let last_bad = (0..window).rev().find(|&offset| bad(&rows[offset]))?;
    if rows[last_bad + 1..].iter().any(bad) || last_bad + 1 >= rows.len() {
        return None;
    }
    let index = first_index + last_bad;
    let what = if vec_poly::is_zero(&vec_poly::trim(&rows[last_bad])) {
        "zero"
    } else {
        "not real-rooted"
    };
    Some((
        index + 1,
        format!(
            "P_{index} is {what} (exact), so no theorem applies from the first index; every \
             row P_n with {} <= n <= {} is nonzero and real-rooted (exact)",
            index + 1,
            first_index + rows.len() - 1
        ),
    ))
}

/// The tail record starting at `tail_first`: the rule, and as seeds the
/// family's rows from `tail_first` up to the rule start of the supplied
/// record and at least one row per lag (generated exactly).
fn tail_record(
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    tail_first: usize,
) -> Result<RecurrenceJson, RecurrenceError> {
    let rule_start = first_index + seeds.len();
    let count = rule_start
        .saturating_sub(tail_first)
        .max(rule.max_offset())
        .max(1);
    let last = tail_first + count;
    let rows = rule
        .generate_rows_rational(seeds, first_index, (last - first_index).max(seeds.len()))
        .map_err(|error| {
            RecurrenceError::InvalidInput(format!("the tail rows cannot be generated: {error}"))
        })?;
    let tail_seeds: Vec<Vec<Q>> = rows[tail_first - first_index..last - first_index].to_vec();
    Ok(RecurrenceJson::from_recurrence_rational(
        rule,
        tail_first,
        &normalized_seed_rows(rule, tail_first, &tail_seeds)?,
        None,
    ))
}

