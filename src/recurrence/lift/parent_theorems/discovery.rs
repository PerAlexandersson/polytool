/// The finder passes of the stage: first-order rules with a derivative and
/// a left-hand factor `f(n)` (the Liu--Wang and Ma--Wang shapes), then rules
/// of lag at most two without a left-hand factor.
fn finder_passes() -> [AdaptiveSearchOptions; 2] {
    let first_order = AdaptiveSearchOptions {
        max_rec_len: 1,
        max_diff_deg: 2,
        try_denominator: true,
        max_denom_var_deg: 0,
        max_denom_idx_deg: 2,
        ..AdaptiveSearchOptions::default()
    };
    let lag_two = AdaptiveSearchOptions {
        max_rec_len: 2,
        max_diff_deg: 1,
        ..AdaptiveSearchOptions::default()
    };
    [first_order, lag_two]
}

fn alternative_search(
    base: &RecurrenceJson,
    options: &RealRootednessTheoremOptions,
    alternative_options: &AlternativeRepresentationOptions,
) -> Result<AlternativeRepresentationSearch, RecurrenceError> {
    let mut search = AlternativeRepresentationSearch {
        options: alternative_options.clone(),
        configurations_considered: 0,
        fitted_rules: 0,
        alternatives: Vec::new(),
    };
    let (rule, first_index, seeds) = base.to_recurrence_parts()?;
    let count = alternative_options.rows.max(seeds.len() + 4);
    let Ok(rows) = rule.generate_rows_rational(&seeds, first_index, count) else {
        return Ok(search);
    };
    let defining =
        RecurrenceJson::from_recurrence_rational(&rule, first_index, &[], None).recurrence;
    let mut candidates: Vec<(RepresentationComplexity, RecurrenceJson)> = Vec::new();
    for pass in finder_passes() {
        let menu = match find_recurrence_representations_rational(
            &rows,
            &pass,
            AdaptiveSearchBudget {
                max_candidates: Some(alternative_options.max_candidates),
                max_work: None,
            },
        )
        .and_then(|menu| menu.reindexed(first_index))
        {
            Ok(menu) => menu,
            Err(_) => continue,
        };
        search.configurations_considered += menu.configurations_considered;
        for representation in menu.representations {
            let Ok((alternative, first, alternative_seeds)) =
                representation.recurrence_json.to_recurrence_parts()
            else {
                continue;
            };
            let (alternative, removed) = without_common_index_factor(&alternative);
            // Rows where the removed factor vanishes were left undetermined by
            // the fitted rule: they stay seeds.
            let seed_count = crate::recurrence::implicit::algebra::roots_in_domain(
                &removed,
                first + alternative_seeds.len(),
                None,
            )
            .into_iter()
            .map(|root| root + 1 - first)
            .fold(alternative_seeds.len(), usize::max);
            let Some(alternative_seeds) = rows.get(..seed_count).map(<[Vec<Q>]>::to_vec) else {
                continue;
            };
            let data =
                RecurrenceJson::from_recurrence_rational(&alternative, first, &[], None).recurrence;
            if data == defining
                || candidates.iter().any(|(_, known)| {
                    known.to_recurrence_parts().ok().map(|(r, f, _)| {
                        RecurrenceJson::from_recurrence_rational(&r, f, &[], None).recurrence
                    }) == Some(data.clone())
                })
            {
                continue;
            }
            let record = RecurrenceJson::from_recurrence_rational(
                &alternative,
                first,
                &alternative_seeds,
                None,
            );
            candidates.push((representation.complexity, record));
        }
    }
    search.fitted_rules = candidates.len();
    candidates.sort_by_key(|(complexity, _)| {
        (
            complexity.rec_len,
            complexity.diff_deg,
            complexity.nonzero_coefficients,
        )
    });
    for (_, candidate) in candidates
        .into_iter()
        .take(alternative_options.max_alternatives)
    {
        // Equality is transitive: a candidate not certified against the
        // family is compared with the alternatives certified before it.
        let mut equality = certify_recurrence_equality(base, &candidate)?;
        let certified: Vec<RecurrenceJson> = search
            .alternatives
            .iter()
            .filter(|a| a.equality.is_certified())
            .map(|a| a.equality.alternative.clone())
            .collect();
        for known in &certified {
            if equality.is_certified() {
                break;
            }
            let chained = certify_recurrence_equality(known, &candidate)?;
            if chained.is_certified() {
                equality = chained;
            }
        }
        let attempts = if equality.is_certified() {
            let (alternative, first, alternative_seeds) = candidate.to_recurrence_parts()?;
            // A rule the theorem checks cannot run on is not recorded.
            let checked =
                validate_discovery_input(&alternative, first, &alternative_seeds, options)
                    .and_then(|()| run_theorems(&alternative, first, &alternative_seeds, options));
            match checked {
                Ok(attempts) => attempts,
                Err(_) => continue,
            }
        } else {
            Vec::new()
        };
        let proved = equality.is_certified() && attempts.iter().any(|a| a.is_proved());
        search.alternatives.push(AlternativeRepresentationProof {
            equality,
            attempts,
            proved,
        });
        if proved {
            break;
        }
    }
    Ok(search)
}

/// The rule with the common factor `c(n)` of its left-hand factor and of
/// every right-hand coefficient divided out (the finder does not cancel
/// it), and `c` (ascending in `n`; `[1]` when nothing is removed).  The result is only a candidate: where `c(n) = 0` the supplied rule
/// leaves the row undetermined and the reduced rule determines it, so the
/// equality certificate decides whether it defines the family's rows.
fn without_common_index_factor(rule: &Recurrence) -> (Recurrence, Vec<Q>) {
    use crate::recurrence::implicit::algebra::{content_and_primitive, Biv};
    if rule.inhomogeneous.is_some() {
        return (rule.clone(), vec![Q::one()]);
    }
    let leader = rule
        .denominator
        .as_ref()
        .map(Biv::from_bivar)
        .unwrap_or_else(Biv::one);
    let mut content = crate::Polynomial::new(content_and_primitive(&leader).0);
    for term in &rule.terms {
        let (term_content, _) = content_and_primitive(&Biv::from_bivar(&term.coeff));
        content = content.gcd(&crate::Polynomial::new(term_content));
    }
    if content.degree().unwrap_or(0) == 0 {
        return (rule.clone(), vec![Q::one()]);
    }
    let divide = |p: &BivarPoly| -> BivarPoly {
        let p = Biv::from_bivar(p);
        let width = p.variable_degree().map_or(0, |d| d + 1);
        let columns: Vec<Vec<Q>> = (0..width)
            .map(|j| {
                let (quotient, _) =
                    crate::Polynomial::new(p.variable_coefficient(j)).div_rem(&content);
                vec_poly::trim(quotient.coeffs())
            })
            .collect();
        let rows = (0..columns.iter().map(Vec::len).max().unwrap_or(0))
            .map(|i| {
                columns
                    .iter()
                    .map(|column| column.get(i).cloned().unwrap_or_else(Q::zero))
                    .collect()
            })
            .collect();
        BivarPoly::from_coefficients_normalized(rows)
    };
    let denominator = divide(&leader.to_bivar());
    let monic =
        denominator.coeffs.len() == 1 && vec_poly::trim(&denominator.coeffs[0]) == vec![Q::one()];
    let reduced = Recurrence {
        terms: rule
            .terms
            .iter()
            .map(|term| RecurrenceTerm {
                coeff: divide(&term.coeff),
                ..term.clone()
            })
            .collect(),
        denominator: (!monic).then_some(denominator),
        inhomogeneous: None,
    };
    (reduced, content.coeffs().to_vec())
}
