//! General recurrence proof discovery. No catalogue, sequence IDs or attestations.
//!
//! [`discover_recurrence_proofs`] runs, in this order:
//!
//! 1. every general theorem of `parent_theorems` on the supplied record, in
//!    the order of the parent cascade ([`DISCOVERY_THEOREMS`]);
//! 2. **tail**: when no theorem proves the record and one of its first rows
//!    (the seeds and the rows of the induction-start window) is zero or not
//!    real-rooted, the same theorems on the *tail* record that starts after
//!    the last such row ([`RecurrenceProofTail`]); its rows are the
//!    family's rows (the new seeds are generated by the rule), so a proof
//!    of the tail is the statement "every row from that index on is
//!    real-rooted";
//! 3. **alternative representations**: when neither proves the family, the
//!    representation menu of the recurrence finder on generated rows
//!    (bounded passes, [`AlternativeRepresentationOptions`]); each fitted
//!    rule is only a candidate until [`certify_recurrence_equality`] proves
//!    that it defines the same rows for every index, and then the theorems
//!    run on it ([`AlternativeRepresentationProof`]).
//!
//! A rule with an inhomogeneous term is matched by no theorem: the report
//! says so with the status `not_applicable` and
//! [`RecurrenceProofDiscoveryReport::not_applicable_reason`].
//!
//! # Replay
//!
//! [`RecurrenceProofDiscoveryReport::verify`] checks a saved report's claims
//! rather than byte equality with a recomputation.  The search is rerun on
//! the recorded record and options; the recorded attempts must appear, in
//! order, among the recomputed attempts (a subsequence), each equal to its
//! recomputed attempt or replaying on its own (an earlier version of the
//! check), or proving nothing where the current check proves (superseded);
//! the six theorems of the first schema version must be recorded.  The tail
//! record is re-derived from the supplied record, every alternative replays
//! its equality certificate and its attempts, and the summary fields
//! (status, first proved index, triviality, statement) must follow from the
//! recorded attempts alone, so a report never claims more than they prove.
//! A recomputation that tries or proves more is fine: reports saved before
//! a theorem was added keep replaying.

use super::recurrence_equality::{certify_recurrence_equality, RecurrenceEqualityCertificate};
use super::*;
use crate::recurrence::{AdaptiveSearchBudget, AdaptiveSearchOptions};

/// Schema for a replayable general recurrence proof search.
pub const RECURRENCE_PROOF_DISCOVERY_SCHEMA: &str = "polytool.recurrence-proof-discovery.v1";

/// The theorems of the discovery search, in the order of the parent cascade
/// (`prove_parent_real_rootedness`).
pub const DISCOVERY_THEOREMS: [RealRootednessTheorem; 8] = [
    RealRootednessTheorem::ProductRecurrence,
    RealRootednessTheorem::ThreeTermRecurrence,
    RealRootednessTheorem::LiuWang,
    RealRootednessTheorem::LiuWangDerivativeLag,
    RealRootednessTheorem::MaWangInterval,
    RealRootednessTheorem::LiuWangThreeTerm,
    RealRootednessTheorem::IteratedPreserver,
    RealRootednessTheorem::HypergeometricRow,
];

/// The RealRooted row routes tried after [`DISCOVERY_THEOREMS`]; their
/// attempts are recorded only when the rule has their form.
pub const ROW_ROUTE_THEOREMS: [RealRootednessTheorem; 2] = [
    RealRootednessTheorem::VariableDelay,
    RealRootednessTheorem::ResidueClassSubsequences,
];

/// The theorems of the first version of the schema; every report records
/// an attempt of each.
const FIRST_VERSION_THEOREMS: usize = 6;

/// The statement of a report of the first version of the schema (and the
/// first sentence of every later statement).
const FIRST_VERSION_STATEMENT: &str = "Each proved attempt establishes its conclusion for the \
     recurrence-defined sequence. Applying it to an independently defined sequence requires an \
     all-index recurrence identity and the stated seeds; finite fitting or held-out checks do \
     not establish that identity. No Lean replay was attempted.";

/// Bounds of the alternative-representation stage of
/// [`discover_recurrence_proofs_with_options`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AlternativeRepresentationOptions {
    /// Candidate configurations inspected by each pass of the recurrence
    /// finder (deterministic count; `0` disables the stage).
    pub max_candidates: usize,
    /// Largest number of fitted rules for which an equality certificate is
    /// attempted.
    pub max_alternatives: usize,
    /// Number of exact rows generated for the finder.
    pub rows: usize,
}

impl Default for AlternativeRepresentationOptions {
    fn default() -> Self {
        Self {
            max_candidates: 300,
            max_alternatives: 4,
            rows: 24,
        }
    }
}

/// The tail of a family whose first rows are not all real-rooted (module
/// documentation, step 2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecurrenceProofTail {
    /// The first index of the tail: the index after the last scanned row
    /// that is zero or not real-rooted.
    pub first_index: usize,
    /// Which row is zero or not real-rooted (exact).
    pub reason: String,
    /// The tail record: the same rule, first index [`Self::first_index`],
    /// seeds that are rows of the supplied family (generated exactly where
    /// needed); the rule computes the same rows as in the supplied record.
    pub recurrence: RecurrenceJson,
    /// Every theorem attempt on the tail record.
    pub attempts: Vec<RealRootednessTheoremReport>,
}

/// One alternative rule of the family (module documentation, step 3).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AlternativeRepresentationProof {
    /// The all-index equality of the alternative record
    /// (`equality.alternative`) with the family; the theorems run only when
    /// it is certified.
    pub equality: RecurrenceEqualityCertificate,
    /// Every theorem attempt on the alternative record (empty when the
    /// equality is not certified).
    pub attempts: Vec<RealRootednessTheoremReport>,
    /// Whether the equality is certified and some attempt is proved.
    pub proved: bool,
}

/// The alternative-representation stage (module documentation, step 3).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AlternativeRepresentationSearch {
    /// The bounds used.
    pub options: AlternativeRepresentationOptions,
    /// Candidate configurations inspected by the finder (all passes).
    pub configurations_considered: usize,
    /// Distinct fitted rules other than the defining rule (finite fits,
    /// not evidence of anything until certified).
    pub fitted_rules: usize,
    /// The examined alternatives, in the order tried; the search stops at
    /// the first proved one.
    pub alternatives: Vec<AlternativeRepresentationProof>,
}

/// The summary of a proof that leaves residue classes of zero rows
/// ([`RecurrenceProofDiscoveryReport::real_rooted_outside_zero_residue_classes`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RealRootedOutsideZeroResidueClasses {
    /// The first index `N` of the statement (the conclusion's first index).
    pub from_index: usize,
    /// The zero classes: every row `P_n`, `n >= from_index`, whose index
    /// lies in them is zero; every other row `P_n`, `n >= from_index`, is
    /// nonzero and real-rooted.
    pub zero_residue_classes: ZeroResidueClasses,
}

/// Complete results of the general recurrence theorem checks.
///
/// Every successful attempt proves its stated conclusion for the sequence
/// defined by `recurrence`. A fitted recurrence still needs an all-index
/// identity for any independently defined sequence. Reports are Rust exact
/// certificates; `lean_replay` never claims they were elaborated in Lean.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecurrenceProofDiscoveryReport {
    /// [`RECURRENCE_PROOF_DISCOVERY_SCHEMA`].
    pub schema: String,
    /// Defining recurrence and seeds, including untrusted search metadata.
    pub recurrence: RecurrenceJson,
    /// Largest induction-start delay attempted.
    pub maximum_start_delay: usize,
    /// Optional requested root region (finite ends interpreted as open).
    pub requested_root_region: Option<RootInterval>,
    /// `proved` if at least one general theorem succeeded (on the record,
    /// its tail or a certified alternative); `not_applicable` when the rule
    /// has a form no theorem matches (an inhomogeneous term, see
    /// `not_applicable_reason`); `not_proved` otherwise.  Neither of the
    /// latter disproves real-rootedness.
    pub status: String,
    /// What is, and is not, established by a successful search.
    pub statement: String,
    /// Every theorem attempt on the supplied record, including failed and
    /// unresolved hypotheses, in the order of [`DISCOVERY_THEOREMS`].
    pub attempts: Vec<RealRootednessTheoremReport>,
    /// Whether the supplied (not fitted) recurrence is in the product seed
    /// class `B(n) P_n = A(x,n) P_(n-k)` and the product attempt proved it:
    /// the sequence is *trivially* real-rooted.  Always false for a record
    /// carrying search metadata, since a fit does not establish the
    /// recurrence.
    #[serde(default)]
    pub trivially_real_rooted: bool,
    /// Always `not_attempted`: exact Rust replay is separate from Lean replay.
    pub lean_replay: String,
    /// The smallest index `N` such that a proved attempt shows every row
    /// `P_n`, `n >= N`, nonzero and real-rooted (the record's first index
    /// unless the proof is of a tail or rows are zero); omitted when not
    /// proved, and when the only proofs leave infinitely many zero rows
    /// (then [`Self::real_rooted_outside_zero_residue_classes`] is set).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub real_rooted_from_index: Option<usize>,
    /// For a family proved only up to whole residue classes of zero rows
    /// (a residue-class proof with zero classes,
    /// [`RealRootednessTheoremConclusion::zero_residue_classes`]): the
    /// rows `P_n`, `n >= from_index`, in the zero classes are zero and every
    /// other row `P_n`, `n >= from_index`, is nonzero and real-rooted.  Set
    /// exactly when the status is `proved` and `real_rooted_from_index` is
    /// omitted; omitted otherwise.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub real_rooted_outside_zero_residue_classes: Option<RealRootedOutsideZeroResidueClasses>,
    /// Why no theorem applies, for the status `not_applicable`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub not_applicable_reason: Option<String>,
    /// The tail attempts (module documentation, step 2); omitted when not
    /// tried.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tail: Option<RecurrenceProofTail>,
    /// The alternative-representation stage (module documentation, step
    /// 3); omitted when not run.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub alternative_representations: Option<AlternativeRepresentationSearch>,
}

/// Try all supported general theorem families, independently of sequence names.
///
/// Tries product induction, Favard/three-term, Liu--Wang first order,
/// derivative-lag, Ma--Wang interval, Liu--Wang three-term, iterated
/// preserver and hypergeometric-row criteria (the order of the parent
/// cascade), then the tail after rows that are zero or not real-rooted and
/// certified alternative representations (module documentation), with the
/// default [`AlternativeRepresentationOptions`]. The RealRooted row routes
/// fixed-delay window ([`check_variable_delay_theorem`]) and residue-class
/// decomposition ([`check_residue_class_subsequence_theorem`]) are recorded
/// after them, only when the rule has their form.
/// This is theorem discovery for a supplied rule, not recurrence fitting.
/// Failed sufficient hypotheses do not disprove real-rootedness. There is no
/// catalogue fallback or external attestation route.
///
/// # Errors
///
/// Invalid recurrence/seeds, index overflow, or errors from a theorem check.
pub fn discover_recurrence_proofs(
    record: &RecurrenceJson,
    options: &RealRootednessTheoremOptions,
) -> Result<RecurrenceProofDiscoveryReport, RecurrenceError> {
    discover_recurrence_proofs_with_options(
        record,
        options,
        &AlternativeRepresentationOptions::default(),
    )
}

/// [`discover_recurrence_proofs`] with explicit bounds of the
/// alternative-representation stage (`max_candidates == 0` disables it).
///
/// # Errors
///
/// As [`discover_recurrence_proofs`].
pub fn discover_recurrence_proofs_with_options(
    record: &RecurrenceJson,
    options: &RealRootednessTheoremOptions,
    alternative_options: &AlternativeRepresentationOptions,
) -> Result<RecurrenceProofDiscoveryReport, RecurrenceError> {
    let (rule, first_index, seeds) = record.to_recurrence_parts()?;
    validate_discovery_input(&rule, first_index, &seeds, options)?;
    let attempts = run_theorems(&rule, first_index, &seeds, options)?;
    let mut report = RecurrenceProofDiscoveryReport {
        schema: RECURRENCE_PROOF_DISCOVERY_SCHEMA.into(),
        recurrence: record.clone(),
        maximum_start_delay: options.maximum_start_delay,
        requested_root_region: options.root_region.as_ref().map(open_root_interval),
        status: String::new(),
        statement: String::new(),
        trivially_real_rooted: record.search.is_none()
            && attempts.iter().any(|attempt| attempt.trivially_real_rooted),
        attempts,
        lean_replay: LIFT_LEAN_REPLAY_NOT_ATTEMPTED.into(),
        real_rooted_from_index: None,
        real_rooted_outside_zero_residue_classes: None,
        not_applicable_reason: None,
        tail: None,
        alternative_representations: None,
    };
    let inhomogeneous = rule.inhomogeneous.as_ref().is_some_and(|g| !g.is_zero());
    if !report
        .attempts
        .iter()
        .any(RealRootednessTheoremReport::is_proved)
        && !inhomogeneous
    {
        if let Some((tail_first, reason)) = tail_start(&rule, first_index, &seeds, options) {
            let tail_record = tail_record(&rule, first_index, &seeds, tail_first)?;
            let (_, _, tail_seeds) = tail_record.to_recurrence_parts()?;
            let attempts = run_theorems(&rule, tail_first, &tail_seeds, options)?;
            report.tail = Some(RecurrenceProofTail {
                first_index: tail_first,
                reason,
                recurrence: tail_record,
                attempts,
            });
        }
        let tail_proved = report
            .tail
            .as_ref()
            .is_some_and(|tail| tail.attempts.iter().any(|a| a.is_proved()));
        if !tail_proved && alternative_options.max_candidates > 0 {
            let base = match &report.tail {
                Some(tail) => tail.recurrence.clone(),
                None => RecurrenceJson::from_recurrence_rational(&rule, first_index, &seeds, None),
            };
            report.alternative_representations =
                Some(alternative_search(&base, options, alternative_options)?);
        }
    }
    report.finish_summary(inhomogeneous.then(|| {
        "the rule has an inhomogeneous term: every theorem route needs a homogeneous rule \
         (not_applicable: inhomogeneous)"
            .to_string()
    }));
    Ok(report)
}

fn validate_discovery_input(
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
) -> Result<(), RecurrenceError> {
    first_index
        .checked_add(seeds.len())
        .and_then(|n| n.checked_add(options.maximum_start_delay))
        .and_then(|n| n.checked_add(GENERATED_ROWS))
        .filter(|n| *n <= i64::MAX as usize)
        .ok_or_else(|| {
            RecurrenceError::InvalidInput("proof-search index range overflows".into())
        })?;
    if seeds.is_empty()
        || rule
            .terms
            .iter()
            .any(|t| t.offset == 0 || t.offset > seeds.len())
    {
        return Err(RecurrenceError::InvalidInput(
            "proof discovery needs seeds for every positive recurrence lag".into(),
        ));
    }
    Ok(())
}

fn run_theorems(
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
) -> Result<Vec<RealRootednessTheoremReport>, RecurrenceError> {
    let mut attempts = DISCOVERY_THEOREMS
        .iter()
        .map(|theorem| check_with_first_proving_start(*theorem, rule, first_index, seeds, options))
        .collect::<Result<Vec<_>, _>>()?;
    // RealRooted row routes (`variableDelay`, `subseq`): recorded only where
    // the rule has their form, so the reports of other rules are unchanged.
    for theorem in ROW_ROUTE_THEOREMS {
        let attempt = check_with_first_proving_start(theorem, rule, first_index, seeds, options)?;
        if attempt.status != RealRootednessTheoremStatus::NotApplicable {
            attempts.push(attempt);
        }
    }
    // Index-section lift (RealRooted `pathPower`): recorded only when a
    // section identity with a parent family is found.
    let attempt = check_with_first_proving_start(
        RealRootednessTheorem::IndexSectionLift,
        rule,
        first_index,
        seeds,
        options,
    )?;
    if attempt.status != RealRootednessTheoremStatus::NotApplicable {
        attempts.push(attempt);
    }
    Ok(attempts)
}

/// What the proved attempts of a list give: the smallest first index of a
/// conclusion without zero residue classes (every row from there on nonzero
/// and real-rooted), else the conclusion with zero residue classes of the
/// smallest first index.
fn proved_rows(attempts: &[RealRootednessTheoremReport]) -> Option<ProvedRows> {
    let conclusions = || {
        attempts
            .iter()
            .filter(|attempt| attempt.is_proved())
            .filter_map(|attempt| attempt.conclusion.as_ref())
    };
    let every_row = conclusions()
        .filter(|c| !c.has_zero_residue_classes())
        .map(|c| c.first_index)
        .min();
    if let Some(from) = every_row {
        return Some(ProvedRows::EveryRow(from));
    }
    conclusions()
        .filter_map(|c| {
            c.zero_residue_classes
                .as_ref()
                .map(|zero| RealRootedOutsideZeroResidueClasses {
                    from_index: c.first_index,
                    zero_residue_classes: zero.clone(),
                })
        })
        .min_by_key(|proved| proved.from_index)
        .map(ProvedRows::OutsideZeroResidueClasses)
}

/// The rows a proof covers (see [`proved_rows`]).
enum ProvedRows {
    /// Every row from this index on is nonzero and real-rooted.
    EveryRow(usize),
    /// Every row from the index on outside the zero classes.
    OutsideZeroResidueClasses(RealRootedOutsideZeroResidueClasses),
}

impl RecurrenceProofDiscoveryReport {
    /// Fill `status`, `statement`, `real_rooted_from_index` and
    /// `real_rooted_outside_zero_residue_classes` from the attempts.
    fn finish_summary(&mut self, not_applicable: Option<String>) {
        let mut proved = proved_rows(&self.attempts);
        let mut route = "the supplied record";
        if proved.is_none() {
            if let Some(tail) = &self.tail {
                proved = proved_rows(&tail.attempts);
                route = "the tail record";
            }
        }
        if proved.is_none() {
            if let Some(search) = &self.alternative_representations {
                proved = search
                    .alternatives
                    .iter()
                    .filter(|a| a.proved)
                    .find_map(|a| proved_rows(&a.attempts));
                route = "a certified alternative representation";
            }
        }
        let (from, outside_zero_classes) = match proved {
            Some(ProvedRows::EveryRow(from)) => (Some(from), None),
            Some(ProvedRows::OutsideZeroResidueClasses(rows)) => (None, Some(rows)),
            None => (None, None),
        };
        let is_proved = from.is_some() || outside_zero_classes.is_some();
        self.real_rooted_from_index = from;
        self.status = match (is_proved, &not_applicable) {
            (true, _) => "proved",
            (false, Some(_)) => "not_applicable",
            (false, None) => "not_proved",
        }
        .into();
        self.not_applicable_reason = if is_proved { None } else { not_applicable };
        let mut statement = String::from(FIRST_VERSION_STATEMENT);
        if let Some(from) = from {
            statement.push_str(&format!(
                " Proved through {route}: every row P_n with n >= {from} is nonzero and \
                 real-rooted."
            ));
        }
        if let Some(rows) = &outside_zero_classes {
            let zero = &rows.zero_residue_classes;
            statement.push_str(&format!(
                " Proved through {route}: every row P_n with n >= {} and n mod {} in {:?} is \
                 zero (infinitely many zero rows), and every other row P_n with n >= {} is \
                 nonzero and real-rooted.",
                rows.from_index, zero.period, zero.residues, rows.from_index
            ));
        }
        self.real_rooted_outside_zero_residue_classes = outside_zero_classes;
        if let Some(tail) = &self.tail {
            statement.push_str(&format!(
                " Tail: {}; the tail record starts at index {} and its rows are the family's \
                 rows.",
                tail.reason, tail.first_index
            ));
        }
        if self.alternative_representations.is_some() {
            statement.push_str(
                " Alternative representations are fitted rules; each is used only after an \
                 all-index equality certificate with the family.",
            );
        }
        self.statement = statement;
    }

    /// The theorem options recorded in the report.
    fn theorem_options(&self) -> Result<RealRootednessTheoremOptions, RecurrenceError> {
        let root_region = self
            .requested_root_region
            .as_ref()
            .map(|r| {
                if !r.is_index_independent() {
                    return Err(RecurrenceError::VerificationFailed(
                        "root region must be index-independent".into(),
                    ));
                }
                r.at(0)
            })
            .transpose()?;
        Ok(RealRootednessTheoremOptions {
            root_region,
            maximum_start_delay: self.maximum_start_delay,
        })
    }

    /// Replay the recorded routes (module documentation, "Replay"): every
    /// recorded attempt by recomputation, the tail and the alternatives by
    /// their certificates, and every summary field.
    ///
    /// Rejects changed conclusions, dropped attempts of the first-version
    /// theorems, attempts out of order, altered evidence labels, or
    /// certificates referring to a different rule or seeds.
    ///
    /// # Errors
    ///
    /// [`RecurrenceError::VerificationFailed`] on a mismatch, or an underlying
    /// recurrence/checker error. Verifying `not_proved` is not a proof.
    pub fn verify(&self) -> Result<(), RecurrenceError> {
        let failed = |what: &str| Err(RecurrenceError::VerificationFailed(what.to_string()));
        if self.schema != RECURRENCE_PROOF_DISCOVERY_SCHEMA {
            return failed("unsupported discovery schema");
        }
        if self.lean_replay != LIFT_LEAN_REPLAY_NOT_ATTEMPTED {
            return failed("the Lean replay status must be not_attempted");
        }
        let options = self.theorem_options()?;
        let (rule, first_index, seeds) = self.recurrence.to_recurrence_parts()?;
        validate_discovery_input(&rule, first_index, &seeds, &options)?;
        let plain = RecurrenceJson::from_recurrence_rational(&rule, first_index, &seeds, None);
        // The current search on the same record and options is the
        // reference: the recorded attempts must be a subsequence of its
        // attempts (a recomputation that tries or proves more is fine).
        let alternative_options = self
            .alternative_representations
            .as_ref()
            .map(|search| search.options.clone())
            .unwrap_or_default();
        let recomputed = discover_recurrence_proofs_with_options(
            &self.recurrence,
            &options,
            &alternative_options,
        )?;
        verify_attempts(&self.attempts, &recomputed.attempts, &plain, &options, true)?;
        let inhomogeneous = rule.inhomogeneous.as_ref().is_some_and(|g| !g.is_zero());
        let proved_directly = self.attempts.iter().any(|a| a.is_proved());
        match &self.tail {
            None => {}
            Some(_) if proved_directly || inhomogeneous => {
                return failed("a tail is recorded although it is not tried");
            }
            Some(tail) => {
                let expected = tail_start(&rule, first_index, &seeds, &options);
                if expected.as_ref().map(|(start, _)| *start) != Some(tail.first_index)
                    || expected.as_ref().map(|(_, reason)| reason) != Some(&tail.reason)
                {
                    return failed("the tail start does not match the supplied record");
                }
                if tail.recurrence != tail_record(&rule, first_index, &seeds, tail.first_index)? {
                    return failed("the tail record is not derived from the supplied record");
                }
                let reference =
                    run_theorems(&rule, tail.first_index, &tail_record_seeds(tail)?, &options)?;
                verify_attempts(
                    &tail.attempts,
                    &reference,
                    &tail.recurrence,
                    &options,
                    false,
                )?;
            }
        }
        let tail_proved = self
            .tail
            .as_ref()
            .is_some_and(|tail| tail.attempts.iter().any(|a| a.is_proved()));
        if let Some(search) = &self.alternative_representations {
            if proved_directly || tail_proved || inhomogeneous {
                return failed("an alternative search is recorded although it is not run");
            }
            let base = match &self.tail {
                Some(tail) => tail.recurrence.clone(),
                None => plain.clone(),
            };
            if search.alternatives.len() > search.options.max_alternatives {
                return failed("more alternatives than the recorded bound");
            }
            for (position, alternative) in search.alternatives.iter().enumerate() {
                // Compared with the family, or (certified) with an earlier
                // certified alternative.
                let chained = alternative.equality.is_certified()
                    && search.alternatives[..position].iter().any(|earlier| {
                        earlier.equality.is_certified()
                            && earlier.equality.alternative == alternative.equality.defining
                    });
                if alternative.equality.defining != base && !chained {
                    return failed("an alternative is not compared with the family");
                }
                alternative.equality.verify()?;
                if alternative.equality.is_certified() {
                    let (alternative_rule, alternative_first, alternative_seeds) =
                        alternative.equality.alternative.to_recurrence_parts()?;
                    let reference = run_theorems(
                        &alternative_rule,
                        alternative_first,
                        &alternative_seeds,
                        &options,
                    )?;
                    verify_attempts(
                        &alternative.attempts,
                        &reference,
                        &alternative.equality.alternative,
                        &options,
                        false,
                    )?;
                } else if !alternative.attempts.is_empty() {
                    return failed("theorem attempts on an uncertified alternative");
                }
                let proved = alternative.equality.is_certified()
                    && alternative.attempts.iter().any(|a| a.is_proved());
                if alternative.proved != proved {
                    return failed("an alternative's proved flag does not match its attempts");
                }
                if proved && position + 1 != search.alternatives.len() {
                    return failed("the alternative search continues after a proof");
                }
            }
        }
        let mut expected = self.clone();
        expected.trivially_real_rooted = self.recurrence.search.is_none()
            && self.attempts.iter().any(|a| a.trivially_real_rooted);
        expected.finish_summary(inhomogeneous.then(|| {
            "the rule has an inhomogeneous term: every theorem route needs a homogeneous rule \
             (not_applicable: inhomogeneous)"
                .to_string()
        }));
        if &expected == self {
            return Ok(());
        }
        // A report of the first schema version: no tail, alternatives or
        // first proved index, and the original statement and status.
        let mut legacy = expected;
        legacy.status = if self.attempts.iter().any(|a| a.is_proved()) {
            "proved"
        } else {
            "not_proved"
        }
        .into();
        legacy.statement = FIRST_VERSION_STATEMENT.into();
        legacy.real_rooted_from_index = None;
        legacy.real_rooted_outside_zero_residue_classes = None;
        legacy.not_applicable_reason = None;
        if self.tail.is_none() && self.alternative_representations.is_none() && &legacy == self {
            return Ok(());
        }
        failed("the report summary does not match its attempts")
    }
}

/// Replay a list of recorded attempts on `record` against `reference`, the
/// attempts of the current search on the same record and options: the
/// recorded attempts must appear among the reference attempts in the same
/// order (a subsequence; each theorem at most once), refer to `record` and
/// the recorded options, and each must equal its reference attempt, or
/// replay on its own (a report of an earlier version of a check), or prove
/// nothing where the current check proves the theorem (superseded).  With
/// `require_first_version` the six theorems of the first schema version
/// must all be recorded; otherwise every reference theorem must be.
fn verify_attempts(
    attempts: &[RealRootednessTheoremReport],
    reference: &[RealRootednessTheoremReport],
    record: &RecurrenceJson,
    options: &RealRootednessTheoremOptions,
    require_first_version: bool,
) -> Result<(), RecurrenceError> {
    let failed = |what: &str| Err(RecurrenceError::VerificationFailed(what.to_string()));
    let (expected_rule, expected_first, expected_seeds) = record.to_recurrence_parts()?;
    let expected_data =
        RecurrenceJson::from_recurrence_rational(&expected_rule, 0, &[], None).recurrence;
    let mut position = 0;
    for attempt in attempts {
        let Some(offset) = reference[position..]
            .iter()
            .position(|current| current.theorem == attempt.theorem)
        else {
            return failed("theorem attempts are out of order, repeated or unknown");
        };
        let current = &reference[position + offset];
        position += offset + 1;
        if attempt.start_delay > options.maximum_start_delay {
            return failed("an attempt moves its start further than the recorded bound");
        }
        if attempt.requested_root_region != options.root_region.as_ref().map(open_root_interval) {
            return failed("an attempt has another requested root region");
        }
        let (rule, first_index, seeds) = attempt.recurrence.to_recurrence_parts()?;
        if first_index != expected_first
            || seeds != expected_seeds
            || RecurrenceJson::from_recurrence_rational(&rule, 0, &[], None).recurrence
                != expected_data
        {
            return failed("an attempt refers to another rule or other seeds");
        }
        if attempt == current {
            continue;
        }
        if let Err(error) = attempt.verify() {
            // A recorded attempt that proves nothing and that the current
            // check proves is superseded, not wrong; a proved attempt always
            // replays.
            if attempt.is_proved() || !current.is_proved() {
                return Err(error);
            }
        }
    }
    let recorded: Vec<RealRootednessTheorem> = attempts.iter().map(|a| a.theorem).collect();
    let required: Vec<RealRootednessTheorem> = if require_first_version {
        DISCOVERY_THEOREMS[..FIRST_VERSION_THEOREMS].to_vec()
    } else {
        // Reports saved before the index-section lift existed omit it.
        reference
            .iter()
            .map(|a| a.theorem)
            .filter(|theorem| *theorem != RealRootednessTheorem::IndexSectionLift)
            .collect()
    };
    if required.iter().any(|theorem| !recorded.contains(theorem)) {
        return failed("a theorem attempt is missing");
    }
    Ok(())
}

