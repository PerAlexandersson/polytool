/// The theorem check with the induction start at the supplied seeds.
fn check_at_supplied_seeds(
    theorem: RealRootednessTheorem,
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
) -> Result<RealRootednessTheoremReport, RecurrenceError> {
    match theorem {
        RealRootednessTheorem::ThreeTermRecurrence => {
            three_term::three_term_report(rule, first_index, seeds, options)
        }
        RealRootednessTheorem::LiuWang => {
            liu_wang::liu_wang_report(rule, first_index, seeds, options)
        }
    }
}

/// The theorem check with the induction start moved `delay` rows past the
/// supplied seeds (module documentation, "Moving the induction start").
///
/// # Errors
///
/// [`RecurrenceError::InvalidInput`] when the rule cannot generate the moved
/// seed rows; errors of the record itself.
fn check_with_start_delay(
    theorem: RealRootednessTheorem,
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
    delay: usize,
) -> Result<RealRootednessTheoremReport, RecurrenceError> {
    let seeds = normalized_seed_rows(rule, first_index, seeds)?;
    if delay == 0 {
        return check_at_supplied_seeds(theorem, rule, first_index, &seeds, options);
    }
    let generated = rule
        .generate_rows_rational(&seeds, first_index, seeds.len() + delay)
        .map_err(|error| {
            RecurrenceError::InvalidInput(format!(
                "the rule cannot generate the moved seed rows: {error}"
            ))
        })?;
    let moved = normalized_seed_rows(rule, first_index, &generated)?;
    let mut report = check_at_supplied_seeds(theorem, rule, first_index, &moved, options)?;
    report.recurrence = RecurrenceJson::from_recurrence_rational(rule, first_index, &seeds, None);
    report.start_delay = delay;
    let rule_start = first_index + moved.len();
    if let Some(conclusion) = report.conclusion.as_mut() {
        let mut note = format!(
            "; the rule is applied from n = {rule_start} on in the induction (start moved \
             {delay} row(s) past the supplied seeds; P_{first_index}, ..., P_{} enter as seed \
             rows, checked exactly)",
            rule_start - 1
        );
        if let (Some(from), Some(kind)) = (conclusion.interlacing_from, conclusion.interlacing) {
            let extended = extend_interlacing_backward(&moved, first_index, from, kind);
            if extended < from {
                conclusion.interlacing_from = Some(extended);
                note.push_str(&format!(
                    "; P_(m-1) {} P_m checked exactly for m = {extended}, ..., {}",
                    match kind {
                        RowInterlacing::Strict => "strictly interlaces",
                        RowInterlacing::Weak => "interlaces",
                    },
                    from - 1
                ));
            }
        }
        conclusion.statement.push_str(&note);
    }
    Ok(report)
}

/// The smallest `m <= from` such that `P_(j-1)` interlaces `P_j` (in the
/// sense of `kind`, checked exactly on the rows `rows[i] = P_(first_index +
/// i)`) for every `j` with `m <= j < from`; the downward walk stops at the
/// first pair that fails.
fn extend_interlacing_backward(
    rows: &[Vec<Q>],
    first_index: usize,
    from: usize,
    kind: RowInterlacing,
) -> usize {
    let mut m = from;
    while m >= first_index + 2 && m - 1 - first_index < rows.len() {
        let previous = integer_coefficients(&vec_poly::trim(&rows[m - 2 - first_index]));
        let current = integer_coefficients(&vec_poly::trim(&rows[m - 1 - first_index]));
        let holds = match kind {
            RowInterlacing::Strict => {
                crate::check_interlacing_bigint_coeffs(&previous, &current) == Some(true)
            }
            RowInterlacing::Weak => {
                crate::check_weak_interlacing_bigint_coeffs(&previous, &current) == Some(true)
            }
        };
        if !holds {
            break;
        }
        m -= 1;
    }
    m
}

/// Run the theorem at the supplied seeds and, unless it is proved or does
/// not apply, with the induction start moved `1, ...,
/// options.maximum_start_delay` rows later; the first proved report, else
/// the report at the supplied seeds.
fn check_with_first_proving_start(
    theorem: RealRootednessTheorem,
    rule: &Recurrence,
    first_index: usize,
    seeds: &[Vec<Q>],
    options: &RealRootednessTheoremOptions,
) -> Result<RealRootednessTheoremReport, RecurrenceError> {
    let report = check_with_start_delay(theorem, rule, first_index, seeds, options, 0)?;
    if report.is_proved() || report.status == RealRootednessTheoremStatus::NotApplicable {
        return Ok(report);
    }
    for delay in 1..=options.maximum_start_delay {
        match check_with_start_delay(theorem, rule, first_index, seeds, options, delay) {
            Ok(moved) if moved.is_proved() => return Ok(moved),
            Ok(_) => {}
            Err(_) => break,
        }
    }
    Ok(report)
}

/// `proved` when every hypothesis is verified, `hypothesis_failed` when one
/// fails, `unresolved` otherwise.
fn status_of(hypotheses: &[LiftHypothesis]) -> RealRootednessTheoremStatus {
    if hypotheses
        .iter()
        .any(|h| matches!(h.status, LiftHypothesisStatus::Failed { .. }))
    {
        RealRootednessTheoremStatus::HypothesisFailed
    } else if hypotheses
        .iter()
        .all(|h| h.status == LiftHypothesisStatus::Verified)
    {
        RealRootednessTheoremStatus::Proved
    } else {
        RealRootednessTheoremStatus::Unresolved
    }
}

/// The interval with the same finite ends, both open.
fn open_root_interval(interval: &RealInterval) -> RootInterval {
    RootInterval::from_real(&RealInterval {
        lower: interval.lower.clone(),
        lower_closed: false,
        upper: interval.upper.clone(),
        upper_closed: false,
    })
}

