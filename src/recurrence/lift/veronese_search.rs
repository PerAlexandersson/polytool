//! The bounded search of [`find_veronese_section_lifts`]: input validation,
//! factorization of `chi(L, x^r)`, enumeration of monic divisors, and the
//! per-candidate work (norm, seed solve, verification, parent triage).

use super::parent_proof::periodic_product_parent;
use super::veronese_algebra::*;
use super::*;
use crate::factorization::{
    irreducible_factorization_monic_bivariate_with_budget, MonicBivariateFactor,
    DEFAULT_RECOMBINATION_SUBSET_LIMIT,
};
use crate::polynomial::Polynomial;
use num_traits::{One, Zero};

/// Largest supported modulus `r` of a Veronese section.
pub const MAX_VERONESE_SECTION_MODULUS: usize = 6;

/// Extra rows beyond the identifying prefix compared as a defensive
/// self-check of an accepted lift (not part of the proof).
const SELF_CHECK_EXTRA_ROWS: usize = 4;

/// Bounds of [`find_veronese_section_lifts`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VeroneseSectionLiftOptions {
    /// Largest modulus `r` tried (moduli `2..=max_modulus`); at least 2 and at
    /// most [`MAX_VERONESE_SECTION_MODULUS`].  Default 4.
    pub max_modulus: usize,
    /// Number of parent rows, from the first index, checked exactly for
    /// being nonzero, of one coefficient sign and real-rooted.  Default 12.
    pub parent_rows_to_check: usize,
    /// Number of candidate parent characteristic polynomials `G` tried per
    /// modulus; reaching it sets
    /// [`exhausted_budget`](VeroneseSectionLiftReport::exhausted_budget).
    /// Default 256.
    pub max_parent_candidates: usize,
    /// Recombination budget passed to the bivariate factorization.  Default
    /// [`DEFAULT_RECOMBINATION_SUBSET_LIMIT`].
    pub max_recombination_subsets: usize,
}

impl Default for VeroneseSectionLiftOptions {
    fn default() -> Self {
        Self {
            max_modulus: 4,
            parent_rows_to_check: 12,
            max_parent_candidates: 256,
            max_recombination_subsets: DEFAULT_RECOMBINATION_SUBSET_LIMIT,
        }
    }
}

/// Validated input: the characteristic polynomial and the identifying rows.
#[derive(Debug, Clone)]
pub(super) struct PreparedVeroneseInput {
    /// The supplied recurrence (used to generate input rows).
    pub(super) recurrence: Recurrence,
    /// Index `n0` of the first row.
    pub(super) first_index: usize,
    /// Recurrence order `d` (largest offset).
    pub(super) order: usize,
    /// `chi(L, y)`, monic of degree `d` in `L`.
    pub(super) characteristic: BivariatePolynomial,
    /// The identifying rows `Q_(n0), ..., Q_(n0 + K - 1)`, `K = d`.
    pub(super) seeds: Vec<Vec<BigRational>>,
}

impl PreparedVeroneseInput {
    /// Input rows `Q_(n0), ..., Q_(n0 + count - 1)` generated by the recurrence.
    fn rows(&self, count: usize) -> Result<Vec<Vec<BigRational>>, RecurrenceError> {
        self.recurrence
            .generate_rows_rational(&self.seeds, self.first_index, count)
            .map_err(|error| {
                RecurrenceError::VerificationFailed(format!(
                    "input recurrence replay failed: {error}"
                ))
            })
    }
}

fn is_constant_bivariate(polynomial: &BivarPoly) -> Option<BigRational> {
    let mut constant = BigRational::zero();
    for (n_degree, row) in polynomial.coeffs.iter().enumerate() {
        for (t_degree, coefficient) in row.iter().enumerate() {
            if coefficient.is_zero() {
                continue;
            }
            if n_degree == 0 && t_degree == 0 {
                constant = coefficient.clone();
            } else {
                return None;
            }
        }
    }
    Some(constant)
}

/// Validate the supported input class and build `chi`.
pub(super) fn prepare_veronese_input(
    recurrence: &Recurrence,
    initial_rows: &[Vec<BigRational>],
    first_index: usize,
) -> Result<PreparedVeroneseInput, RecurrenceError> {
    if recurrence.terms.is_empty() {
        return Err(RecurrenceError::Unsupported(
            "Veronese-section lifts need a recurrence with at least one term".into(),
        ));
    }
    for (position, term) in recurrence.terms.iter().enumerate() {
        if term.offset == 0 {
            return Err(RecurrenceError::InvalidInput(format!(
                "recurrence term {position} has offset 0; offsets must be positive"
            )));
        }
        if term.deriv_order != 0 {
            return Err(RecurrenceError::Unsupported(format!(
                "recurrence term {position} has derivative order {}; Veronese-section lifts \
                 support only derivative-free terms",
                term.deriv_order
            )));
        }
        if term.sign != RecurrenceSign::None {
            return Err(RecurrenceError::Unsupported(format!(
                "recurrence term {position} has an alternating (-1)^n factor; Veronese-section \
                 lifts support only coefficients independent of n"
            )));
        }
        if term
            .coeff
            .coeffs
            .iter()
            .skip(1)
            .flatten()
            .any(|c| !c.is_zero())
        {
            return Err(RecurrenceError::Unsupported(format!(
                "recurrence term {position} has a coefficient depending on n; Veronese-section \
                 lifts support only coefficients independent of n"
            )));
        }
    }
    let denominator = match &recurrence.denominator {
        None => BigRational::one(),
        Some(denominator) => match is_constant_bivariate(denominator) {
            Some(constant) if constant.is_zero() => {
                return Err(RecurrenceError::InvalidInput(
                    "the recurrence denominator is zero".into(),
                ))
            }
            Some(constant) => constant,
            None => {
                return Err(RecurrenceError::Unsupported(
                    "the recurrence denominator depends on n or t; Veronese-section lifts \
                     support only a constant denominator"
                        .into(),
                ))
            }
        },
    };
    if recurrence
        .inhomogeneous
        .as_ref()
        .is_some_and(|inhomogeneous| !inhomogeneous.is_zero())
    {
        return Err(RecurrenceError::Unsupported(
            "the recurrence has an inhomogeneous term; Veronese-section lifts support only \
             homogeneous recurrences"
                .into(),
        ));
    }
    let order = recurrence.max_offset();
    if initial_rows.len() < order {
        return Err(RecurrenceError::InvalidInput(format!(
            "the recurrence has order {order} but only {} initial rows were supplied",
            initial_rows.len()
        )));
    }
    let seed_count = recurrence.generation_initial_count(first_index, initial_rows.len());
    let normalized_rows: Vec<Vec<BigRational>> = initial_rows
        .iter()
        .map(|row| polynomial_row(&Polynomial::new(row.clone())))
        .collect();
    let seeds = normalized_rows[..seed_count].to_vec();
    let generated = recurrence
        .generate_rows_rational(&seeds, first_index, normalized_rows.len())
        .map_err(|error| {
            RecurrenceError::InvalidInput(format!("the recurrence cannot be replayed: {error}"))
        })?;
    for (offset, (supplied, generated)) in normalized_rows.iter().zip(&generated).enumerate() {
        if Polynomial::new(supplied.clone()) != Polynomial::new(generated.clone()) {
            return Err(RecurrenceError::InvalidInput(format!(
                "supplied row {} disagrees with the row generated by the recurrence",
                first_index + offset
            )));
        }
    }

    // chi(L, y) = L^d - sum_k c_k(y) L^(d-k), with c_k the summed coefficients
    // of offset k divided by the constant denominator.
    let mut characteristic = vec![UnivariatePolynomial::zero(); order + 1];
    characteristic[order] = Polynomial::one();
    for term in &recurrence.terms {
        let row = term.coeff.coeffs.first().cloned().unwrap_or_default();
        let coefficient = Polynomial::new(row).scale(&(BigRational::one() / &denominator));
        let slot = order - term.offset;
        characteristic[slot] = characteristic[slot].clone() - coefficient;
    }
    Ok(PreparedVeroneseInput {
        recurrence: recurrence.clone(),
        first_index,
        order,
        characteristic: Polynomial::new(characteristic),
        seeds,
    })
}

/// Search for Veronese-section lifts of a recurrence-defined sequence.
///
/// Given `Q_n(y)` by a recurrence and its initial rows `Q_(n0), ...`
/// (`initial_rows[0]` is `Q_(first_index)`, ascending coefficients in the
/// recurrence variable, here called `y`), finds parents `P_n(x)` with a
/// constant-coefficient recurrence and polynomial seeds such that
/// `V_(r, j)(P_n) = Q_n` for every `n >= n0`.  Every reported lift is an
/// exact all-index identity; its [`status`](VeroneseSectionLift::status)
/// says whether it also proves real-rootedness of the `Q_n`.  The search is
/// bounded: finding no lift does not show that none exists.
///
/// # Sections and the transfer theorem
///
/// For a modulus `r >= 2` and a residue `0 <= j < r`, the Veronese section
/// of `P(x) = sum_i a_i x^i` is `V_(r, j)(P)(y) = sum_k a_(r k + j) y^k`.
///
/// **Theorem.** If `P` is real-rooted and its coefficients all have one sign
/// (equivalently, `P` is nonzero with all roots in `(-inf, 0]`), then every
/// section `V_(r, j)(P)` is zero or real-rooted with nonpositive roots.
///
/// *Reason.* After a sign change the coefficients of `P` are nonnegative, and
/// by the Aissen--Schoenberg--Whitney--Edrei theorem they form a Pólya
/// frequency sequence (M. Aissen, I. J. Schoenberg, A. Whitney, *On the
/// generating functions of totally positive sequences I*, J. Analyse Math. 2
/// (1952) 93--103; A. Edrei, *On the generating functions of totally positive
/// sequences II*, J. Analyse Math. 2 (1953) 104--109; see also F. Brenti,
/// *Unimodal, log-concave and Pólya frequency sequences in combinatorics*,
/// Mem. Amer. Math. Soc. 413, 1989).  The Toeplitz matrix
/// `(a_(r(k - i) + j))_(i, k)` of the subsequence is the submatrix of the
/// Toeplitz matrix `(a_(q - p))_(p, q)` with rows `p = r i` and columns
/// `q = r k + j`, so it is totally nonnegative as well, and the same theorem
/// gives the real roots of the section.
///
/// # Supported input
///
/// Every term derivative-free, without a `(-1)^n` factor and with a
/// coefficient independent of `n`; a denominator that is absent or a nonzero
/// constant; no inhomogeneous term; at least one term.  With
/// `Q_m = sum_k c_k(y) Q_(m-k)` (after dividing by the denominator) and `d`
/// the largest offset, the characteristic polynomial is
/// `chi(L, y) = L^d - sum_k c_k(y) L^(d-k)`.  The identifying rows are the
/// first `K = d` rows (`K` is
/// [`Recurrence::generation_initial_count`]); supplied rows beyond them must
/// agree with the recurrence.
///
/// # Algorithm
///
/// A parent with characteristic polynomial `G(L, x) = L^e + sum_(i<e) g_i(x) L^i`
/// satisfies `P_(n+e) = -sum_i g_i(x) P_(n+i)` for `n >= n0`.  All its
/// sections then satisfy the recurrence with characteristic polynomial
/// `N(L, y) = Norm_r(G) = prod_(w^r = 1) G(L, w x)` written in `y = x^r`,
/// monic of `L`-degree `r e`: `N(E, x^r)` is `G(E, x)` times the other
/// conjugates (`E` the index shift), and its coefficients lie in `Q[x^r]`, so
/// it commutes with taking sections (`V_j(g(x^r) H(x)) = g(y) V_j(H)`).  `N`
/// is the determinant of multiplication by `G` on the basis
/// `1, x, ..., x^(r-1)` of `Q[L, y][x] / (x^r - y)`.
///
/// For each modulus `r = 2, ..., max_modulus` (moduli above `d` admit no
/// parent and are not searched):
///
/// 1. `F(L, x) = chi(L, x^r)` is factored over `Q`
///    ([`crate::factorization`]); on failure the modulus is recorded in
///    [`skipped_moduli`](VeroneseSectionLiftReport::skipped_moduli).
/// 2. The monic divisors `G` of `F` (products of the irreducible factors with
///    multiplicities up to theirs), nonconstant with `r deg_L G <= d`, are
///    tried by increasing `L`-degree, then `x`-degree, at most
///    `max_parent_candidates` of them.
/// 3. `G` is kept only if `N` divides `chi` in `Q[y][L]`; `chi / N` is the
///    reported cofactor.
/// 4. For each residue `j`, the seed sections `s_(i, a)(y)` (`i < e`, `a < r`)
///    of `P_(n0+i)(x) = sum_a x^a s_(i, a)(x^r)` are solved from
///    `V_j(P_n) = Q_n`, `n0 <= n < n0 + K`.  By linearity this is a system
///    `O(y) s = (Q_(n0), ...)` whose column `(i, a)` is `V_j` of the parent
///    rows generated from the basis seed `P_(n0+i) = x^a` (other seeds 0).  It
///    is solved exactly over `Q(y)` by fraction-free elimination with row
///    pivoting, and every `s_(i, a)` must be a polynomial.  Rank below `r e` is
///    rejected as "seeds not determined" (a limitation of this version: such
///    a candidate may still have polynomial seeds).  The parent rows from the
///    solved seeds are compared with all `K` identifying rows.
/// 5. The first `parent_rows_to_check` parent rows are checked exactly for
///    being nonzero, of one coefficient sign and real-rooted (after clearing
///    denominators, with [`crate::is_real_rooted_bigint_coeffs`]).  A failing
///    row means that this lift cannot give a proof; it is still reported,
///    with a failing status.
/// 6. For a parent `G = L^k - c(x)` (order `k`, in particular every order-one
///    parent), `P_(n0 + k m + i) = c^m P_(n0 + i)` for `0 <= i < k`; if `c` and
///    the `k` seeds are nonzero, real-rooted and of one sign, so is every
///    `P_n`, and the lift proves that every `Q_n`, `n >= n0`, is zero or
///    real-rooted with nonpositive roots
///    ([`VeroneseSectionLiftStatus::ProvedProductParent`]).  Otherwise the
///    parent statement stays open (a finite row check is evidence, not a
///    proof).
///
/// **Why the identifying rows suffice.**  Let `S_n = V_j(P_n) - Q_n`.  The
/// sections of `P` satisfy the `N` recurrence at every target `>= n0 + r e`,
/// and `N` divides `chi`, so they satisfy the `chi` recurrence at every
/// target `>= n0 + d`; `Q` satisfies it at every target `>= n0 + K`, `K = d`.
/// Hence `S` satisfies the monic order-`d` recurrence `chi` from `n0 + K` on
/// and vanishes at the `K` identifying indices, so `S = 0`.  A few further
/// rows are compared as a defensive self-check (not part of the proof).
///
/// The trivial lift `P_n = Q_n(x^r)` has a norm of `L`-degree `r d > d` and
/// is never listed.  Conjugate parents such as `L - 1 - x` and `L - 1 + x`
/// (for `r = 2`) are both listed; the parent row checks separate them.
///
/// # Errors
///
/// [`RecurrenceError::Unsupported`] for a recurrence outside the supported
/// class (derivative, alternating or `n`-dependent terms, a non-constant
/// denominator, an inhomogeneous term, no terms);
/// [`RecurrenceError::InvalidInput`] for invalid options, too few initial
/// rows, or supplied rows that disagree with the recurrence;
/// [`RecurrenceError::VerificationFailed`] if an internal self-check fails.
///
/// # Example
///
/// ```
/// use polytool::recurrence::{
///     find_veronese_section_lifts, BigRational, BivarPoly, Recurrence, RecurrenceTerm,
///     VeroneseSectionLiftOptions, VeroneseSectionLiftStatus,
/// };
///
/// let q = |n: i64| BigRational::from_integer(n.into());
/// // Q_(n+2) = 2 Q_(n+1) + (y - 1) Q_n with Q_0 = Q_1 = 1: the even sections of (1 + x)^n.
/// let recurrence = Recurrence {
///     terms: vec![
///         RecurrenceTerm::new(1, 0, BivarPoly { coeffs: vec![vec![q(2)]] }),
///         RecurrenceTerm::new(2, 0, BivarPoly { coeffs: vec![vec![q(-1), q(1)]] }),
///     ],
///     denominator: None,
///     inhomogeneous: None,
/// };
/// let rows = vec![vec![q(1)], vec![q(1)]];
/// let report =
///     find_veronese_section_lifts(&recurrence, &rows, 0, &VeroneseSectionLiftOptions::default())?;
/// let best = &report.lifts[0];
/// assert_eq!((best.modulus, best.residue), (2, 0));
/// assert_eq!(best.status, VeroneseSectionLiftStatus::ProvedProductParent);
/// # Ok::<(), polytool::recurrence::RecurrenceError>(())
/// ```
pub fn find_veronese_section_lifts(
    recurrence: &Recurrence,
    initial_rows: &[Vec<BigRational>],
    first_index: usize,
    options: &VeroneseSectionLiftOptions,
) -> Result<VeroneseSectionLiftReport, RecurrenceError> {
    validate_options(options)?;
    let prepared = prepare_veronese_input(recurrence, initial_rows, first_index)?;
    let mut accumulator = LiftAccumulator::default();
    for modulus in 2..=options.max_modulus {
        if modulus > prepared.order {
            break;
        }
        let substituted = substitute_power_bivariate(&prepared.characteristic, modulus);
        match irreducible_factorization_monic_bivariate_with_budget(
            &bivariate_to_coefficients(&substituted),
            options.max_recombination_subsets,
        ) {
            Ok(factors) => search_modulus_with_factors(
                &prepared,
                modulus,
                &factors,
                options,
                &mut accumulator,
            )?,
            Err(error) => accumulator
                .skipped_moduli
                .push(VeroneseSectionLiftSkippedModulus {
                    modulus,
                    reason: format!("factorization of chi(L, x^{modulus}) failed: {error}"),
                }),
        }
    }
    Ok(accumulator.into_report(&prepared))
}

fn validate_options(options: &VeroneseSectionLiftOptions) -> Result<(), RecurrenceError> {
    if !(2..=MAX_VERONESE_SECTION_MODULUS).contains(&options.max_modulus) {
        return Err(RecurrenceError::InvalidInput(format!(
            "max_modulus must be between 2 and {MAX_VERONESE_SECTION_MODULUS}, got {}",
            options.max_modulus
        )));
    }
    Ok(())
}

/// Collected results across moduli.
#[derive(Debug, Default)]
pub(super) struct LiftAccumulator {
    pub(super) lifts: Vec<VeroneseSectionLift>,
    pub(super) rejected_candidates: Vec<VeroneseSectionLiftRejection>,
    pub(super) skipped_moduli: Vec<VeroneseSectionLiftSkippedModulus>,
    pub(super) exhausted_budget: bool,
}

impl LiftAccumulator {
    pub(super) fn into_report(
        mut self,
        prepared: &PreparedVeroneseInput,
    ) -> VeroneseSectionLiftReport {
        // Stable: equal keys keep the search order.
        self.lifts.sort_by_key(|lift| {
            (
                lift.status.group(),
                lift.modulus,
                lift.parent_order(),
                lift.parent_degree_in_x(),
                lift.residue,
            )
        });
        VeroneseSectionLiftReport {
            input_characteristic_polynomial: bivariate_to_coefficients(&prepared.characteristic),
            lifts: self.lifts,
            rejected_candidates: self.rejected_candidates,
            skipped_moduli: self.skipped_moduli,
            exhausted_budget: self.exhausted_budget,
        }
    }
}

/// Enumerate the monic divisors of `chi(L, x^r)` from its factorization and
/// evaluate each one (crate-internal: takes the factors directly).
///
/// Divisors are products of the irreducible factors with multiplicities up
/// to theirs, nonconstant, with `r deg_L G <= d`, in order of increasing
/// `L`-degree, then `x`-degree, then exponent vector.
pub(super) fn search_modulus_with_factors(
    prepared: &PreparedVeroneseInput,
    modulus: usize,
    factors: &[MonicBivariateFactor],
    options: &VeroneseSectionLiftOptions,
    accumulator: &mut LiftAccumulator,
) -> Result<(), RecurrenceError> {
    let factor_polynomials: Vec<BivariatePolynomial> = factors
        .iter()
        .map(|factor| bivariate_from_coefficients(&factor.coefficients))
        .collect();
    let substituted = substitute_power_bivariate(&prepared.characteristic, modulus);
    let mut product = BivariatePolynomial::one();
    for (factor, polynomial) in factors.iter().zip(&factor_polynomials) {
        if !is_monic_in_shift(polynomial) || degree_in_shift(polynomial) == 0 {
            return Err(RecurrenceError::VerificationFailed(format!(
                "factorization of chi(L, x^{modulus}) returned a factor that is not monic and \
                 nonconstant in L"
            )));
        }
        product = product * polynomial.pow(factor.multiplicity);
    }
    if product != substituted {
        return Err(RecurrenceError::VerificationFailed(format!(
            "the factors of chi(L, x^{modulus}) do not multiply back to it"
        )));
    }
    let shift_degrees: Vec<usize> = factor_polynomials.iter().map(degree_in_shift).collect();
    let x_degrees: Vec<usize> = factor_polynomials
        .iter()
        .map(degree_in_second_variable)
        .collect();
    let multiplicities: Vec<usize> = factors.iter().map(|factor| factor.multiplicity).collect();
    let max_shift_degree = prepared.order / modulus;
    let mut tried = 0usize;
    for shift_degree in 1..=max_shift_degree {
        let mut exponent_vectors = Vec::new();
        collect_exponent_vectors(
            &shift_degrees,
            &multiplicities,
            shift_degree,
            &mut vec![0; factors.len()],
            0,
            &mut exponent_vectors,
        );
        // deg_x is additive over Q[L][x], so the x-degree of a product is the
        // weighted sum of the factor x-degrees.
        exponent_vectors.sort_by_key(|exponents: &Vec<usize>| {
            let x_degree: usize = exponents
                .iter()
                .zip(&x_degrees)
                .map(|(exponent, degree)| exponent * degree)
                .sum();
            (x_degree, exponents.clone())
        });
        for exponents in exponent_vectors {
            if tried >= options.max_parent_candidates {
                accumulator.exhausted_budget = true;
                return Ok(());
            }
            tried += 1;
            let mut parent = BivariatePolynomial::one();
            for (exponent, polynomial) in exponents.iter().zip(&factor_polynomials) {
                parent = parent * polynomial.pow(*exponent);
            }
            let evaluation = evaluate_veronese_section_lift_candidate(
                prepared,
                modulus,
                &parent,
                options.parent_rows_to_check,
            )?;
            accumulator.lifts.extend(evaluation.lifts);
            accumulator
                .rejected_candidates
                .extend(evaluation.rejections);
        }
    }
    Ok(())
}

/// All exponent vectors `a` with `a_i <= multiplicity_i` and
/// `sum a_i deg_L(f_i) == target`, in lexicographic order.
fn collect_exponent_vectors(
    shift_degrees: &[usize],
    multiplicities: &[usize],
    target: usize,
    current: &mut Vec<usize>,
    position: usize,
    output: &mut Vec<Vec<usize>>,
) {
    if position == shift_degrees.len() {
        if target == 0 {
            output.push(current.clone());
        }
        return;
    }
    let degree = shift_degrees[position];
    let mut exponent = 0;
    while exponent <= multiplicities[position] && exponent * degree <= target {
        current[position] = exponent;
        collect_exponent_vectors(
            shift_degrees,
            multiplicities,
            target - exponent * degree,
            current,
            position + 1,
            output,
        );
        exponent += 1;
    }
    current[position] = 0;
}

/// Lifts and rejections produced by one candidate `G`.
#[derive(Debug, Default)]
pub(super) struct CandidateEvaluation {
    pub(super) lifts: Vec<VeroneseSectionLift>,
    pub(super) rejections: Vec<VeroneseSectionLiftRejection>,
}

/// Outcome of the exact seed solve.
enum SeedSolve {
    Solved(Vec<UnivariatePolynomial>),
    NotDetermined,
    NotPolynomial,
}

/// Parent recurrence `P_n = sum_k -g_(e-k)(x) P_(n-k)` of a monic `G`.
fn parent_recurrence_from_characteristic(parent: &BivariatePolynomial) -> Recurrence {
    let order = degree_in_shift(parent);
    let mut terms = Vec::new();
    for offset in 1..=order {
        let coefficient = -parent.coeff(order - offset);
        if coefficient.is_zero() && offset < order {
            continue;
        }
        let row = if coefficient.is_zero() {
            vec![BigRational::zero()]
        } else {
            coefficient.coeffs().to_vec()
        };
        terms.push(RecurrenceTerm::new(
            offset,
            0,
            BivarPoly::from_coefficients_normalized(vec![row]),
        ));
    }
    Recurrence {
        terms,
        denominator: None,
        inhomogeneous: None,
    }
}

fn polynomial_row(polynomial: &UnivariatePolynomial) -> Vec<BigRational> {
    if polynomial.is_zero() {
        vec![BigRational::zero()]
    } else {
        polynomial.coeffs().to_vec()
    }
}

/// Solve `matrix * s = rhs` over `Q(y)` exactly by fraction-free (Bareiss)
/// elimination with row pivoting on the first `columns` independent rows,
/// and require a polynomial solution.
fn solve_section_system(
    matrix: &[Vec<UnivariatePolynomial>],
    rhs: &[UnivariatePolynomial],
    columns: usize,
) -> Result<SeedSolve, RecurrenceError> {
    let row_count = matrix.len();
    let mut augmented: Vec<Vec<UnivariatePolynomial>> = matrix
        .iter()
        .zip(rhs)
        .map(|(row, value)| {
            let mut row = row.clone();
            row.push(value.clone());
            row
        })
        .collect();
    let mut previous_pivot = UnivariatePolynomial::one();
    for column in 0..columns {
        let Some(pivot_row) = (column..row_count).find(|&row| !augmented[row][column].is_zero())
        else {
            return Ok(SeedSolve::NotDetermined);
        };
        augmented.swap(column, pivot_row);
        let (upper, lower) = augmented.split_at_mut(column + 1);
        let pivot_row = &upper[column];
        let pivot = pivot_row[column].clone();
        for row in lower.iter_mut() {
            let factor = std::mem::replace(&mut row[column], UnivariatePolynomial::zero());
            for (entry, pivot_entry) in row.iter_mut().zip(pivot_row).skip(column + 1) {
                let value = pivot.clone() * entry.clone() - factor.clone() * pivot_entry.clone();
                *entry = exact_quotient(&value, &previous_pivot).ok_or_else(|| {
                    RecurrenceError::VerificationFailed(
                        "fraction-free elimination produced an inexact division".into(),
                    )
                })?;
            }
        }
        previous_pivot = pivot;
    }
    let mut solution = vec![UnivariatePolynomial::zero(); columns];
    for column in (0..columns).rev() {
        let mut numerator = augmented[column][columns].clone();
        for later in column + 1..columns {
            numerator = numerator - augmented[column][later].clone() * solution[later].clone();
        }
        match exact_quotient(&numerator, &augmented[column][column]) {
            Some(quotient) => solution[column] = quotient,
            None => return Ok(SeedSolve::NotPolynomial),
        }
    }
    Ok(SeedSolve::Solved(solution))
}

/// Evaluate one candidate parent characteristic polynomial `G` at modulus `r`
/// for every residue (crate-internal entry point; takes `G` directly).
///
/// `G` must be monic in `L` with `1 <= r deg_L G <= d`.
pub(super) fn evaluate_veronese_section_lift_candidate(
    prepared: &PreparedVeroneseInput,
    modulus: usize,
    parent: &BivariatePolynomial,
    parent_rows_to_check: usize,
) -> Result<CandidateEvaluation, RecurrenceError> {
    let parent_order = degree_in_shift(parent);
    if !is_monic_in_shift(parent) || parent_order == 0 || modulus * parent_order > prepared.order {
        return Err(RecurrenceError::InvalidInput(format!(
            "a candidate parent must be monic in L with 1 <= {modulus} * deg_L G <= {}",
            prepared.order
        )));
    }
    let parent_coefficients = bivariate_to_coefficients(parent);
    let mut evaluation = CandidateEvaluation::default();
    let rejection = |residue: Option<usize>, reason| VeroneseSectionLiftRejection {
        modulus,
        residue,
        parent_characteristic_polynomial: parent_coefficients.clone(),
        reason,
    };

    // Step 3: N = Norm_r(G) must divide chi in Q[y][L].
    let norm = veronese_norm(parent, modulus);
    if !is_monic_in_shift(&norm) || degree_in_shift(&norm) != modulus * parent_order {
        return Err(RecurrenceError::VerificationFailed(format!(
            "the modulus-{modulus} norm of a monic parent is not monic of L-degree {}",
            modulus * parent_order
        )));
    }
    let (cofactor, remainder) = divide_monic_in_shift(&prepared.characteristic, &norm)
        .expect("the norm was checked to be monic");
    if !remainder.is_zero() {
        evaluation.rejections.push(rejection(
            None,
            VeroneseSectionLiftRejectionReason::NormDoesNotDivideCharacteristicPolynomial,
        ));
        return Ok(evaluation);
    }

    // Step 4: basis solutions B^(i, a) with seeds P_(n0 + i) = x^a.
    let parent_recurrence = parent_recurrence_from_characteristic(parent);
    let identifying_rows = prepared.seeds.len();
    let unknowns = modulus * parent_order;
    let generate_parent = |seeds: &[Vec<BigRational>], count: usize| {
        parent_recurrence
            .generate_rows_rational(seeds, prepared.first_index, count)
            .map_err(|error| {
                RecurrenceError::VerificationFailed(format!(
                    "parent recurrence replay failed: {error}"
                ))
            })
    };
    let mut basis_rows = Vec::with_capacity(unknowns);
    for seed_index in 0..parent_order {
        for power in 0..modulus {
            let seeds: Vec<Vec<BigRational>> = (0..parent_order)
                .map(|index| {
                    if index == seed_index {
                        polynomial_row(&Polynomial::monomial(BigRational::one(), power))
                    } else {
                        vec![BigRational::zero()]
                    }
                })
                .collect();
            basis_rows.push(generate_parent(&seeds, identifying_rows)?);
        }
    }
    let check_rows = parent_rows_to_check.max(identifying_rows + SELF_CHECK_EXTRA_ROWS);
    let input_rows = prepared.rows(identifying_rows + SELF_CHECK_EXTRA_ROWS)?;
    let targets: Vec<UnivariatePolynomial> = input_rows[..identifying_rows]
        .iter()
        .map(|row| Polynomial::new(row.clone()))
        .collect();

    for residue in 0..modulus {
        let matrix: Vec<Vec<UnivariatePolynomial>> = (0..identifying_rows)
            .map(|row| {
                basis_rows
                    .iter()
                    .map(|basis| coefficient_section(&basis[row], modulus, residue))
                    .collect()
            })
            .collect();
        let sections = match solve_section_system(&matrix, &targets, unknowns)? {
            SeedSolve::Solved(sections) => sections,
            SeedSolve::NotDetermined => {
                evaluation.rejections.push(rejection(
                    Some(residue),
                    VeroneseSectionLiftRejectionReason::SeedsNotDetermined,
                ));
                continue;
            }
            SeedSolve::NotPolynomial => {
                evaluation.rejections.push(rejection(
                    Some(residue),
                    VeroneseSectionLiftRejectionReason::SeedsNotPolynomial,
                ));
                continue;
            }
        };
        let parent_seeds: Vec<Vec<BigRational>> = sections
            .chunks(modulus)
            .map(|seed_sections| polynomial_row(&assemble_from_sections(seed_sections)))
            .collect();
        let parent_rows = generate_parent(&parent_seeds, check_rows)?;

        // Identification on the K = d identifying rows (the proof), then the
        // defensive self-check on a few more rows.
        let mismatch = (0..identifying_rows)
            .find(|&row| coefficient_section(&parent_rows[row], modulus, residue) != targets[row]);
        if let Some(row) = mismatch {
            evaluation.rejections.push(rejection(
                Some(residue),
                VeroneseSectionLiftRejectionReason::RowMismatch {
                    index: prepared.first_index + row,
                },
            ));
            continue;
        }
        for row in identifying_rows..identifying_rows + SELF_CHECK_EXTRA_ROWS {
            if coefficient_section(&parent_rows[row], modulus, residue)
                != Polynomial::new(input_rows[row].clone())
            {
                return Err(RecurrenceError::VerificationFailed(format!(
                    "lift with modulus {modulus} and residue {residue} matches the identifying \
                     rows but not row {}",
                    prepared.first_index + row
                )));
            }
        }

        // Step 5: parent triage; step 6: order-one product parents.
        let parent_row_check =
            check_parent_rows(&parent_rows[..parent_rows_to_check], prepared.first_index);
        // `G = L^k - c(x)` gives `P_(n0 + k m + i) = c^m P_(n0 + i)` (the
        // periodic-product route shared with `certify_veronese_section_lift`).
        let product_parent_proved =
            periodic_product_parent(&parent_recurrence, &parent_seeds).is_ok();
        let status = parent_status(product_parent_proved, &parent_row_check);
        if product_parent_proved && status != VeroneseSectionLiftStatus::ProvedProductParent {
            return Err(RecurrenceError::VerificationFailed(
                "a proved product parent has a failing checked row".into(),
            ));
        }
        evaluation.lifts.push(VeroneseSectionLift {
            modulus,
            residue,
            parent_characteristic_polynomial: parent_coefficients.clone(),
            section_characteristic_polynomial: bivariate_to_coefficients(&norm),
            cofactor: bivariate_to_coefficients(&cofactor),
            parent_recurrence: parent_recurrence.clone(),
            parent_first_index: prepared.first_index,
            parent_initial_rows: parent_seeds,
            parent_row_check,
            status,
        });
    }
    Ok(evaluation)
}

fn check_parent_rows(
    rows: &[Vec<BigRational>],
    first_index: usize,
) -> VeroneseSectionParentRowCheck {
    let mut check = VeroneseSectionParentRowCheck {
        rows_checked: rows.len(),
        ..Default::default()
    };
    for (offset, row) in rows.iter().enumerate() {
        let index = first_index + offset;
        let shape = classify_row(row);
        if shape.is_zero {
            check.first_zero_row_index.get_or_insert(index);
            continue;
        }
        if !shape.has_one_sign {
            check.first_mixed_sign_row_index.get_or_insert(index);
        }
        if !shape.is_real_rooted {
            check.first_not_real_rooted_row_index.get_or_insert(index);
        }
    }
    check
}

/// The earliest failing checked row decides a failing status (a zero row,
/// then mixed signs, then non-real roots at the same index).
fn parent_status(
    product_parent_proved: bool,
    check: &VeroneseSectionParentRowCheck,
) -> VeroneseSectionLiftStatus {
    let candidates = [
        check
            .first_zero_row_index
            .map(|index| (index, 0, VeroneseSectionLiftStatus::ParentRowZero { index })),
        check.first_mixed_sign_row_index.map(|index| {
            (
                index,
                1,
                VeroneseSectionLiftStatus::ParentRowMixedSigns { index },
            )
        }),
        check.first_not_real_rooted_row_index.map(|index| {
            (
                index,
                2,
                VeroneseSectionLiftStatus::ParentRowNotRealRooted { index },
            )
        }),
    ];
    match candidates
        .into_iter()
        .flatten()
        .min_by_key(|(index, priority, _)| (*index, *priority))
    {
        Some((_, _, status)) => status,
        None if product_parent_proved => VeroneseSectionLiftStatus::ProvedProductParent,
        None => VeroneseSectionLiftStatus::ParentRealRootednessOpen,
    }
}
