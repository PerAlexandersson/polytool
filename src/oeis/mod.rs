/// One nonzero coefficient `value * n^n_degree * t^variable_degree`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SparseCoefficient {
    /// Exponent of the recurrence index `n`.
    pub n_degree: usize,
    /// Exponent of the polynomial variable `t`.
    pub variable_degree: usize,
    /// Exact rational coefficient as a string (`"3"`, `"-1/2"`).
    pub value: &'static str,
}

impl SparseCoefficient {
    /// Construct one sparse bivariate monomial coefficient.
    pub const fn new(n_degree: usize, variable_degree: usize, value: &'static str) -> Self {
        Self {
            n_degree,
            variable_degree,
            value,
        }
    }
}

/// One differential-polynomial term in a scalar recurrence.
///
/// The term contributes `sign(n) * c(n,t) * D^d P_{n-r}(t)` to the right-hand
/// side, with `r = offset`, `d = derivative_order`, `D = d/dt`, and
/// `sign(n) = (-1)^n` when `alternating_sign` is set (otherwise 1).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SparseRecurrenceTerm {
    /// Recurrence offset `r`: the term uses row `P_{n-r}`.
    pub offset: usize,
    /// Order `d` of the `t`-derivative applied to `P_{n-r}`.
    pub derivative_order: usize,
    /// Whether the term is multiplied by `(-1)^n`.
    pub alternating_sign: bool,
    /// The coefficient polynomial `c(n,t)` as a list of nonzero monomials
    /// (no duplicate `(n_degree, variable_degree)` pairs).
    pub coefficient: &'static [SparseCoefficient],
}

/// Sparse executable form of a recurrence found by polytool.
///
/// Same shape as [`crate::recurrence::Recurrence`]:
/// `denominator(n,t) * P_n = sum of terms + inhomogeneous(n,t)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SparseRecurrence {
    /// Right-hand-side terms.
    pub terms: &'static [SparseRecurrenceTerm],
    /// Left-hand-side factor `f(n,t)`; `None` means 1.
    pub denominator: Option<&'static [SparseCoefficient]>,
    /// Additive term `g(n,t)`; `None` means homogeneous.
    pub inhomogeneous: Option<&'static [SparseCoefficient]>,
}

/// One bundled OEIS polynomial family.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OeisSequenceDefinition {
    /// OEIS A-number, upper case (`"A008292"`).
    pub id: &'static str,
    /// OEIS title of the sequence.
    pub name: &'static str,
    /// How strongly the recurrence has been validated.
    pub status: OeisSequenceStatus,
    /// Row-shape convention of the OEIS data.
    pub layout: OeisLayout,
    /// Displayed index of the first bundled row.
    pub first_row: i64,
    /// Flattened OEIS index of the first bundled coefficient.
    pub flattened_offset: i64,
    /// Whether the bundled flattened prefix agrees with local OEIS data.
    pub bfile_prefix_verified: bool,
    /// Recurrence benchmark slug used for exact regression testing.
    pub fixture_slug: &'static str,
    /// Number of canonical rows preceding the first fixture row.
    pub fixture_row_offset: usize,
    /// Complete rows before the recurrence's first row.
    pub prefix_rows: &'static [&'static [&'static str]],
    /// Recurrence index `n` of `initial_rows[0]`: the first row computed by the
    /// recurrence has index `recurrence_first_index + initial_rows.len()`, and
    /// this is the `n` substituted into the recurrence coefficients.
    pub recurrence_first_index: usize,
    /// Structural width (length including trailing zeros) of the first
    /// recurrence-generated row; later rows of a `RegularTriangle` grow by one
    /// each.  Used to pad rows whose top coefficients vanish.
    pub recurrence_first_width: usize,
    /// Initial rows (decimal rational strings, ascending powers of `t`)
    /// supplied to the recurrence evaluator, starting at index
    /// `recurrence_first_index`.
    pub initial_rows: &'static [&'static [&'static str]],
    /// The recurrence itself, in sparse static form.
    pub recurrence: SparseRecurrence,
    /// Number of OEIS-derived rows used when the entry was generated.
    pub source_rows: usize,
    /// Number of those rows held out from fitting (0 unless the status is
    /// [`OeisSequenceStatus::Verified`]).
    pub verification_rows: usize,
    /// SHA-256 fingerprint of the source row data at generation time;
    /// provenance only, not recomputed at run time.
    pub rows_sha256: &'static str,
}

/// The real-rootedness flag of a bundled catalog entry (see
/// [`OeisCatalogRealRootedness`], its data-file form).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OeisRealRootedness {
    /// What is known about the rows.
    pub status: OeisRealRootednessStatus,
    /// Date (`YYYY-MM-DD`) of the proof snapshot or check, when recorded.
    pub as_of: Option<&'static str>,
}

/// The evidence record of a bundled catalog entry (see
/// [`OeisCatalogEvidence`], its data-file form): the strongest coefficient
/// property that held on every one of the first `rows_checked` rows.
///
/// This is evidence about a finite segment of rows, not a proof for every row,
/// and it is separate from the [`OeisRealRootedness`] flag.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OeisEvidence {
    /// The strongest property holding on every checked row.
    pub strongest: OeisEvidenceProperty,
    /// Number of consecutive rows checked, starting at the entry's first row.
    pub rows_checked: usize,
    /// For each property stronger than `strongest`, the first checked row
    /// where it fails (displayed OEIS row index).
    pub first_failure: OeisEvidenceFirstFailures,
    /// Date (`YYYY-MM-DD`) of the check.
    pub as_of: &'static str,
}

/// Whether one row has an [`OeisEvidenceProperty`], with the exact definitions
/// of that enum.
///
/// `NoProperty` is never held.  `RealRooted` is the exact
/// [`crate::is_real_rooted_bigint_coeffs`]; the other three need a row with
/// nonnegative coefficients and no zero between two nonzero coefficients and
/// then use the corresponding `*_bigint_coeffs` check.
pub fn row_has_evidence_property(row: &[BigInt], property: OeisEvidenceProperty) -> bool {
    use num_traits::Signed;
    use num_traits::Zero;
    let shape_is_admissible = || {
        let first = row.iter().position(|value| !value.is_zero());
        let last = row.iter().rposition(|value| !value.is_zero());
        match (first, last) {
            (Some(first), Some(last)) => row[first..=last].iter().all(|value| value.is_positive()),
            _ => true,
        }
    };
    match property {
        OeisEvidenceProperty::RealRooted => crate::is_real_rooted_bigint_coeffs(row),
        OeisEvidenceProperty::UltraLogConcave => {
            shape_is_admissible() && crate::is_ultra_log_concave_bigint_coeffs(row)
        }
        OeisEvidenceProperty::LogConcave => {
            shape_is_admissible() && crate::is_log_concave_bigint_coeffs(row)
        }
        OeisEvidenceProperty::Unimodal => {
            shape_is_admissible() && crate::is_unimodal_bigint_coeffs(row)
        }
        OeisEvidenceProperty::NoProperty => false,
    }
}

/// Incremental builder of an [`OeisCatalogEvidence`] record: feed consecutive
/// rows, starting at the entry's first row, then [`Self::finish`].
///
/// Properties that already failed are not re-checked on later rows, and
/// nothing is checked on rows never pushed, so the caller controls the time
/// spent (for example by stopping at a deadline: the record then covers the
/// rows pushed so far).
#[derive(Debug, Clone)]
pub struct OeisEvidenceAccumulator {
    first_row: i64,
    rows_checked: usize,
    first_failure: OeisEvidenceFirstFailures,
}

impl OeisEvidenceAccumulator {
    /// Start accumulating at the displayed row index `first_row`.
    pub fn new(first_row: i64) -> Self {
        Self {
            first_row,
            rows_checked: 0,
            first_failure: OeisEvidenceFirstFailures::default(),
        }
    }

    /// Number of rows pushed so far.
    pub fn rows_checked(&self) -> usize {
        self.rows_checked
    }

    /// Check the next row (the one after the rows pushed so far).
    pub fn push_row(&mut self, row: &[BigInt]) {
        let index = self.first_row.saturating_add(self.rows_checked as i64);
        for property in OeisEvidenceProperty::ALL {
            if self.first_failure.get(property).is_none()
                && !row_has_evidence_property(row, property)
            {
                self.first_failure.set(property, Some(index));
            }
        }
        self.rows_checked += 1;
    }

    /// The record for the rows pushed so far dated `as_of`, or `None` when no
    /// row was pushed.  `strongest` is the first property (in the order of
    /// [`OeisEvidenceProperty::ALL`]) that never failed, else `NoProperty`;
    /// `first_failure` keeps only the properties stronger than it.
    pub fn finish(&self, as_of: &str) -> Option<OeisCatalogEvidence> {
        if self.rows_checked == 0 {
            return None;
        }
        let strongest = OeisEvidenceProperty::ALL
            .into_iter()
            .find(|&property| self.first_failure.get(property).is_none())
            .unwrap_or(OeisEvidenceProperty::NoProperty);
        let mut first_failure = self.first_failure;
        for property in OeisEvidenceProperty::ALL {
            if property.rank() >= strongest.rank() {
                first_failure.set(property, None);
            }
        }
        Some(OeisCatalogEvidence {
            strongest,
            rows_checked: self.rows_checked,
            first_failure,
            as_of: as_of.to_string(),
        })
    }
}

/// Failure while decoding or evaluating a bundled sequence.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OeisSequenceError {
    /// A catalog entry could not be decoded (bad rational string, duplicate
    /// monomial, index overflow); indicates a corrupt catalog entry.
    InvalidDefinition {
        /// A-number of the entry.
        id: &'static str,
        /// What went wrong.
        message: String,
    },
    /// The recurrence evaluator failed.
    Evaluation(RecurrenceEvaluationError),
    /// A generated coefficient was not an integer.
    NonIntegralCoefficient {
        /// A-number of the entry.
        id: &'static str,
        /// Displayed row index where it occurred.
        row: i64,
    },
    /// The requested displayed row precedes the first bundled row.
    RowBeforeStart {
        /// Requested displayed row index.
        requested: i64,
        /// First available displayed row index.
        first: i64,
    },
    /// Flattened (b-file) offsets are unavailable because the bundled prefix
    /// does not align with the OEIS data.
    BFilePrefixNotVerified {
        /// A-number of the entry.
        id: &'static str,
    },
}

impl fmt::Display for OeisSequenceError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidDefinition { id, message } => {
                write!(formatter, "invalid OEIS catalog entry {id}: {message}")
            }
            Self::Evaluation(error) => error.fmt(formatter),
            Self::NonIntegralCoefficient { id, row } => {
                write!(formatter, "{id} generated a nonintegral coefficient in row {row}")
            }
            Self::RowBeforeStart { requested, first } => {
                write!(formatter, "requested row {requested} is before first row {first}")
            }
            Self::BFilePrefixNotVerified { id } => write!(
                formatter,
                "strict b-file output for {id} is disabled because its OEIS prefix mapping is not verified"
            ),
        }
    }
}

impl std::error::Error for OeisSequenceError {}

impl From<RecurrenceEvaluationError> for OeisSequenceError {
    fn from(error: RecurrenceEvaluationError) -> Self {
        Self::Evaluation(error)
    }
}

fn decode_sparse_polynomial(
    id: &'static str,
    terms: &[SparseCoefficient],
) -> Result<BivarPoly, OeisSequenceError> {
    let n_degree = terms.iter().map(|term| term.n_degree).max().unwrap_or(0);
    let variable_degree = terms
        .iter()
        .map(|term| term.variable_degree)
        .max()
        .unwrap_or(0);
    let mut coeffs =
        vec![vec![BigRational::from_integer(BigInt::from(0)); variable_degree + 1]; n_degree + 1];
    let mut seen = BTreeSet::new();
    for term in terms {
        if !seen.insert((term.n_degree, term.variable_degree)) {
            return Err(OeisSequenceError::InvalidDefinition {
                id,
                message: format!(
                    "duplicate sparse monomial n^{} t^{}",
                    term.n_degree, term.variable_degree
                ),
            });
        }
        coeffs[term.n_degree][term.variable_degree] =
            parse_rational_coeff(term.value).map_err(|message| {
                OeisSequenceError::InvalidDefinition {
                    id,
                    message: format!("invalid recurrence coefficient `{}`: {message}", term.value),
                }
            })?;
    }
    Ok(BivarPoly { coeffs })
}

fn decode_rows(
    id: &'static str,
    rows: &[&[&str]],
) -> Result<Vec<Vec<BigRational>>, OeisSequenceError> {
    rows.iter()
        .enumerate()
        .map(|(row_index, row)| {
            row.iter()
                .enumerate()
                .map(|(coefficient_index, value)| {
                    parse_rational_coeff(value).map_err(|message| {
                        OeisSequenceError::InvalidDefinition {
                            id,
                            message: format!(
                                "invalid initial coefficient at row {row_index}, coefficient \
                                 {coefficient_index}: {message}"
                            ),
                        }
                    })
                })
                .collect()
        })
        .collect()
}

impl OeisSequenceDefinition {
    /// The real-rootedness flag recorded for the bundled catalog entry with
    /// this definition's id (`None`: unknown).
    ///
    /// The flag belongs to the bundled data file; a definition built from
    /// another catalog file still reads the bundled flag of its id.
    pub fn real_rootedness(&self) -> Option<OeisRealRootedness> {
        OEIS_REAL_ROOTEDNESS
            .binary_search_by_key(&self.id, |(id, _, _)| id)
            .ok()
            .map(|index| {
                let (_, status, as_of) = OEIS_REAL_ROOTEDNESS[index];
                OeisRealRootedness { status, as_of }
            })
    }

    /// The evidence record stored for the bundled catalog entry with this
    /// definition's id (`None`: none recorded).
    ///
    /// Like [`Self::real_rootedness`], it belongs to the bundled data file.
    /// It is evidence about the first `rows_checked` rows only, not a proof.
    pub fn evidence(&self) -> Option<OeisEvidence> {
        OEIS_EVIDENCE
            .binary_search_by_key(&self.id, |(id, _)| id)
            .ok()
            .map(|index| OEIS_EVIDENCE[index].1)
    }

    /// Compute the evidence record of the first `rows` rows exactly, dated
    /// `as_of` (see [`OeisEvidenceProperty`] for the definitions).
    ///
    /// If the recurrence cannot generate that many rows, the rows generated
    /// before the failure are checked and `rows_checked` says how many.
    /// Returns `Ok(None)` when `rows == 0`.
    ///
    /// # Errors
    ///
    /// The generation error when not even the first row can be generated.
    pub fn compute_evidence(
        &self,
        rows: usize,
        as_of: &str,
    ) -> Result<Option<OeisCatalogEvidence>, OeisSequenceError> {
        let mut accumulator = OeisEvidenceAccumulator::new(self.first_row);
        for row in self.generate_rows_iter()?.take(rows) {
            match row {
                Ok(row) => accumulator.push_row(&row),
                Err(error) if accumulator.rows_checked() == 0 => return Err(error),
                Err(_) => break,
            }
        }
        Ok(accumulator.finish(as_of))
    }

    /// Decode the sparse static description into the recurrence evaluator.
    pub fn recurrence_parts(
        &self,
    ) -> Result<(Recurrence, Vec<Vec<BigRational>>), OeisSequenceError> {
        let terms = self
            .recurrence
            .terms
            .iter()
            .map(|term| {
                Ok(RecurrenceTerm {
                    offset: term.offset,
                    deriv_order: term.derivative_order,
                    sign: if term.alternating_sign {
                        RecurrenceSign::AlternatingN
                    } else {
                        RecurrenceSign::None
                    },
                    coeff: decode_sparse_polynomial(self.id, term.coefficient)?,
                })
            })
            .collect::<Result<Vec<_>, OeisSequenceError>>()?;
        let denominator = self
            .recurrence
            .denominator
            .map(|terms| decode_sparse_polynomial(self.id, terms))
            .transpose()?;
        let inhomogeneous = self
            .recurrence
            .inhomogeneous
            .map(|terms| decode_sparse_polynomial(self.id, terms))
            .transpose()?;
        let initial_rows = decode_rows(self.id, self.initial_rows)?;
        Ok((
            Recurrence {
                terms,
                denominator,
                inhomogeneous,
            },
            initial_rows,
        ))
    }

    /// Decode a recurrence for export at the displayed OEIS row indices.
    ///
    /// Catalog recurrence indices may begin before or after the displayed
    /// sequence, and some recurrences are valid only after an authoritative
    /// prefix.  The returned recurrence has its `n` variable shifted to the
    /// displayed index, while the returned initial rows contain both the
    /// prefix and every delayed recurrence initial row.
    pub fn recurrence_export_parts(
        &self,
    ) -> Result<(Recurrence, Vec<Vec<BigRational>>, i64), OeisSequenceError> {
        let (recurrence, initial_rows) = self.recurrence_parts()?;
        let mut rows = decode_rows(self.id, self.prefix_rows)?;
        let prefix_count =
            i64::try_from(rows.len()).map_err(|_| OeisSequenceError::InvalidDefinition {
                id: self.id,
                message: "prefix row count does not fit in i64".to_string(),
            })?;
        let displayed_recurrence_start =
            self.first_row.checked_add(prefix_count).ok_or_else(|| {
                OeisSequenceError::InvalidDefinition {
                    id: self.id,
                    message: "displayed recurrence index overflows i64".to_string(),
                }
            })?;
        let internal_recurrence_start =
            i64::try_from(self.recurrence_first_index).map_err(|_| {
                OeisSequenceError::InvalidDefinition {
                    id: self.id,
                    message: "recurrence first index does not fit in i64".to_string(),
                }
            })?;
        let shift = internal_recurrence_start
            .checked_sub(displayed_recurrence_start)
            .ok_or_else(|| OeisSequenceError::InvalidDefinition {
                id: self.id,
                message: "recurrence export index shift overflows i64".to_string(),
            })?;
        rows.extend(initial_rows);
        Ok((recurrence.shift_index(shift), rows, self.first_row))
    }

    /// Lazily iterate over the complete rows in catalog order, beginning at
    /// [`first_row`](Self::first_row).
    ///
    /// The stream is the authoritative [`prefix_rows`](Self::prefix_rows)
    /// followed by the recurrence's initial rows and then the rows computed by
    /// the shared [`RecurrenceRowIterator`], with the same exact rational
    /// evaluation, integer conversion and width padding as
    /// [`Self::generate_rows`].  See [`OeisRowIterator`] for the laziness and
    /// error contract.
    ///
    /// # Errors
    ///
    /// Only a corrupt prefix is reported here (construction time:
    /// [`OeisSequenceError::InvalidDefinition`]).  Everything else, including a
    /// corrupt recurrence, is reported by the iterator when the row is reached.
    pub fn generate_rows_iter(&self) -> Result<OeisRowIterator, OeisSequenceError> {
        Ok(OeisRowIterator {
            definition: *self,
            prefix: decode_rows(self.id, self.prefix_rows)?.into(),
            recurrence_rows: None,
            rows_consumed: 0,
            pending_skip: 0,
            finished: false,
        })
    }

    /// Like [`Self::generate_rows_iter`], but the first row yielded is the one with
    /// displayed OEIS row index `first_row`.
    ///
    /// The earlier rows are still traversed (nothing is random access), but
    /// lazily on the first call to `next` and without being retained; an error
    /// in a skipped row is yielded as the first item.  Construction does no
    /// evaluation.
    ///
    /// # Errors
    ///
    /// [`OeisSequenceError::RowBeforeStart`] if `first_row < self.first_row`,
    /// and the construction-time error of [`Self::generate_rows_iter`].
    pub fn generate_rows_from_iter(
        &self,
        first_row: i64,
    ) -> Result<OeisRowIterator, OeisSequenceError> {
        if first_row < self.first_row {
            return Err(OeisSequenceError::RowBeforeStart {
                requested: first_row,
                first: self.first_row,
            });
        }
        let mut rows = self.generate_rows_iter()?;
        rows.pending_skip = usize::try_from(first_row - self.first_row).unwrap_or(usize::MAX);
        Ok(rows)
    }

    /// Generate the first `row_count` complete rows in catalog order.
    ///
    /// Collects the first `row_count` items of [`Self::generate_rows_iter`].  A request
    /// that fits in the authoritative prefix, and a request for zero rows,
    /// evaluate no recurrence step.
    pub fn generate_rows(&self, row_count: usize) -> Result<Vec<Vec<BigInt>>, OeisSequenceError> {
        self.generate_rows_iter()?.take(row_count).collect()
    }

    /// Generate `row_count` rows beginning at a displayed OEIS row index.
    ///
    /// The rows before `first_row` are generated and validated but not
    /// retained; use [`Self::generate_rows_from_iter`] to keep consuming lazily.
    pub fn generate_rows_from(
        &self,
        first_row: i64,
        row_count: usize,
    ) -> Result<Vec<Vec<BigInt>>, OeisSequenceError> {
        let mut rows = self.generate_rows_from_iter(first_row)?;
        rows.discard_pending_skip()?;
        rows.take(row_count).collect()
    }

    /// Flattened index corresponding to the beginning of `displayed_row`.
    pub fn flattened_offset_for_row(&self, displayed_row: i64) -> Result<i64, OeisSequenceError> {
        if !self.bfile_prefix_verified {
            return Err(OeisSequenceError::BFilePrefixNotVerified { id: self.id });
        }
        if displayed_row < self.first_row {
            return Err(OeisSequenceError::RowBeforeStart {
                requested: displayed_row,
                first: self.first_row,
            });
        }
        let skipped = usize::try_from(displayed_row - self.first_row).unwrap_or(usize::MAX);
        let mut skipped_terms = Some(0i64);
        for row in self.generate_rows_iter()?.take(skipped) {
            let row = row?;
            skipped_terms = skipped_terms.and_then(|sum| {
                i64::try_from(row.len())
                    .ok()
                    .and_then(|length| sum.checked_add(length))
            });
        }
        skipped_terms
            .and_then(|terms| self.flattened_offset.checked_add(terms))
            .ok_or_else(|| OeisSequenceError::InvalidDefinition {
                id: self.id,
                message: "flattened offset overflow".to_string(),
            })
    }
}

/// Lazy iterator over the rows of one [`OeisSequenceDefinition`], created by
/// [`OeisSequenceDefinition::generate_rows_iter`] or
/// [`OeisSequenceDefinition::generate_rows_from_iter`].
///
/// It is an adapter over the shared [`RecurrenceRowIterator`], not a separate
/// generator: the decoded authoritative prefix rows come first, then the
/// recurrence initial rows and computed rows at their *internal* recurrence
/// indices (starting at [`OeisSequenceDefinition::recurrence_first_index`]),
/// while error messages and [`Self::next_displayed_row`] use the *displayed*
/// OEIS row indices.  Items are integer coefficient rows in ascending powers of
/// `t`, padded to the structural width of the triangle exactly as in
/// [`OeisSequenceDefinition::generate_rows`].
///
/// # Contract
///
/// * The first item is the first row at or after the requested start; the
///   iterator keeps its position, so `by_ref().take(k)` followed by more calls
///   continues without recomputation.
/// * Nothing is evaluated until a row beyond the prefix is requested, and the
///   recurrence is decoded and started only then.  Stopping consumption stops
///   generation.  Only the bounded history window of the recurrence is
///   retained.
/// * A step failure ([`OeisSequenceError::Evaluation`]), a nonintegral
///   coefficient ([`OeisSequenceError::NonIntegralCoefficient`]) or a corrupt
///   recurrence entry is yielded once, after which the iterator ends
///   ([`FusedIterator`]).  Unlike the batch evaluation of the whole prefix,
///   errors are reported in row order, so an earlier nonintegral row wins
///   over a later step failure.
#[derive(Debug, Clone)]
pub struct OeisRowIterator {
    definition: OeisSequenceDefinition,
    prefix: VecDeque<Vec<BigRational>>,
    recurrence_rows: Option<RecurrenceRowIterator>,
    /// Rows already taken from the underlying stream (yielded or skipped).
    rows_consumed: usize,
    /// Rows still to be discarded before the first one is yielded.
    pending_skip: usize,
    finished: bool,
}

impl OeisRowIterator {
    /// The sequence definition being iterated.
    pub fn definition(&self) -> &OeisSequenceDefinition {
        &self.definition
    }

    /// Displayed OEIS row index of the row the next call to `next` yields, or
    /// `None` if it does not fit in `i64`.
    pub fn next_displayed_row(&self) -> Option<i64> {
        let consumed = i64::try_from(self.rows_consumed.checked_add(self.pending_skip)?).ok()?;
        self.definition.first_row.checked_add(consumed)
    }

    /// Number of recurrence steps evaluated so far (zero while only the
    /// authoritative prefix and the recurrence's initial rows were consumed).
    pub fn recurrence_steps_evaluated(&self) -> usize {
        self.recurrence_rows
            .as_ref()
            .map_or(0, RecurrenceRowIterator::steps_evaluated)
    }

    /// Number of rows retained in memory: the not yet consumed prefix rows and
    /// the recurrence's bounded history (see
    /// [`RecurrenceRowIterator::retained_row_count`]).
    pub fn retained_row_count(&self) -> usize {
        self.prefix.len()
            + self
                .recurrence_rows
                .as_ref()
                .map_or(0, RecurrenceRowIterator::retained_row_count)
    }

    fn next_raw_row(&mut self) -> Result<Vec<BigRational>, OeisSequenceError> {
        if let Some(row) = self.prefix.pop_front() {
            return Ok(row);
        }
        if self.recurrence_rows.is_none() {
            let (recurrence, initial_rows) = self.definition.recurrence_parts()?;
            self.recurrence_rows = Some(RecurrenceRowIterator::new(
                recurrence,
                initial_rows,
                self.definition.recurrence_first_index,
            ));
        }
        match self.recurrence_rows.as_mut().and_then(Iterator::next) {
            Some(row) => Ok(row?),
            None => Err(OeisSequenceError::InvalidDefinition {
                id: self.definition.id,
                message: "recurrence row stream ended".to_string(),
            }),
        }
    }

    fn convert_row(
        &self,
        index: usize,
        row: Vec<BigRational>,
    ) -> Result<Vec<BigInt>, OeisSequenceError> {
        let definition = &self.definition;
        let displayed_row = i64::try_from(index)
            .ok()
            .and_then(|offset| definition.first_row.checked_add(offset))
            .ok_or_else(|| OeisSequenceError::InvalidDefinition {
                id: definition.id,
                message: "displayed row index overflows i64".to_string(),
            })?;
        let mut integers = row
            .into_iter()
            .map(|coefficient| {
                if coefficient.denom() != &BigInt::one() {
                    Err(OeisSequenceError::NonIntegralCoefficient {
                        id: definition.id,
                        row: displayed_row,
                    })
                } else {
                    Ok(coefficient.numer().clone())
                }
            })
            .collect::<Result<Vec<_>, _>>()?;
        let prefix_count = definition.prefix_rows.len();
        if definition.bfile_prefix_verified
            && definition.layout == OeisLayout::RegularTriangle
            && index >= prefix_count
        {
            let expected_width = definition
                .recurrence_first_width
                .checked_add(index - prefix_count)
                .ok_or_else(|| OeisSequenceError::InvalidDefinition {
                    id: definition.id,
                    message: "row width overflow".to_string(),
                })?;
            integers.resize(expected_width, BigInt::from(0));
        }
        Ok(integers)
    }

    /// Next converted row of the underlying stream, ignoring `pending_skip`.
    fn next_converted(&mut self) -> Result<Vec<BigInt>, OeisSequenceError> {
        let raw = self.next_raw_row()?;
        let row = self.convert_row(self.rows_consumed, raw)?;
        self.rows_consumed += 1;
        Ok(row)
    }

    /// Consume the rows that precede the requested start row.  An error ends
    /// the iterator and is returned.
    fn discard_pending_skip(&mut self) -> Result<(), OeisSequenceError> {
        while self.pending_skip > 0 && !self.finished {
            if let Err(error) = self.next_converted() {
                self.finish();
                return Err(error);
            }
            self.pending_skip -= 1;
        }
        Ok(())
    }

    fn finish(&mut self) {
        self.finished = true;
        self.prefix.clear();
        self.recurrence_rows = None;
    }
}

impl Iterator for OeisRowIterator {
    type Item = Result<Vec<BigInt>, OeisSequenceError>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.finished {
            return None;
        }
        if let Err(error) = self.discard_pending_skip() {
            return Some(Err(error));
        }
        match self.next_converted() {
            Ok(row) => Some(Ok(row)),
            Err(error) => {
                self.finish();
                Some(Err(error))
            }
        }
    }
}

impl FusedIterator for OeisRowIterator {}

