//! Recurrence-backed OEIS polynomial families.
//!
//! Every catalog entry is a small sparse recurrence description plus the
//! initial rows needed to replay it.  The generated ID functions, such as
//! [`A008292`], make individual families convenient to use while [`by_id`] and
//! [`catalog`] support dynamic discovery.
//!
//! Entry points: [`by_id`] (case-insensitive A-number lookup),
//! [`catalog`] (all entries, sorted by A-number), and
//! [`OeisSequenceDefinition::generate_rows`] /
//! [`OeisSequenceDefinition::generate_rows_from`] to replay rows, and
//! [`OeisSequenceDefinition::generate_rows_iter`] /
//! [`OeisSequenceDefinition::generate_rows_from_iter`] ([`OeisRowIterator`]) to pull
//! them lazily, one at a time, from the shared
//! [`RecurrenceRowIterator`]; the batch functions collect from it.
//!
//! Conventions: rows are `Vec<BigInt>` coefficient vectors in ascending powers
//! of `t` (entry `k` is the coefficient of `t^k`, the OEIS column index for
//! triangles), generated by exact rational recurrence evaluation; a
//! non-integral coefficient is reported as
//! [`OeisSequenceError::NonIntegralCoefficient`].  Row indices passed to
//! `generate_rows_from` and friends are *displayed* OEIS row indices (starting
//! at [`OeisSequenceDefinition::first_row`]), while recurrence indices (used
//! inside the recurrence coefficients) start at
//! [`OeisSequenceDefinition::recurrence_first_index`].
//!
//! Data: the single source of truth is the tracked file
//! `data/oeis-catalog.jsonl` (one [`OeisCatalogRecord`] per line, sorted by
//! A-number, each with an [`OeisCatalogProvenance`]).  The build script turns
//! it into the static catalog; add entries with `polytool oeis add` rather than
//! by hand, and re-validate them against local OEIS data with
//! `polytool oeis check`.  For recurrence evaluation and search see
//! `crate::recurrence`.
//!
//! Real-rootedness flags: a record may carry an
//! [`OeisCatalogRealRootedness`] flag, read with
//! [`OeisSequenceDefinition::real_rootedness`] and listed by
//! [`entries_with_real_rootedness_flag`].  [`OeisRealRootednessStatus::LeanProved`]
//! records that every row is zero or real-rooted by a machine-checked Lean
//! proof made outside polytool; polytool never reports such a family as proved
//! by itself, and the Veronese parent provers treat a parent that equals a
//! flagged entry as conditional on the flag.
//!
//! Finite evidence: a record may also carry an [`OeisCatalogEvidence`], read
//! with [`OeisSequenceDefinition::evidence`]: the strongest of real-rooted,
//! ultra-log-concave, log-concave and unimodal ([`OeisEvidenceProperty`]) that
//! holds on every one of the first `rows_checked` rows, with the first failing
//! row of each stronger property.  It is computed by
//! [`OeisSequenceDefinition::compute_evidence`] (or incrementally with
//! [`OeisEvidenceAccumulator`]) and is evidence about a finite segment only,
//! never a proof, and independent of the real-rootedness flag.
//!
//! B-files: [`flatten_rows_to_bfile`] turns any list of coefficient rows (not
//! only catalog rows) into OEIS b-file text, with an offset, row orientation, a
//! zero-trimming policy and a term cap that never splits a row
//! ([`BFileOptions`]).
//!
//! OEIS text: [`OeisRecurrencePresentation`] re-indexes any recurrence to the
//! rows of an OEIS triangle (offset, orientation and zero trimming as in
//! [`OeisTriangleReading`]) and formats the `%e` "Triangle begins:" block, the
//! `%F` recurrence sentence and `%t` (Mathematica) and `%o` (PARI/GP) programs
//! that reproduce the rows ([`OeisText`]).  Conventions: the row polynomials
//! are `P(n,x)` with ascending coefficients; the recurrence index `n` in the
//! text is the OEIS row number; the text is plain ASCII (`*`, `^`,
//! `d/dx P(n-1,x)`, exact rationals `a/b`); see [`OeisRecurrencePresentation`].

