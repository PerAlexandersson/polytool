    OEIS_REAL_ROOTEDNESS
        .iter()
        .filter_map(|(id, status, as_of)| {
            by_id(id).map(|entry| {
                (
                    entry,
                    OeisRealRootedness {
                        status: *status,
                        as_of: *as_of,
                    },
                )
            })
        })
