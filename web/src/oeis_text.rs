//! WASM exports for OEIS-ready text and OEIS-aligned rows of a recurrence.
//!
//! Both exports take one JSON request: the recurrence record
//! (`polytool.recurrence.v1`) and how its rows are read as an OEIS triangle,
//!
//! ```json
//! {"recurrence": {...}, "first_row": 1, "offset": 0, "reversed": true,
//!  "trim_zeros": "none", "regular_triangle": true, "rows": 10}
//! ```
//!
//! `first_row` is the absolute index of the first row used (default the
//! record's first index), `offset` the OEIS row number of that row (default
//! the same index), `trim_zeros` one of `none`, `low`, `high`, `both`.  The
//! reading is `polytool::oeis::OeisTriangleReading`, so the text, the rows and
//! the b-file agree with `polytool recurrence-generate --format
//! oeis-json|bfile --first-row ... --offset ...`.  Failures are returned as
//! `{"error": "..."}`.

use num_bigint::BigInt;
use polytool::oeis::{
    bfile_row_terms, flatten_rows_to_bfile, BFileOptions, BFileRowOrientation, BFileStoppingRule,
    BFileZeroPolicy, OeisRecurrencePresentation, OeisTriangleReading,
};
use polytool::recurrence::RecurrenceJson;
use serde::{Deserialize, Serialize};
use wasm_bindgen::prelude::*;

/// Largest JSON request accepted.
const MAX_REQUEST_BYTES: usize = 1_048_576;
/// Most rows shown by `oeis_text_for_recurrence`.
const MAX_TEXT_ROWS: usize = 100;
/// Most rows generated by `generate_oeis_rows`.
const MAX_ROWS: usize = 1000;
/// Most b-file terms written by `generate_oeis_rows`.
const MAX_TERMS: usize = 200_000;
/// Consecutive rows without terms after which a term-capped request stops.
const MAX_BARREN_ROWS: usize = 10_000;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct OeisRowsRequest {
    recurrence: RecurrenceJson,
    #[serde(default)]
    first_row: Option<usize>,
    #[serde(default)]
    offset: Option<i64>,
    #[serde(default)]
    reversed: bool,
    #[serde(default)]
    trim_zeros: Option<String>,
    #[serde(default)]
    regular_triangle: bool,
    #[serde(default)]
    rows: Option<usize>,
    #[serde(default)]
    max_terms: Option<usize>,
    #[serde(default)]
    nearest_row: bool,
}

#[derive(Serialize)]
struct OeisRows {
    schema: &'static str,
    first_row_index: i64,
    rows: Vec<Vec<String>>,
    rows_included: usize,
    terms_included: usize,
    bfile: String,
}

fn presentation(
    request_json: &str,
) -> Result<(OeisRowsRequest, OeisRecurrencePresentation), String> {
    if request_json.len() > MAX_REQUEST_BYTES {
        return Err("request exceeds 1 MiB".to_string());
    }
    let request: OeisRowsRequest =
        serde_json::from_str(request_json).map_err(|error| format!("invalid request: {error}"))?;
    let zero_policy = match request.trim_zeros.as_deref().unwrap_or("none") {
        "none" => BFileZeroPolicy::KeepAll,
        "low" => BFileZeroPolicy::TrimLowOrder,
        "high" => BFileZeroPolicy::TrimHighOrder,
        "both" => BFileZeroPolicy::TrimBothEnds,
        other => {
            return Err(format!(
                "trim_zeros must be none, low, high or both, got {other}"
            ))
        }
    };
    let first_row = request.first_row.unwrap_or(request.recurrence.first_index);
    let first_row_index = match request.offset {
        Some(offset) => offset,
        None => i64::try_from(first_row).map_err(|_| "first_row does not fit in i64")?,
    };
    let reading = OeisTriangleReading {
        first_row_index,
        orientation: if request.reversed {
            BFileRowOrientation::Reversed
        } else {
            BFileRowOrientation::AsStored
        },
        zero_policy,
        regular_triangle: request.regular_triangle,
    };
    let presentation = OeisRecurrencePresentation::from_recurrence_json(
        &request.recurrence,
        Some(first_row),
        reading,
    )
    .map_err(|error| error.to_string())?;
    Ok((request, presentation))
}

fn error_json(error: String) -> String {
    serde_json::json!({ "error": error }).to_string()
}

/// OEIS text fields (`polytool.oeis-text.v1`: the `%e` "Triangle begins:"
/// block, the `%F` recurrence sentence, Mathematica and PARI/GP programs) for
/// the first `rows` OEIS rows (default 10, at most 100) of a recurrence.
#[wasm_bindgen]
pub fn oeis_text_for_recurrence(request_json: &str) -> String {
    let run = || -> Result<String, String> {
        let (request, presentation) = presentation(request_json)?;
        let rows = request.rows.unwrap_or(10);
        if rows > MAX_TEXT_ROWS {
            return Err(format!("at most {MAX_TEXT_ROWS} rows of OEIS text"));
        }
        let text = presentation
            .oeis_text(rows)
            .map_err(|error| error.to_string())?;
        serde_json::to_string(&text).map_err(|error| error.to_string())
    };
    run().unwrap_or_else(error_json)
}

/// OEIS-aligned integer rows and their b-file text (`polytool.oeis-rows.v1`).
///
/// With `rows` (at most 1000) that many rows from `first_row` on are read; with
/// `max_terms` (at most 200000) and no `rows`, rows are generated until the
/// b-file has `max_terms` terms, whole rows only (`nearest_row`: the whole row
/// nearest the cap).  `rows` in the result are the OEIS rows (fewer when a
/// regular triangle reading stops early); `bfile` holds the lines `index
/// value` from the offset on.
#[wasm_bindgen]
pub fn generate_oeis_rows(request_json: &str) -> String {
    let run = || -> Result<String, String> {
        let (request, presentation) = presentation(request_json)?;
        let (row_limit, max_terms) = match (request.rows, request.max_terms) {
            (Some(rows), _) if rows > MAX_ROWS => {
                return Err(format!("at most {MAX_ROWS} rows in the browser"))
            }
            (_, Some(terms)) if terms > MAX_TERMS => {
                return Err(format!("at most {MAX_TERMS} b-file terms in the browser"))
            }
            (Some(rows), terms) => (rows, terms),
            (None, Some(terms)) => (MAX_ROWS.max(terms), Some(terms)),
            (None, None) => return Err("give rows or max_terms".to_string()),
        };
        let zero_policy = presentation.reading().zero_policy;
        let mut integer_rows: Vec<Vec<BigInt>> = Vec::new();
        let mut terms = 0usize;
        let mut barren = 0usize;
        for row in presentation.rows_iter() {
            if integer_rows.len() >= row_limit
                || (request.rows.is_none() && max_terms.is_some_and(|cap| terms >= cap))
            {
                break;
            }
            let row = row.map_err(|error| error.to_string())?;
            let index = presentation.reading().first_row_index + integer_rows.len() as i64;
            let row: Vec<BigInt> = row
                .iter()
                .map(|c| c.is_integer().then(|| c.to_integer()))
                .collect::<Option<_>>()
                .ok_or_else(|| format!("row {index} has a non-integral coefficient"))?;
            let kept = bfile_row_terms(&row, zero_policy).len();
            barren = if kept == 0 { barren + 1 } else { 0 };
            if barren > MAX_BARREN_ROWS {
                return Err(format!("{MAX_BARREN_ROWS} consecutive rows without terms"));
            }
            terms += kept;
            integer_rows.push(row);
        }
        let read = presentation.reading().read_rows(&integer_rows);
        let options = BFileOptions {
            first_index: presentation.reading().first_row_index,
            max_terms,
            stopping_rule: if request.nearest_row {
                BFileStoppingRule::NearestWholeRow
            } else {
                BFileStoppingRule::AtMostCap
            },
            ..BFileOptions::default()
        };
        let file = flatten_rows_to_bfile(&read, &options).map_err(|error| error.to_string())?;
        let rows = read
            .iter()
            .take(file.rows_included)
            .map(|row| row.iter().map(ToString::to_string).collect())
            .collect();
        serde_json::to_string(&OeisRows {
            schema: "polytool.oeis-rows.v1",
            first_row_index: presentation.reading().first_row_index,
            rows,
            rows_included: file.rows_included,
            terms_included: file.terms_included,
            bfile: file.text,
        })
        .map_err(|error| error.to_string())
    };
    run().unwrap_or_else(error_json)
}

#[cfg(test)]
mod tests {
    use super::*;

    const DERIVATIVE: &str = r#"{"schema": "polytool.recurrence.v1", "first_index": 0,
      "initial_polynomials": [["1"]],
      "recurrence": {"terms": [
        {"offset": 1, "deriv_order": 0, "sign": "none", "coeff": {"coeffs": [["1", "-2"], ["0", "2"]]}},
        {"offset": 1, "deriv_order": 1, "sign": "none", "coeff": {"coeffs": [["0", "2", "-2"]]}}]}}"#;

    fn request(extra: &str) -> String {
        format!(
            r#"{{"recurrence": {DERIVATIVE}, "first_row": 1, "offset": 0, "reversed": true,
               "regular_triangle": true{extra}}}"#
        )
    }

    #[test]
    fn rows_and_bfile_follow_the_reading() {
        let value: serde_json::Value =
            serde_json::from_str(&generate_oeis_rows(&request(r#", "rows": 4"#))).unwrap();
        assert_eq!(value["rows"][3], serde_json::json!(["8", "60", "36", "1"]));
        assert_eq!(value["terms_included"], 10);
        assert!(value["bfile"]
            .as_str()
            .unwrap()
            .starts_with("0 1\n1 2\n2 1\n3 4\n"));
    }

    #[test]
    fn term_cap_ends_at_a_whole_row() {
        let value: serde_json::Value =
            serde_json::from_str(&generate_oeis_rows(&request(r#", "max_terms": 12"#))).unwrap();
        assert_eq!(value["terms_included"], 10);
        let nearest: serde_json::Value = serde_json::from_str(&generate_oeis_rows(&request(
            r#", "max_terms": 14, "nearest_row": true"#,
        )))
        .unwrap();
        assert_eq!(nearest["terms_included"], 15);
    }

    #[test]
    fn text_matches_the_library() {
        let value: serde_json::Value =
            serde_json::from_str(&oeis_text_for_recurrence(&request(r#", "rows": 3"#))).unwrap();
        assert_eq!(value["schema"], "polytool.oeis-text.v1");
        assert_eq!(
            value["triangle_example"],
            "Triangle begins:\n  0: 1;\n  1: 2,  1;\n  2: 4, 10, 1;\n"
        );
    }

    #[test]
    fn limits_and_errors_are_reported() {
        let error: serde_json::Value =
            serde_json::from_str(&generate_oeis_rows(&request(r#", "rows": 5000"#))).unwrap();
        assert!(error["error"].as_str().unwrap().contains("1000"));
        let error: serde_json::Value = serde_json::from_str(&generate_oeis_rows(&request(
            r#", "trim_zeros": "middle", "rows": 2"#,
        )))
        .unwrap();
        assert!(error["error"].as_str().unwrap().contains("trim_zeros"));
    }
}
