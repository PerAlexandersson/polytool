/// Switches for the Buchberger criteria and batching; the defaults enable all of them.
///
/// Every setting yields a correct Gröbner basis; they only change the amount
/// of work (compare [`BuchbergerStats`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GroebnerOptions {
    /// Buchberger product criterion: if leading monomials are relatively
    /// prime, the corresponding S-polynomial reduces to zero.
    pub skip_relatively_prime_leading_terms: bool,
    /// Buchberger chain criterion using already handled S-pairs.
    pub skip_chain_criterion_pairs: bool,
    /// Reduce all currently minimal lcm-degree S-polynomials in one matrix
    /// batch. Disable this to compare against scalar Buchberger reduction.
    pub batch_reduce_same_lcm_degree: bool,
}

impl Default for GroebnerOptions {
    fn default() -> Self {
        Self {
            skip_relatively_prime_leading_terms: true,
            skip_chain_criterion_pairs: true,
            batch_reduce_same_lcm_degree: true,
        }
    }
}

/// Counters describing one Buchberger run, for comparing option settings.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BuchbergerStats {
    /// Number of generators passed in (including zero polynomials).
    pub input_generators: usize,
    /// Number of nonzero generators, made monic, that seeded the basis.
    pub monic_generators: usize,
    /// S-pairs taken from the queue.
    pub pairs_processed: usize,
    /// Pairs skipped by the product criterion (relatively prime leading monomials).
    pub pairs_skipped_relatively_prime: usize,
    /// Pairs skipped by the chain criterion.
    pub pairs_skipped_chain_criterion: usize,
    /// Number of matrix (F4-style) reduction batches.
    pub matrix_reduction_batches: usize,
    /// Total S-polynomials reduced in matrix batches.
    pub matrix_reduction_polynomials: usize,
    /// Matrix remainders that were zero and re-checked by scalar reduction.
    pub matrix_zero_rechecks: usize,
    /// Re-checked remainders that turned out nonzero (matrix reduction missed them).
    pub matrix_zero_rechecks_nonzero: usize,
    /// Times the batched run was discarded and recomputed without batching
    /// because the result failed the Gröbner check.
    pub batch_fallbacks: usize,
    /// S-polynomials that reduced to zero.
    pub zero_remainders: usize,
    /// S-polynomials with a nonzero remainder (each adds a basis element).
    pub nonzero_remainders: usize,
}

/// A basis together with the statistics of the computation that produced it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GroebnerComputation<P: SparsePolynomial> {
    /// The computed basis (monic polynomials).
    pub basis: Vec<P>,
    /// Work counters for the run.
    pub stats: BuchbergerStats,
}

/// A reduced Gröbner basis bundled with its monomial order and leading terms.
///
/// Build it with [`GroebnerBasis::new`]; use [`GroebnerBasis::normal_form`]
/// to reduce polynomials modulo the ideal.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GroebnerBasis<P: SparsePolynomial> {
    /// Number of variables of the polynomial ring.
    pub num_vars: usize,
    /// The monomial order the basis is Gröbner for.
    pub order: MonomialOrder,
    /// The reduced basis polynomials (monic, sorted by decreasing leading monomial).
    pub generators: Vec<P>,
    /// `leading_terms[i]` is the leading term of `generators[i]` under `order`.
    pub leading_terms: Vec<LeadingTerm<Coefficient<P>>>,
    /// Statistics of the run that produced the basis.
    pub stats: BuchbergerStats,
}

impl<P: SparsePolynomial<Field: ExactField>> GroebnerBasis<P> {
    /// Compute the reduced Gröbner basis of the ideal generated by `generators`.
    ///
    /// # Panics
    ///
    /// Panics if the generators do not all have the same number of variables.
    pub fn new(generators: Vec<P>, order: MonomialOrder) -> Self {
        Self::with_options(generators, order, GroebnerOptions::default())
    }

    /// Like [`GroebnerBasis::new`] with explicit [`GroebnerOptions`].
    ///
    /// # Panics
    ///
    /// Panics if the generators do not all have the same number of variables.
    pub fn with_options(
        generators: Vec<P>,
        order: MonomialOrder,
        options: GroebnerOptions,
    ) -> Self {
        let input_num_vars = generators.first().map(P::num_vars).unwrap_or(0);
        let computation = reduced_groebner_basis_with_stats(&generators, order, options);
        let leading_terms = computation
            .basis
            .iter()
            .map(|polynomial| leading_term(polynomial, order).expect("nonzero polynomial"))
            .collect();
        let num_vars = computation
            .basis
            .first()
            .map(P::num_vars)
            .unwrap_or(input_num_vars);
        Self {
            num_vars,
            order,
            generators: computation.basis,
            leading_terms,
            stats: computation.stats,
        }
    }

    /// The unique normal form of `polynomial` modulo the ideal: zero iff the
    /// polynomial is in the ideal, and no remaining term is divisible by a
    /// leading monomial of the basis.
    ///
    /// # Panics
    ///
    /// Panics if `polynomial` does not have [`num_vars`](Self::num_vars) variables.
    pub fn normal_form(&self, polynomial: &P) -> P {
        normal_form_with_leading_terms(
            polynomial,
            &self.generators,
            &self.leading_terms,
            self.order,
        )
    }
}

/// The S-polynomial of `f` and `g`: both scaled to be monic with common
/// leading monomial `lcm(LM(f), LM(g))`, then subtracted.
///
/// # Panics
///
/// Panics if either polynomial is zero or the variable counts differ.
pub fn s_polynomial<P: SparsePolynomial<Field: ExactField>>(
    f: &P,
    g: &P,
    order: MonomialOrder,
) -> P {
    assert_eq!(
        f.num_vars(),
        g.num_vars(),
        "polynomials have different rings"
    );
    let lt_f = leading_term(f, order).expect("first polynomial is zero");
    let lt_g = leading_term(g, order).expect("second polynomial is zero");
    let lcm = monomial_lcm(&lt_f.exponents, &lt_g.exponents);
    let exp_f = monomial_difference(&lcm, &lt_f.exponents);
    let exp_g = monomial_difference(&lcm, &lt_g.exponents);

    multiply_by_monomial(
        f,
        &exp_f,
        P::Field::divide(P::Field::one(), lt_f.coefficient),
    ) - multiply_by_monomial(
        g,
        &exp_g,
        P::Field::divide(P::Field::one(), lt_g.coefficient),
    )
}

fn s_polynomial_with_leading_terms<P: SparsePolynomial<Field: ExactField>>(
    f: &P,
    g: &P,
    lt_f: &LeadingTerm<Coefficient<P>>,
    lt_g: &LeadingTerm<Coefficient<P>>,
) -> P {
    assert_eq!(
        f.num_vars(),
        g.num_vars(),
        "polynomials have different rings"
    );
    let lcm = monomial_lcm(&lt_f.exponents, &lt_g.exponents);
    let exp_f = monomial_difference(&lcm, &lt_f.exponents);
    let exp_g = monomial_difference(&lcm, &lt_g.exponents);

    multiply_by_monomial(
        f,
        &exp_f,
        P::Field::divide(P::Field::one(), lt_f.coefficient.clone()),
    ) - multiply_by_monomial(
        g,
        &exp_g,
        P::Field::divide(P::Field::one(), lt_g.coefficient.clone()),
    )
}

/// A (not necessarily reduced) Gröbner basis of the ideal generated by
/// `generators`, with the default [`GroebnerOptions`].
///
/// # Panics
///
/// Panics if the generators do not all have the same number of variables.
pub fn buchberger_basis<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
) -> Vec<P> {
    buchberger_basis_with_options(generators, order, GroebnerOptions::default())
}

/// [`buchberger_basis`] with explicit options.
///
/// # Panics
///
/// Panics if the generators do not all have the same number of variables.
pub fn buchberger_basis_with_options<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
    options: GroebnerOptions,
) -> Vec<P> {
    buchberger_basis_with_stats(generators, order, options).basis
}

/// [`buchberger_basis`] with explicit options, also returning [`BuchbergerStats`].
///
/// The basis consists of monic polynomials. If the batched (matrix) reduction
/// yields a set that fails [`is_groebner_basis`], the run is repeated without
/// batching (`stats.batch_fallbacks` counts this). An empty input gives an empty basis.
///
/// # Panics
///
/// Panics if the generators have different numbers of variables.
pub fn buchberger_basis_with_stats<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
    options: GroebnerOptions,
) -> GroebnerComputation<P> {
    let mut computation = buchberger_observed(
        generators,
        order,
        options,
        Strategy::DegreeIndex,
        &mut Unlimited,
    )
    .unwrap_or_else(|never| match never {});
    if options.batch_reduce_same_lcm_degree && !is_groebner_basis(&computation.basis, order) {
        let mut fallback_options = options;
        fallback_options.batch_reduce_same_lcm_degree = false;
        computation = buchberger_basis_with_stats(generators, order, fallback_options);
        computation.stats.batch_fallbacks += 1;
    }
    computation
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Strategy {
    DegreeIndex,
    OrderedLexicographic,
}

fn buchberger_observed<P: SparsePolynomial<Field: ExactField>, O: ReductionObserver<P>>(
    generators: &[P],
    order: MonomialOrder,
    options: GroebnerOptions,
    strategy: Strategy,
    observer: &mut O,
) -> Result<GroebnerComputation<P>, O::Error> {
    if generators.is_empty() {
        return Ok(GroebnerComputation {
            basis: Vec::new(),
            stats: BuchbergerStats::default(),
        });
    }
    let num_vars = generators[0].num_vars();
    assert!(
        generators
            .iter()
            .all(|polynomial| polynomial.num_vars() == num_vars),
        "all generators must have the same number of variables"
    );

    let mut basis = Vec::new();
    let mut basis_lts = Vec::new();
    for generator in generators.iter().filter(|p| !p.is_zero()) {
        let remainder = if strategy == Strategy::OrderedLexicographic {
            normal_form_observed(generator, &basis, &basis_lts, order, observer)?
        } else {
            generator.clone()
        };
        if !remainder.is_zero() {
            let monic = make_monic(&remainder, order);
            basis_lts.push(leading_term(&monic, order).expect("nonzero polynomial"));
            basis.push(monic);
        }
    }
    let mut pairs = PairScheduler::new(&basis_lts, strategy);
    let mut handled_pairs = HashSet::new();
    let mut stats = BuchbergerStats {
        input_generators: generators.len(),
        monic_generators: basis.len(),
        ..BuchbergerStats::default()
    };

    while !pairs.is_empty() {
        if strategy == Strategy::OrderedLexicographic && basis.iter().any(is_constant) {
            break;
        }
        let pair_batch = pairs.take_next_batch(options.batch_reduce_same_lcm_degree, &basis_lts);
        let mut active_pairs = Vec::new();
        let mut s_polynomials = Vec::new();

        for (i, j) in pair_batch {
            stats.pairs_processed += 1;
            let pair = canonical_pair(i, j);
            if options.skip_relatively_prime_leading_terms
                && leading_monomials_are_relatively_prime(&basis_lts[i], &basis_lts[j])
            {
                stats.pairs_skipped_relatively_prime += 1;
                handled_pairs.insert(pair);
                continue;
            }
            if options.skip_chain_criterion_pairs
                && chain_criterion_applies(i, j, &basis_lts, &handled_pairs)
            {
                stats.pairs_skipped_chain_criterion += 1;
                handled_pairs.insert(pair);
                continue;
            }

            active_pairs.push(pair);
            s_polynomials.push(s_polynomial_with_leading_terms(
                &basis[i],
                &basis[j],
                &basis_lts[i],
                &basis_lts[j],
            ));
        }

        if s_polynomials.is_empty() {
            continue;
        }

        let remainders = if s_polynomials.len() == 1 || !options.batch_reduce_same_lcm_degree {
            s_polynomials
                .iter()
                .map(|s| normal_form_observed(s, &basis, &basis_lts, order, observer))
                .collect::<Result<Vec<_>, _>>()?
        } else {
            stats.matrix_reduction_batches += 1;
            stats.matrix_reduction_polynomials += s_polynomials.len();
            let mut remainders =
                matrix_normal_forms_with_leading_terms(&s_polynomials, &basis, &basis_lts, order);
            for (s, remainder) in s_polynomials.iter().zip(remainders.iter_mut()) {
                if !remainder.is_zero() {
                    continue;
                }
                stats.matrix_zero_rechecks += 1;
                let scalar_remainder = normal_form_with_leading_terms(s, &basis, &basis_lts, order);
                if !scalar_remainder.is_zero() {
                    stats.matrix_zero_rechecks_nonzero += 1;
                    *remainder = scalar_remainder;
                }
            }
            remainders
        };

        for (pair, remainder) in active_pairs.into_iter().zip(remainders) {
            handled_pairs.insert(pair);
            if remainder.is_zero() {
                stats.zero_remainders += 1;
                continue;
            }
            stats.nonzero_remainders += 1;
            let new_index = basis.len();
            let new_polynomial = make_monic(&remainder, order);
            let new_lt = leading_term(&new_polynomial, order).expect("nonzero polynomial");
            basis.push(new_polynomial);
            basis_lts.push(new_lt);
            observer.after_basis_append(basis.len())?;
            for i in 0..new_index {
                pairs.insert(i, new_index, &basis_lts);
            }
        }
    }

    Ok(GroebnerComputation { basis, stats })
}

/// The reduced Gröbner basis (monic, each element fully reduced by the others,
/// no element's leading monomial divisible by another's), sorted by decreasing
/// leading monomial. It is unique for the ideal and `order`; the zero ideal
/// gives an empty vector.
///
/// # Panics
///
/// Panics if the generators do not all have the same number of variables.
pub fn reduced_groebner_basis<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
) -> Vec<P> {
    reduced_groebner_basis_with_options(generators, order, GroebnerOptions::default())
}

/// [`reduced_groebner_basis`] with explicit options.
///
/// # Panics
///
/// Panics if the generators do not all have the same number of variables.
pub fn reduced_groebner_basis_with_options<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
    options: GroebnerOptions,
) -> Vec<P> {
    reduced_groebner_basis_with_stats(generators, order, options).basis
}

/// [`reduced_groebner_basis`] with explicit options, also returning [`BuchbergerStats`].
///
/// # Panics
///
/// Panics if the generators do not all have the same number of variables.
pub fn reduced_groebner_basis_with_stats<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    order: MonomialOrder,
    options: GroebnerOptions,
) -> GroebnerComputation<P> {
    let computation = buchberger_basis_with_stats(generators, order, options);
    let reduced = interreduce_observed(
        computation.basis,
        order,
        Strategy::DegreeIndex,
        &mut Unlimited,
    )
    .unwrap_or_else(|never| match never {});
    if options.batch_reduce_same_lcm_degree
        && (!is_groebner_basis(&reduced, order)
            || !generators_reduce_to_zero(generators, &reduced, order))
    {
        let mut fallback_options = options;
        fallback_options.batch_reduce_same_lcm_degree = false;
        let mut fallback = reduced_groebner_basis_with_stats(generators, order, fallback_options);
        fallback.stats.batch_fallbacks += 1;
        return fallback;
    }
    GroebnerComputation {
        basis: reduced,
        stats: computation.stats,
    }
}

fn is_constant<P: SparsePolynomial>(polynomial: &P) -> bool {
    !polynomial.is_zero() && polynomial.terms().keys().all(|m| m.iter().all(|&e| e == 0))
}

fn interreduce_observed<P: SparsePolynomial<Field: ExactField>, O: ReductionObserver<P>>(
    mut basis: Vec<P>,
    order: MonomialOrder,
    strategy: Strategy,
    observer: &mut O,
) -> Result<Vec<P>, O::Error> {
    if strategy == Strategy::OrderedLexicographic {
        if let Some(constant) = basis.iter().find(|p| is_constant(*p)) {
            return Ok(vec![make_monic(constant, order)]);
        }
    }
    minimize_leading_monomials(&mut basis, order);
    let mut reduced = Vec::new();
    for i in 0..basis.len() {
        let others: Vec<_> = basis
            .iter()
            .enumerate()
            .filter_map(|(j, p)| (i != j).then_some(p.clone()))
            .collect();
        let leading: Vec<_> = others
            .iter()
            .map(|p| leading_term(p, order).expect("nonzero divisor"))
            .collect();
        let lead = leading_term(&basis[i], order).expect("nonzero polynomial");
        let leading_polynomial = P::monomial(basis[i].num_vars(), lead.exponents, lead.coefficient);
        let dividend = if strategy == Strategy::OrderedLexicographic {
            basis[i].clone() - leading_polynomial.clone()
        } else {
            basis[i].clone()
        };
        let mut remainder = normal_form_observed(&dividend, &others, &leading, order, observer)?;
        if strategy == Strategy::OrderedLexicographic {
            remainder = remainder + leading_polynomial;
        }
        if !remainder.is_zero() {
            reduced.push(make_monic(&remainder, order));
        }
    }
    if strategy == Strategy::DegreeIndex {
        reduced.sort_by(|a, b| {
            order.compare(
                &leading_term(b, order)
                    .expect("nonzero polynomial")
                    .exponents,
                &leading_term(a, order)
                    .expect("nonzero polynomial")
                    .exponents,
            )
        });
    }
    Ok(reduced)
}

/// Reduced rational lexicographic basis with a reusable subtraction budget.
///
/// This policy reduces inputs in order, schedules minimal `(lcm degree, lex lcm)`
/// pairs using first-vector ties and swap removal, skips coprime leading terms,
/// exits pair processing on a constant, and interreduces tails in insertion order.
/// It uses neither matrix batches nor chain criteria or unbudgeted postchecks.
/// See [`super::GroebnerBudget`] for the exact debit and size-check boundaries.
/// Variable-count errors leave the budget unchanged.
///
/// # Panics
///
/// Panics if a monomial exponent or total lcm degree overflows `u32`.
pub fn reduced_lexicographic_groebner_basis_with_budget<
    P: SparsePolynomial<Field = super::RationalField>,
>(
    generators: &[P],
    budget: &mut super::GroebnerBudget,
) -> Result<Vec<P>, super::GroebnerError> {
    if let Some(first) = generators.first() {
        if generators.iter().any(|p| p.num_vars() != first.num_vars()) {
            return Err(super::GroebnerError::IncompatibleVariableCounts);
        }
    }
    let options = GroebnerOptions {
        skip_relatively_prime_leading_terms: true,
        skip_chain_criterion_pairs: false,
        batch_reduce_same_lcm_degree: false,
    };
    let computation = buchberger_observed(
        generators,
        MonomialOrder::Lex,
        options,
        Strategy::OrderedLexicographic,
        budget,
    )?;
    interreduce_observed(
        computation.basis,
        MonomialOrder::Lex,
        Strategy::OrderedLexicographic,
        budget,
    )
}

/// Whether `basis` is a Gröbner basis for `order`: every S-polynomial of a pair
/// reduces to zero modulo the basis (Buchberger's criterion). Quadratic in the
/// basis size; `basis` must consist of nonzero polynomials.
///
/// # Panics
///
/// Panics if some element of `basis` is zero, or if the elements do not all have the same number of
/// variables.
pub fn is_groebner_basis<P: SparsePolynomial<Field: ExactField>>(
    basis: &[P],
    order: MonomialOrder,
) -> bool {
    for (i, j) in all_pairs(basis.len()) {
        let s = s_polynomial(&basis[i], &basis[j], order);
        if !normal_form(&s, basis, order).is_zero() {
            return false;
        }
    }
    true
}

fn generators_reduce_to_zero<P: SparsePolynomial<Field: ExactField>>(
    generators: &[P],
    basis: &[P],
    order: MonomialOrder,
) -> bool {
    generators
        .iter()
        .all(|generator| normal_form(generator, basis, order).is_zero())
}

/// Scale `polynomial` so its leading coefficient under `order` is one.
///
/// # Panics
///
/// Panics on the zero polynomial.
pub fn make_monic<P: SparsePolynomial<Field: ExactField>>(
    polynomial: &P,
    order: MonomialOrder,
) -> P {
    let lt = leading_term(polynomial, order).expect("zero polynomial has no monic form");
    polynomial.scale(&(P::Field::divide(P::Field::one(), lt.coefficient)))
}

fn monomial_lcm(a: &[u32], b: &[u32]) -> Vec<u32> {
    assert_eq!(a.len(), b.len(), "monomials have different lengths");
    a.iter().zip(b.iter()).map(|(&x, &y)| x.max(y)).collect()
}

fn leading_monomials_are_relatively_prime<C>(lt_f: &LeadingTerm<C>, lt_g: &LeadingTerm<C>) -> bool {
    lt_f.exponents
        .iter()
        .zip(lt_g.exponents.iter())
        .all(|(&a, &b)| a == 0 || b == 0)
}

fn monomial_difference(a: &[u32], b: &[u32]) -> Vec<u32> {
    assert_eq!(a.len(), b.len(), "monomials have different lengths");
    a.iter()
        .zip(b.iter())
        .map(|(&x, &y)| {
            assert!(x >= y, "monomial difference would have negative exponent");
            x - y
        })
        .collect()
}

fn all_pairs(n: usize) -> Vec<(usize, usize)> {
    let mut pairs = Vec::new();
    for i in 0..n {
        for j in i + 1..n {
            pairs.push((i, j));
        }
    }
    pairs
}

fn canonical_pair(i: usize, j: usize) -> (usize, usize) {
    if i < j {
        (i, j)
    } else {
        (j, i)
    }
}

fn pair_lcm_total_degree<C>(i: usize, j: usize, leading_terms: &[LeadingTerm<C>]) -> u32 {
    leading_terms[i]
        .exponents
        .iter()
        .zip(leading_terms[j].exponents.iter())
        .map(|(&a, &b)| a.max(b))
        .sum()
}

enum PairScheduler {
    DegreeIndex(CriticalPairQueue),
    Lexicographic(Vec<(usize, usize)>),
}
impl PairScheduler {
    fn new<C>(leading: &[LeadingTerm<C>], strategy: Strategy) -> Self {
        if strategy == Strategy::DegreeIndex {
            Self::DegreeIndex(CriticalPairQueue::new(leading))
        } else {
            Self::Lexicographic(
                (0..leading.len())
                    .flat_map(|j| (0..j).map(move |i| (i, j)))
                    .collect(),
            )
        }
    }
    fn is_empty(&self) -> bool {
        match self {
            Self::DegreeIndex(q) => q.is_empty(),
            Self::Lexicographic(q) => q.is_empty(),
        }
    }
    fn insert<C>(&mut self, i: usize, j: usize, leading: &[LeadingTerm<C>]) {
        match self {
            Self::DegreeIndex(q) => q.insert(i, j, leading),
            Self::Lexicographic(q) => q.push((i, j)),
        }
    }
    fn take_next_batch<C>(
        &mut self,
        batch: bool,
        leading: &[LeadingTerm<C>],
    ) -> Vec<(usize, usize)> {
        match self {
            Self::DegreeIndex(q) => q.take_next_batch(batch),
            Self::Lexicographic(q) => {
                let position = (0..q.len())
                    .min_by_key(|&index| {
                        let (i, j) = q[index];
                        let lcm = monomial_lcm(&leading[i].exponents, &leading[j].exponents);
                        (lcm.iter().sum::<u32>(), lcm)
                    })
                    .expect("critical pair queue is nonempty");
                vec![q.swap_remove(position)]
            }
        }
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct CriticalPairQueue {
    by_lcm_degree: BTreeMap<u32, Vec<(usize, usize)>>,
    len: usize,
}

impl CriticalPairQueue {
    fn new<C>(leading_terms: &[LeadingTerm<C>]) -> Self {
        let mut queue = Self::default();
        for i in 0..leading_terms.len() {
            for j in i + 1..leading_terms.len() {
                queue.insert(i, j, leading_terms);
            }
        }
        queue
    }

    fn is_empty(&self) -> bool {
        self.len == 0
    }

    fn insert<C>(&mut self, i: usize, j: usize, leading_terms: &[LeadingTerm<C>]) {
        let pair = canonical_pair(i, j);
        let degree = pair_lcm_total_degree(pair.0, pair.1, leading_terms);
        self.by_lcm_degree.entry(degree).or_default().push(pair);
        self.len += 1;
    }

    fn take_next_batch(&mut self, batch_same_lcm_degree: bool) -> Vec<(usize, usize)> {
        assert!(self.len > 0, "critical pair queue is empty");
        if batch_same_lcm_degree {
            return self.take_smallest_degree_bucket();
        }
        vec![self.take_best_pair()]
    }

    fn take_smallest_degree_bucket(&mut self) -> Vec<(usize, usize)> {
        let degree = *self
            .by_lcm_degree
            .keys()
            .next()
            .expect("critical pair queue is empty");
        let mut bucket = self
            .by_lcm_degree
            .remove(&degree)
            .expect("degree bucket disappeared");
        self.len -= bucket.len();
        bucket.sort_by_key(|&(i, j)| (i.max(j), i.min(j)));
        bucket
    }

    fn take_best_pair(&mut self) -> (usize, usize) {
        let degree = *self
            .by_lcm_degree
            .keys()
            .next()
            .expect("critical pair queue is empty");
        let bucket = self
            .by_lcm_degree
            .get_mut(&degree)
            .expect("degree bucket disappeared");
        let best_index = bucket
            .iter()
            .enumerate()
            .min_by_key(|entry| {
                let &(i, j) = entry.1;
                (i.max(j), i.min(j))
            })
            .map(|(index, _)| index)
            .expect("degree bucket is empty");
        let pair = bucket.swap_remove(best_index);
        if bucket.is_empty() {
            self.by_lcm_degree.remove(&degree);
        }
        self.len -= 1;
        pair
    }
}

fn chain_criterion_applies<C>(
    i: usize,
    j: usize,
    leading_terms: &[LeadingTerm<C>],
    handled_pairs: &HashSet<(usize, usize)>,
) -> bool {
    let lcm_ij = monomial_lcm(&leading_terms[i].exponents, &leading_terms[j].exponents);
    (0..leading_terms.len()).any(|k| {
        if k == i || k == j {
            return false;
        }
        if !handled_pairs.contains(&canonical_pair(i, k))
            || !handled_pairs.contains(&canonical_pair(k, j))
        {
            return false;
        }
        let lcm_ik = monomial_lcm(&leading_terms[i].exponents, &leading_terms[k].exponents);
        let lcm_kj = monomial_lcm(&leading_terms[k].exponents, &leading_terms[j].exponents);
        monomial_divides(&lcm_ik, &lcm_ij) && monomial_divides(&lcm_kj, &lcm_ij)
    })
}

/// Remove leading-monomial multiples, retaining the first equal representative.
///
/// This only minimizes leading monomials; it does not interreduce polynomial tails.
///
/// # Panics
///
/// Panics if a polynomial is zero or exponent-vector lengths differ.
pub fn minimize_leading_monomials<P: SparsePolynomial>(basis: &mut Vec<P>, order: MonomialOrder) {
    let leading_terms: Vec<_> = basis
        .iter()
        .map(|polynomial| leading_term(polynomial, order).expect("nonzero polynomial"))
        .collect();
    // Every proper divisor precedes its multiples in lexicographic order.
    // Inspect equal leading monomials in input order, retaining the first.
    // A discarded element must have a retained divisor, rather than another
    // discarded element, as its witness.
    let mut indices: Vec<_> = (0..basis.len()).collect();
    indices.sort_by(|&i, &j| {
        leading_terms[i]
            .exponents
            .cmp(&leading_terms[j].exponents)
            .then_with(|| i.cmp(&j))
    });
    let mut kept_indices = Vec::<usize>::new();
    let mut keep = vec![false; basis.len()];
    for i in indices {
        if !kept_indices
            .iter()
            .any(|&j| monomial_divides(&leading_terms[j].exponents, &leading_terms[i].exponents))
        {
            keep[i] = true;
            kept_indices.push(i);
        }
    }

    let old_basis = std::mem::take(basis);
    *basis = old_basis
        .into_iter()
        .enumerate()
        .filter_map(|(i, polynomial)| keep[i].then_some(polynomial))
        .collect();
}

