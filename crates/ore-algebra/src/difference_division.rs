//! Pseudo-division of operators with the variable shift `E`: right
//! pseudo-division by a recurrence (in the index shift `S`) and right
//! pseudo-division of shift-free operators by a difference operator (in
//! `E`).
//!
//! # Division by a recurrence
//!
//! Let `L = g(n) S^k + (terms of shift < k)` with `g` a nonzero polynomial
//! in `n` only.  Since `g(n)` commutes with `x`, `D` and `E`, the level-by-
//! level reduction of [`crate::right_pseudo_division`] carries over
//! unchanged: from `m = m_top` down to `k`, multiply the remainder and the
//! quotient on the left by `g(n + m - k)` and subtract `c S^(m-k) o L`, `c`
//! the shift-free coefficient operator of `S^m`.  The result is
//!
//! ```text
//! w(n) P = H o L + R,   w(n) = prod_(m = k..m_top) g(n + m - k),
//! ```
//!
//! with `R` of shift `< k`, linear in `P` for a fixed `m_top`.  The algebra
//! is the skew polynomial ring in `S` over the ring generated by
//! `Q(n, x)`, `D` and `E^(+-1)`, and `g(n)` is a unit there, so the
//! remainder of right division by `L` is unique: `R = 0` exactly when `P`
//! lies in the left ideal generated by `L` over `Q(n, x)`.
//!
//! # Division in `E`
//!
//! Let `A = a_r(n, x) E^r + (terms with E^e, e < r)` be free of `S` and of
//! `D`.  A shift-free `P` is reduced level by level, from `E^(m_top)` down
//! to `E^r` and, within each level `m`, from `D^(d_top)` down to `D^0`:
//! multiply the remainder and the quotient on the left by
//! `f_m = a_r(n, x + m - r)` and subtract `c D^d E^(m - r) o A`, `c` the
//! coefficient of `D^d E^m` before the multiplication.  The leading part of
//! `c D^d E^(m-r) o A` is
//! `c sum_t binom(d, t) (d/dx)^t a_r(n, x + m - r) D^(d - t) E^m`, whose
//! `t = 0` term cancels `f_m c D^d E^m` and whose other terms lie at lower
//! derivative orders of the same level.  The result is
//!
//! ```text
//! w(n, x) P = H o A + R,   w = prod_m f_m^(d_top + 1),
//! ```
//!
//! with every power of `E` in `R` below `r`; every level multiplies, so `R`
//! is linear in `P` for fixed tops.  For `P` and `A` with nonnegative powers
//! of `E` and `A` free of `E^e`, `e < 0`, this is division in the skew
//! polynomial ring in `E` over `Q(n, x)` with `D` adjoined, and the
//! remainder is unique.

use crate::bivariate::BivariatePolynomial;
use crate::differential_difference::DifferentialDifferenceOperator;
use crate::Rational;
use num_traits::Zero;

/// The identity `multiplier · dividend = quotient o divisor + remainder` of
/// [`difference_right_pseudo_division`] and
/// [`variable_shift_pseudo_division`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DifferentialDifferenceDivision {
    /// `w`, a nonzero polynomial (in `n` only for division by a recurrence).
    pub multiplier: BivariatePolynomial,
    /// `H`.
    pub quotient: DifferentialDifferenceOperator,
    /// `R`.
    pub remainder: DifferentialDifferenceOperator,
}

/// The order `k` and leader `g(n)` of a divisor whose top shift column is a
/// single term `g(n) S^k` free of `x`, of derivatives and of `E`; `None`
/// otherwise.
pub fn difference_index_only_leader(
    divisor: &DifferentialDifferenceOperator,
) -> Option<(usize, BivariatePolynomial)> {
    if divisor.is_zero() {
        return None;
    }
    let order = divisor.max_shift();
    let column = divisor.column(order);
    if column.term_count() != 1 {
        return None;
    }
    let leader = column.0.get(&(0, 0, 0))?;
    leader.is_variable_free().then(|| (order, leader.clone()))
}

/// Right pseudo-division of `dividend` by a recurrence `divisor` with every
/// level from `top_shift` (at least the dividend's largest shift) down to
/// the divisor's order (module documentation).
///
/// Returns `None` when the divisor's top shift column is not a single term
/// `g(n) S^k` free of `x`, of derivatives and of `E`, or when `top_shift`
/// is below the dividend's largest shift.  When `top_shift` is below the
/// divisor's order nothing is reduced: the multiplier is one and the
/// remainder is the dividend.
pub fn difference_right_pseudo_division(
    dividend: &DifferentialDifferenceOperator,
    divisor: &DifferentialDifferenceOperator,
    top_shift: usize,
) -> Option<DifferentialDifferenceDivision> {
    let (order, leader) = difference_index_only_leader(divisor)?;
    if !dividend.is_zero() && dividend.max_shift() > top_shift {
        return None;
    }
    let mut remainder = dividend.clone();
    let mut quotient = DifferentialDifferenceOperator::default();
    let mut multiplier = BivariatePolynomial::one();
    if top_shift < order {
        return Some(DifferentialDifferenceDivision {
            multiplier,
            quotient,
            remainder,
        });
    }
    for level in (order..=top_shift).rev() {
        let offset = level - order;
        let factor = leader.shift_index(offset as i64);
        let column = remainder.column(level);
        remainder = remainder.left_multiply(&factor);
        quotient = quotient.left_multiply(&factor);
        multiplier = multiplier.multiply(&factor);
        if column.is_zero() {
            continue;
        }
        let mut step = DifferentialDifferenceOperator::default();
        for ((_, d, e), c) in &column.0 {
            step.add_term((offset, *d, *e), c.clone());
        }
        remainder = remainder.subtract(&step.compose(divisor));
        quotient = quotient.add(&step);
    }
    Some(DifferentialDifferenceDivision {
        multiplier,
        quotient,
        remainder,
    })
}

/// Right pseudo-division of a shift-free `dividend` by a `divisor` free of
/// `S` and of `D`, in decreasing powers of `E` from `top_variable_shift`
/// down to the divisor's largest power `r`, and within each power in
/// decreasing derivative order from `top_derivative` (module
/// documentation).
///
/// Returns `None` when the divisor is zero or involves `S` or `D`, when the
/// dividend has a shift, or when it has a power of `E` above
/// `top_variable_shift` or a derivative order above `top_derivative`.  When
/// `top_variable_shift < r` nothing is reduced.
pub fn variable_shift_pseudo_division(
    dividend: &DifferentialDifferenceOperator,
    divisor: &DifferentialDifferenceOperator,
    top_variable_shift: i64,
    top_derivative: usize,
) -> Option<DifferentialDifferenceDivision> {
    if divisor.is_zero() || divisor.max_shift() != 0 || !divisor.is_derivative_free() {
        return None;
    }
    if !dividend.is_zero()
        && (dividend.max_shift() != 0
            || dividend.max_variable_shift() > top_variable_shift
            || dividend.max_derivative() > top_derivative)
    {
        return None;
    }
    let r = divisor.max_variable_shift();
    let lead = divisor.0.get(&(0, 0, r)).cloned().unwrap_or_default();
    let mut remainder = dividend.clone();
    let mut quotient = DifferentialDifferenceOperator::default();
    let mut multiplier = BivariatePolynomial::one();
    if top_variable_shift < r {
        return Some(DifferentialDifferenceDivision {
            multiplier,
            quotient,
            remainder,
        });
    }
    for level in (r..=top_variable_shift).rev() {
        let offset = level - r;
        let factor = lead.shift(&Rational::zero(), &Rational::from_integer(offset.into()));
        for d in (0..=top_derivative).rev() {
            let top = remainder.0.get(&(0, d, level)).cloned();
            remainder = remainder.left_multiply(&factor);
            quotient = quotient.left_multiply(&factor);
            multiplier = multiplier.multiply(&factor);
            let Some(top) = top else {
                continue;
            };
            let step = DifferentialDifferenceOperator::single(0, d, offset, top);
            remainder = remainder.subtract(&step.compose(divisor));
            quotient = quotient.add(&step);
        }
    }
    Some(DifferentialDifferenceDivision {
        multiplier,
        quotient,
        remainder,
    })
}
