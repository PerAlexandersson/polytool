//! Right pseudo-division by an operator whose leader is free of `x` and of
//! derivatives.
//!
//! Let `L = g(n) S^k + (terms of shift < k)` with `g` a nonzero polynomial in
//! `n` only.  A dividend `E` of shift at most `m_top` is reduced level by
//! level, from `m = m_top` down to `m = k`: take the shift-free coefficient
//! operator `c` of `S^m` in the current remainder, multiply the remainder
//! and the quotient on the left by `g(n + m - k)` and subtract
//! `c S^(m-k) o L`.  The shift-`m` terms cancel because
//! `S^(m-k) o g(n) = g(n + m - k) S^(m-k)` and `g(n + m - k)` commutes with
//! `c` (it involves neither `x` nor `S`, so it commutes with `D` and with the
//! coefficients of `c`).  The result is the identity
//!
//! ```text
//! w(n) E = H o L + R,   w(n) = prod_(m = k..m_top) g(n + m - k),
//! ```
//!
//! with a remainder `R` of shift `< k`.  Every level multiplies by its
//! factor, even when its column is empty, so for a fixed `m_top` the
//! multiplier does not depend on `E` and the remainder is linear in `E` over
//! the rationals (and over polynomials in `n`).
//!
//! Over the field `Q(n, x)` the remainder of right division by `L` is
//! unique, so `R = 0` exactly when `E` lies in the left ideal generated by
//! `L` over `Q(n, x)`.

use crate::bivariate::BivariatePolynomial;
use crate::operator::OreOperator;

/// The identity `multiplier · dividend = quotient o divisor + remainder` of
/// [`right_pseudo_division`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RightPseudoDivision {
    /// `w(n)`, a nonzero polynomial in `n` only (the product of the shifted
    /// leaders `g(n + m - k)`).
    pub multiplier: BivariatePolynomial,
    /// `H`, with shifts up to `m_top - k`.
    pub quotient: OreOperator,
    /// `R`, of shift below the divisor's order `k`.
    pub remainder: OreOperator,
}

/// The order `k` and leader `g(n)` of a divisor whose top shift column is a
/// single term `g(n) S^k` free of `x` and of derivatives; `None` otherwise.
pub fn index_only_leader(divisor: &OreOperator) -> Option<(usize, BivariatePolynomial)> {
    let order = divisor.max_shift();
    let column = divisor.column(order);
    if column.term_count() != 1 {
        return None;
    }
    let leader = column.0.get(&(0, 0))?;
    leader.is_variable_free().then(|| (order, leader.clone()))
}

/// Right pseudo-division of `dividend` by `divisor` with every level from
/// `top_shift` (at least the dividend's largest shift) down to the
/// divisor's order (module documentation).
///
/// Returns `None` when the divisor's top shift column is not a single term
/// `g(n) S^k` free of `x` and of derivatives, or when `top_shift` is below
/// the dividend's largest shift.  When `top_shift` is below the divisor's
/// order nothing is reduced: the multiplier is one and the remainder is the
/// dividend.
pub fn right_pseudo_division(
    dividend: &OreOperator,
    divisor: &OreOperator,
    top_shift: usize,
) -> Option<RightPseudoDivision> {
    let (order, leader) = index_only_leader(divisor)?;
    if !dividend.is_zero() && dividend.max_shift() > top_shift {
        return None;
    }
    let mut remainder = dividend.clone();
    let mut quotient = OreOperator::default();
    let mut multiplier = BivariatePolynomial::one();
    if top_shift < order {
        return Some(RightPseudoDivision {
            multiplier,
            quotient,
            remainder,
        });
    }
    for level in (order..=top_shift).rev() {
        let offset = level - order;
        let factor = leader.shift_index(offset as i64);
        let column = remainder.column(level);
        remainder = remainder.left_multiply(&factor);
        quotient = quotient.left_multiply(&factor);
        multiplier = multiplier.multiply(&factor);
        if column.is_zero() {
            continue;
        }
        // c S^offset as an operator.
        let mut step = OreOperator::default();
        for ((_, d), c) in &column.0 {
            step.add_term((offset, *d), c.clone());
        }
        remainder = remainder.subtract(&step.compose(divisor));
        quotient = quotient.add(&step);
    }
    Some(RightPseudoDivision {
        multiplier,
        quotient,
        remainder,
    })
}
