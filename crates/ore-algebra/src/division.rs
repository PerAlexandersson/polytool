//! Right pseudo-division by an operator whose leader is free of `x` and of
//! derivatives.
//!
//! Let `L = g(n) S^k + (terms of shift < k)` with `g` a nonzero polynomial in
//! `n` only.  A dividend `E` of shift at most `m_top` is reduced level by
//! level, from `m = m_top` down to `m = k`: take the shift-free coefficient
//! operator `c` of `S^m` in the current remainder, multiply the remainder
//! and the quotient on the left by `g(n + m - k)` and subtract
//! `c S^(m-k) o L`.  The shift-`m` terms cancel because
//! `S^(m-k) o g(n) = g(n + m - k) S^(m-k)` and `g(n + m - k)` commutes with
//! `c` (it involves neither `x` nor `S`, so it commutes with `D` and with the
//! coefficients of `c`).  The result is the identity
//!
//! ```text
//! w(n) E = H o L + R,   w(n) = prod_(m = k..m_top) g(n + m - k),
//! ```
//!
//! with a remainder `R` of shift `< k`.  Every level multiplies by its
//! factor, even when its column is empty, so for a fixed `m_top` the
//! multiplier does not depend on `E` and the remainder is linear in `E` over
//! the rationals (and over polynomials in `n`).
//!
//! Over the field `Q(n, x)` the remainder of right division by `L` is
//! unique, so `R = 0` exactly when `E` lies in the left ideal generated by
//! `L` over `Q(n, x)`.
//!
//! # Rows and systems
//!
//! The same reduction divides a row `rho = (rho_0, ..., rho_(r-1))` of
//! operators by a square system `Phi` (rows `Phi_b`, so `Phi V = 0` for a
//! vector sequence `V` says `sum_a Phi_(b,a) V_a = 0` for every `b`) whose
//! shift-`k` part is `g(n) S^k I` and which has no larger shift
//! ([`right_pseudo_division_of_row`]).  At level `m` the shift-free
//! coefficients `c_a` of `S^m` in `rho_a` are taken, the remainder and the
//! quotients are multiplied on the left by `g(n + m - k)`, and
//! `sum_b c_b S^(m-k) o Phi_b` is subtracted; its shift-`m` part is
//! `c_a g(n + m - k) S^m` in entry `a`.  The result is
//!
//! ```text
//! w(n) rho = sum_b H_b o Phi_b + R,
//! ```
//!
//! with `R` of shift `< k` in every entry, so `(rho V)_n = (R V)_n` at every
//! base where `Phi V = 0` holds and `w(n) != 0`.  A `1 x 1` system is the
//! scalar division above.

use crate::bivariate::BivariatePolynomial;
use crate::operator::OreOperator;

/// The identity `multiplier · dividend = quotient o divisor + remainder` of
/// [`right_pseudo_division`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RightPseudoDivision {
    /// `w(n)`, a nonzero polynomial in `n` only (the product of the shifted
    /// leaders `g(n + m - k)`).
    pub multiplier: BivariatePolynomial,
    /// `H`, with shifts up to `m_top - k`.
    pub quotient: OreOperator,
    /// `R`, of shift below the divisor's order `k`.
    pub remainder: OreOperator,
}

/// The order `k` and leader `g(n)` of a divisor whose top shift column is a
/// single term `g(n) S^k` free of `x` and of derivatives; `None` otherwise.
pub fn index_only_leader(divisor: &OreOperator) -> Option<(usize, BivariatePolynomial)> {
    let order = divisor.max_shift();
    let column = divisor.column(order);
    if column.term_count() != 1 {
        return None;
    }
    let leader = column.0.get(&(0, 0))?;
    leader.is_variable_free().then(|| (order, leader.clone()))
}

/// Right pseudo-division of `dividend` by `divisor` with every level from
/// `top_shift` (at least the dividend's largest shift) down to the
/// divisor's order (module documentation).
///
/// Returns `None` when the divisor's top shift column is not a single term
/// `g(n) S^k` free of `x` and of derivatives, or when `top_shift` is below
/// the dividend's largest shift.  When `top_shift` is below the divisor's
/// order nothing is reduced: the multiplier is one and the remainder is the
/// dividend.
pub fn right_pseudo_division(
    dividend: &OreOperator,
    divisor: &OreOperator,
    top_shift: usize,
) -> Option<RightPseudoDivision> {
    let (order, leader) = index_only_leader(divisor)?;
    if !dividend.is_zero() && dividend.max_shift() > top_shift {
        return None;
    }
    let mut remainder = dividend.clone();
    let mut quotient = OreOperator::default();
    let mut multiplier = BivariatePolynomial::one();
    if top_shift < order {
        return Some(RightPseudoDivision {
            multiplier,
            quotient,
            remainder,
        });
    }
    for level in (order..=top_shift).rev() {
        let offset = level - order;
        let factor = leader.shift_index(offset as i64);
        let column = remainder.column(level);
        remainder = remainder.left_multiply(&factor);
        quotient = quotient.left_multiply(&factor);
        multiplier = multiplier.multiply(&factor);
        if column.is_zero() {
            continue;
        }
        // c S^offset as an operator.
        let mut step = OreOperator::default();
        for ((_, d), c) in &column.0 {
            step.add_term((offset, *d), c.clone());
        }
        remainder.subtract_assign(&step.compose(divisor));
        quotient.add_assign(&step);
    }
    Some(RightPseudoDivision {
        multiplier,
        quotient,
        remainder,
    })
}

/// The identity `multiplier · dividend = sum_b quotients[b] o system[b] +
/// remainder` of [`right_pseudo_division_of_row`] (rows of operators).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RowPseudoDivision {
    /// `w(n)`, a nonzero polynomial in `n` only.
    pub multiplier: BivariatePolynomial,
    /// `H_b`, one per row of the system, with shifts up to `m_top - k`.
    pub quotients: Vec<OreOperator>,
    /// `R`, every entry of shift below `k`.
    pub remainder: Vec<OreOperator>,
}

/// The order `k` and leader `g(n)` of a square system whose shift-`k` part
/// is `g(n) S^k I` (each diagonal entry has the single top term `g(n) S^k`
/// free of `x` and of derivatives, no entry has a larger shift, and the
/// off-diagonal entries have smaller shifts); `None` otherwise.
pub fn system_index_only_leader(
    system: &[Vec<OreOperator>],
) -> Option<(usize, BivariatePolynomial)> {
    let size = system.len();
    if size == 0 || system.iter().any(|row| row.len() != size) {
        return None;
    }
    let (order, leader) = index_only_leader(&system[0][0])?;
    for (b, row) in system.iter().enumerate() {
        for (a, entry) in row.iter().enumerate() {
            if entry.is_zero() {
                if a == b {
                    return None;
                }
                continue;
            }
            if entry.max_shift() > order {
                return None;
            }
            let column = entry.column(order);
            let expected = if a == b {
                OreOperator::single(0, 0, leader.clone())
            } else {
                OreOperator::default()
            };
            if column != expected {
                return None;
            }
        }
    }
    Some((order, leader))
}

/// Right pseudo-division of a row of operators by a square system with
/// every level from `top_shift` (at least the dividend's largest shift)
/// down to the system's order (module documentation, "Rows and systems").
///
/// Returns `None` when the system is not square of the row's length, its
/// shift-`k` part is not `g(n) S^k I` ([`system_index_only_leader`]), or
/// `top_shift` is below the dividend's largest shift.
pub fn right_pseudo_division_of_row(
    dividend: &[OreOperator],
    system: &[Vec<OreOperator>],
    top_shift: usize,
) -> Option<RowPseudoDivision> {
    if system.len() != dividend.len() {
        return None;
    }
    let (order, leader) = system_index_only_leader(system)?;
    if dividend
        .iter()
        .any(|op| !op.is_zero() && op.max_shift() > top_shift)
    {
        return None;
    }
    let size = dividend.len();
    let mut remainder = dividend.to_vec();
    let mut quotients = vec![OreOperator::default(); size];
    let mut multiplier = BivariatePolynomial::one();
    if top_shift < order {
        return Some(RowPseudoDivision {
            multiplier,
            quotients,
            remainder,
        });
    }
    for level in (order..=top_shift).rev() {
        let offset = level - order;
        let factor = leader.shift_index(offset as i64);
        let columns: Vec<OreOperator> = remainder.iter().map(|op| op.column(level)).collect();
        remainder = remainder
            .iter()
            .map(|op| op.left_multiply(&factor))
            .collect();
        quotients = quotients
            .iter()
            .map(|op| op.left_multiply(&factor))
            .collect();
        multiplier = multiplier.multiply(&factor);
        for (b, column) in columns.iter().enumerate() {
            if column.is_zero() {
                continue;
            }
            // c_b S^offset as an operator.
            let mut step = OreOperator::default();
            for ((_, d), c) in &column.0 {
                step.add_term((offset, *d), c.clone());
            }
            for (entry, divisor) in remainder.iter_mut().zip(&system[b]) {
                if !divisor.is_zero() {
                    entry.subtract_assign(&step.compose(divisor));
                }
            }
            quotients[b].add_assign(&step);
        }
    }
    Some(RowPseudoDivision {
        multiplier,
        quotients,
        remainder,
    })
}

/// `sum_b quotients[b] o system[b]`, entry by entry.
pub(crate) fn combine_rows(
    quotients: &[OreOperator],
    system: &[Vec<OreOperator>],
) -> Vec<OreOperator> {
    let size = system.first().map_or(0, Vec::len);
    let mut out = vec![OreOperator::default(); size];
    for (quotient, row) in quotients.iter().zip(system) {
        if quotient.is_zero() {
            continue;
        }
        for (entry, divisor) in out.iter_mut().zip(row) {
            if !divisor.is_zero() {
                entry.add_assign(&quotient.compose(divisor));
            }
        }
    }
    out
}
